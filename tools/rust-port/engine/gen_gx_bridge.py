#!/usr/bin/env python3
"""Generate rust/melee_engine/src/gxbridge_gen.rs: assign melee_engine::gxbridge::GX* to every TU's `ext::hook::GX*`.

The hooks are listed in seams_gen.rs (one per TU and name); the bridge functions and their parameter types are parsed
from gxbridge.rs, so adding a bridge function is enough (rerun this script)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[3] / 'rust' / 'melee_engine' / 'src'
bridge = (root / 'gxbridge.rs').read_text()
fns = {}
for m in re.finditer(r'^pub (?:unsafe )?fn (GX\w+)\(([^)]*)\)(?:\s*->\s*([\w\*]+))?', bridge, re.M):
    params = []
    for p in [x.strip() for x in m.group(2).split(',') if x.strip()]:
        name, ty = [s.strip() for s in p.split(':', 1)]
        params.append(ty)
    fns[m.group(1)] = (params, m.group(3))
seams = (root / 'seams_gen.rs').read_text()
hooks = sorted(set(re.findall(r'(melee_\w+::tu::[\w:]+::ext::hook)::(GX\w+)', seams)))
PRIM = {'u8', 'u16', 'u32', 'i32', 'i8', 'f32', 'usize', 'u64'}
out = ['// @generated by tools/rust-port/engine/gen_gx_bridge.py. Do not edit.',
       '#![allow(non_snake_case, unused_unsafe, clippy::all)]', 'use core::ffi::c_void;', '',
       '/// Point every TU\'s GX hook at the bridge (the render pass then feeds melee_gx). Call before `install_gen`.',
       'pub fn install_gx() {']
n = 0
for path, name in hooks:
    if name not in fns:
        continue
    params, ret = fns[name]
    args = []
    for i, t in enumerate(params):
        a = f'a{i}'
        args.append(f'{a} as {t}' if (t in PRIM or t.startswith('*')) else a)
    ps = ', '.join(f'a{i}' for i in range(len(params)))
    call = f'crate::gxbridge::{name}({", ".join(args)})'
    if ret:
        call += ' as _'
    out.append(f'    unsafe {{ {path}::{name} = Some(|{ps}| unsafe {{ {call} }}); }}')
    n += 1
out.append('}')
(root / 'gxbridge_gen.rs').write_text('\n'.join(out) + '\n')
print(f'{n} hooks bridged; unbridged: ' + ', '.join(sorted({h[1] for h in hooks} - set(fns))))
