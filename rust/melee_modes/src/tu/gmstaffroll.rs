//! src/melee/gm/gmstaffroll.c: the credits ("Staff Roll") scene: the 198-entry credit table with its
//! unlock predicates, the scene setup (`gm_Scene_StaffRoll_OnEnter`), the GObj procs and render
//! callbacks, the entry sort/text-window builder (`fn_801AAB74`) and the cursor/selection/animation
//! driver (`fn_801AB200`).
//!
//! Fused float sites (tools/rust-port/fma_sites.py): `fn_801AB200` has four, all `fmadds`
//! (`vel*vel + 6400.0f` twice, `0.19f * text_idx + 0.67f`, `0.5f * g + 1.7f`), plus MSL `sqrtf`'s three
//! f64 fmas (`melee_runtime::gekko::sqrtf`). `tanf` is MSL's (`gekko::tanf`).
//!
//! Native-layout notes:
//! - `staffInfo` / `staffInfoSortBuf` / `StaffRollPtclNode` are this file's own views over memory
//!   other code owns; they keep the C field order with native (8-byte) pointers, so the
//!   `HSD_MemAlloc` sizes are the native element sizes times 198 (the C asks for the GameCube sizes
//!   0x948 / 0x2E68).
//! - The C reads a `GXColor` through `*(s32*)` and builds one from `gm_804DAAEC`'s bytes: on the
//!   console (big endian) that is the word `r<<24 | g<<16 | b<<8 | a`. The port keeps that value
//!   semantic ([`color_word`], [`COLOR_HIT`]) rather than the little-endian byte image.
//!
//! Checked against the C by the state oracle `tests/s497_gmstaffroll.rs` (rust/melee_modes/oracle/s497).
