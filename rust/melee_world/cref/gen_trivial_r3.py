"""Night-3 round-3 generator: the constant-return / empty stage callbacks of the per-stage
gr TUs (every gr/*.c except stage.c, ground.c, grlib.c, whose bodies are exactly one of
`return false;` `return true;` `return 0;` `return 1;` `return NULL;` `return;` or nothing).

Writes:
  rust/melee_world/src/gr/trivial.rs          the Rust ports (one module per TU)
  <out>/trivial_r3_body.inc                   the C bodies, verbatim, renamed TU__name
  <out>/trivial_r3_driver.c                   the oracle driver (prints `tu name pass ret`)
Usage: python gen_trivial_r3.py <repo root> <out dir>   (gen_trivial_r3_ref.sh runs it)
"""
import glob, os, re, sys

root, out = sys.argv[1], sys.argv[2]
KEEP = {'return false;': '0', 'return 0;': '0', 'return true;': '1', 'return 1;': '1',
        'return NULL;': 'null', 'return;': None, '': None}
SKIP = {'stage.c', 'ground.c', 'grlib.c'}
PTR = {'Ground_GObj*': 'HSD_GObj', 'HSD_GObj*': 'HSD_GObj', 'Item_GObj*': 'HSD_GObj',
       'HSD_JObj*': 'HSD_JObj', 'Vec3*': 'Vec3', 'Ground*': 'Ground'}
INT = {'int', 'enum_t', 'bool'}


def ptype(p):
    p = p.strip().replace('struct ', '')
    m = re.match(r'^(.*?)(\w+)$', p)
    if p in INT or p in PTR or not m or not m.group(1).strip():
        return p.replace(' ', '')
    return m.group(1).replace(' ', '')


fns = []
for fn in sorted(glob.glob(os.path.join(root, 'src/melee/gr/*.c'))):
    base = os.path.basename(fn)
    if base in SKIP:
        continue
    tu = base[:-2]
    L = open(fn, encoding='utf8', errors='ignore').read().split('\n')
    i = 0
    while i < len(L):
        l = L[i]
        if re.match(r'^[A-Za-z].*\(.*\)\s*$', l) and ';' not in l and i + 1 < len(L) and L[i + 1].startswith('{'):
            j = i + 2
            body = []
            while j < len(L) and not L[j].startswith('}'):
                body.append(L[j])
                j += 1
            b = re.sub(r'\s+', ' ', '\n'.join(body)).strip()
            if b in KEEP:
                m = re.match(r'^(?:static\s+)?(?:inline\s+)?(.*?)\b(\w+)\s*\((.*)\)\s*$', l)
                ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
                ret = ret.replace('struct ', '').replace(' ', '')
                ps = [] if params == 'void' else [ptype(p) for p in params.split(',')]
                ok = all(t in PTR or t in INT for t in ps) and ret in ('bool', 'void', 'DynamicsDesc*')
                if not ok:
                    sys.exit(f'unmapped {base}:{name}: {ret} {ps}')
                fns.append(dict(tu=tu, name=name, ret=ret, ps=ps, val=KEEP[b], line=i + 1,
                                sig=l, body='\n'.join(body)))
            i = j
        i += 1

with open(os.path.join(out, 'trivial_r3_body.inc'), 'w', newline='\n') as f:
    for d in fns:
        sig = re.sub(r'^static\s+(inline\s+)?', '', d['sig'])
        sig = re.sub(r'\b%s\s*\(' % d['name'], '%s__%s(' % (d['tu'], d['name']), sig, count=1)
        f.write(f"{sig}\n{{\n{d['body']}\n}}\n")
with open(os.path.join(out, 'trivial_r3_driver.c'), 'w', newline='\n') as f:
    f.write('#include <stdio.h>\n#include <stdint.h>\n')
    for d in fns:
        r = {'bool': 'int', 'void': 'void', 'DynamicsDesc*': 'void*'}[d['ret']]
        a = ', '.join('void*' if t in PTR else 'int' for t in d['ps']) or 'void'
        f.write(f"{r} {d['tu']}__{d['name']}({a});\n")
    f.write('int main(void)\n{\n    void* J = (void*) (uintptr_t) 0x1234560;\n')
    for k in (0, 1):
        for d in fns:
            a = ', '.join(('(%d ? J : 0)' % k) if t in PTR else ('(%d ? -7 : 0)' % k) for t in d['ps'])
            call = f"{d['tu']}__{d['name']}({a})"
            tag = f"{d['tu']} {d['name']} {k}"
            if d['ret'] == 'void':
                f.write(f'    {call}; printf("{tag} -\\n");\n')
            elif d['ret'] == 'bool':
                f.write(f'    printf("{tag} %x\\n", (unsigned) {call});\n')
            else:
                f.write(f'    printf("{tag} %llx\\n", (unsigned long long) (uintptr_t) {call});\n')
    f.write('    return 0;\n}\n')

RT = {'bool': ' -> i32', 'void': '', 'DynamicsDesc*': ' -> *mut DynamicsDesc'}
RV = {'0': '0', '1': '1', 'null': 'core::ptr::null_mut()', None: ''}
o = ['//! Night 3 round 3: the constant-return and empty callbacks of the per-stage gr TUs',
     '//! (generated by `cref/gen_trivial_r3.py`; do not edit by hand). Each is the C body',
     '//! verbatim: `return false;` / `return true;` / `return 0;` / `return 1;` / `return NULL;` /',
     "//! empty. `bool` is the game's `int` bool, so the predicates match `HSD_GObjPredicate` and",
     '//! can be stored in `StageCallbacks` as they are. One module per TU (several TUs define a',
     '//! static `stageGObjN_Callback1`). Checked against the C by `tests/trivial_r3_vs_c.rs`.',
     '#![allow(non_snake_case, unused_variables, clippy::all)]', '',
     'use melee_types::{DynamicsDesc, Ground, HSD_GObj, HSD_JObj, Vec3};', '']
calls = []
cur = None
for d in fns:
    if d['tu'] != cur:
        if cur is not None:
            o.append('}\n')
        cur = d['tu']
        o.append(f'/// src/melee/gr/{cur}.c\npub mod {cur} {{\n    use super::*;')
    args = ', '.join(f'a{k}: ' + (f'*mut {PTR[t]}' if t in PTR else 'i32') for k, t in enumerate(d['ps']))
    o.append(f"    /// {d['name']} (gr/{d['tu']}.c:{d['line']})")
    v = RV[d['val']]
    if d['ret'] == 'DynamicsDesc*' and d['val'] == '0':
        v = 'core::ptr::null_mut()'  # `return 0;` from a pointer function
    o.append(f"    pub extern \"C\" fn {d['name']}({args}){RT[d['ret']]} {{ {v} }}")
    ca = ', '.join((f'if junk {{ J as *mut {PTR[t]} }} else {{ core::ptr::null_mut() }}') if t in PTR
                   else 'if junk { -7 } else { 0 }' for t in d['ps'])
    c = f"{d['tu']}::{d['name']}({ca})"
    if d['ret'] == 'void':
        calls.append(f'        ("{d["tu"]}", "{d["name"]}") => {{ {c}; None }}')
    elif d['ret'] == 'bool':
        calls.append(f'        ("{d["tu"]}", "{d["name"]}") => Some({c} as u32 as u64),')
    else:
        calls.append(f'        ("{d["tu"]}", "{d["name"]}") => Some({c} as usize as u64),')
o.append('}\n')
o.append(f'/// Number of functions in this module.\npub const COUNT: usize = {len(fns)};\n')
o.append('/// Test entry: call `tu::name` with all-zero arguments (`junk == false`) or with a junk')
o.append('/// pointer / -7 (`junk == true`). `Some(Some(ret))`, `Some(None)` for void, `None` if unknown.')
o.append('#[doc(hidden)]\npub fn call_by_name(tu: &str, name: &str, junk: bool) -> Option<Option<u64>> {')
o.append('    const J: usize = 0x1234560;\n    Some(match (tu, name) {')
o += calls
o.append('        _ => return None,\n    })\n}')
open(os.path.join(root, 'rust/melee_world/src/gr/trivial.rs'), 'w', newline='\n').write('\n'.join(o) + '\n')
print(len(fns))
