/// `HSD_JObjMtxIsDirty` (baselib/jobj.h, static inline).
unsafe fn HSD_JObjMtxIsDirty(jobj: *mut HSD_JObj) -> bool {
    hsd_assert(564, !jobj.is_null(), c"jobj");
    let mut result = false;
    if ((*jobj).flags & JOBJ_USER_DEF_MTX as u32) == 0 && ((*jobj).flags & JOBJ_MTX_DIRTY as u32) != 0 {
        result = true;
    }
    result
}

/// `HSD_JObjSetTranslateY` (static inline; its `HSD_JObjSetMtxDirty` is the macro form).
unsafe fn HSD_JObjSetTranslateY(jobj: *mut HSD_JObj, y: f32) {
    hsd_assert(947, !jobj.is_null(), c"jobj");
    (*jobj).translate.y = y;
    if ((*jobj).flags & JOBJ_MTX_INDEP_SRT as u32) == 0 && !jobj.is_null() && !HSD_JObjMtxIsDirty(jobj) {
        ext::HSD_JObjSetMtxDirtySub(jobj);
    }
}

