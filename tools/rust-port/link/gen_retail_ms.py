#!/usr/bin/env python3
"""Generate rust/melee_link/src/retail_ms.rs (MotionState tables) and, through gen_retail, retail.rs.

The MotionState tables are the data of ftmotionstates.c and of every ft*/kinds/*.c: rows of {anim_id, flags, move id,
five callbacks}.  They are read from the transpiled initialisers under rust/*/src/raw (data only: no raw function is
ever called) and the callbacks are resolved to the canonical tu/ functions exactly as gen_retail does.  The tables are
static arrays in melee_link; `install_ms()` fills them once at boot.  Run: gen_retail_ms.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import gen_link as g
import gen_retail as r

MS_OUT = os.path.join(g.RUST, 'melee_link', 'src', 'retail_ms.rs')
KW = {'as', 'unsafe', 'i32', 'u32', 'u8', 'u16', 'i8', 'i16', 'u64', 'i64', 'usize', 'isize', 'f32', 'f64', 'bool', 'crate',
      'core', 'ffi', 'c_int', 'c_uint', 'enum_t', 'u32_0', 'u8_0', 'u16_0', 's32', 'MotionFlags', 'static', 'mut', 'const'}
TABLE_RE = re.compile(r'(?m)^pub static mut (\w+): \[MotionState; (\d+)\]\s*=\s*unsafe \{')


def types_consts():
    t = open(os.path.join(g.RUST, 'melee_types', 'src', 'gen.rs'), encoding='utf8').read()
    return set(re.findall(r'(?m)^pub const (\w+)\s*:', t))


def ms_files():
    out = []
    for crate in ('melee_fighter', 'melee_chara'):
        base = os.path.join(g.RUST, crate, 'src', 'raw')
        for dp, dn, fn in os.walk(base):
            for f in sorted(fn):
                if f.endswith('.rs'):
                    p = os.path.join(dp, f)
                    s = open(p, encoding='utf8', errors='replace').read()
                    if TABLE_RE.search(s):
                        out.append((crate, p, s))
    return sorted(out, key=lambda x: x[1])


def run_ms(gen):
    tconsts = types_consts()
    text = ['// @generated by tools/rust-port/link/gen_retail_ms.py. Do not edit.',
            '#![allow(non_snake_case, non_upper_case_globals, unused_unsafe, unused_variables, unused_imports, clippy::all)]',
            'use crate::cast;', 'use melee_types::*;', '']
    inst = ['/// Fill the callbacks of every MotionState table (the C static initialisers). Call once at boot.',
            'pub fn install_ms() {', '    unsafe {']
    ntab = 0
    nrow = 0
    seen = set()
    for crate, path, src in ms_files():
        bl = g.blank(src)
        mod = re.sub(r'\W', '_', os.path.splitext(os.path.basename(path))[0]).lower()
        consts, local = [], set()
        for cm in re.finditer(r'(?m)^(?:pub\s+)?static mut (\w+): MotionFlags = unsafe \{', bl):
            e = g.match_close(bl, cm.end() - 1)
            consts.append((cm.group(1), src[cm.end():e].strip()))
            local.add(cm.group(1))

        def resolve(expr, where, q=True):
            def sub(m):
                n = m.group(0)
                if n in KW:
                    return n
                if m.start() > 0 and m.string[m.start() - 1] in ':.':
                    return n
                if n in local:
                    return f'{mod}::{n}' if q else n
                if n in tconsts:
                    return f'melee_types::{n}'
                gen.unres.append(f'const {n} ({where})')
                return '0'
            e = re.sub(r'::core::ffi::c_int', 'i32', expr)
            e = re.sub(r'\bu32_0\b', 'u32', e)
            return re.sub(r'\b[A-Za-z_]\w*\b', sub, e)

        tables = [(m.group(1), int(m.group(2)), m.end()) for m in TABLE_RE.finditer(bl) if m.group(1) not in seen]
        if not tables:
            continue
        lines = [f'pub mod {mod} {{', '    #![allow(unused_imports)]', '    use super::*;']
        for n, ex in consts:
            lines.append(f'    pub const {n}: u32 = ({resolve(ex, mod, False)}) as u32;')
        ilines = []
        for name, cnt, pos in tables:
            seen.add(name)
            s = bl.find('[', pos)
            e2 = g.match_close(bl, s, '[', ']')
            rows = g.split_top(src[s + 1:e2], ',')
            lines.append(f'    pub static mut {name}: [MotionState; {cnt}] = unsafe {{ core::mem::zeroed() }};')
            ntab += 1
            ilines.append(f'        let t = &raw mut {mod}::{name};')
            for i, row in enumerate(rows):
                row = row.strip()
                if not row:
                    continue
                rm = re.fullmatch(r'MotionState\s*\{(.*)\}', row, re.S)
                if not rm:
                    gen.unres.append(f'{name}[{i}]: not a MotionState literal')
                    continue
                flds = {}
                for fld in g.split_top(rm.group(1), ','):
                    fm = re.fullmatch(r'\s*(\w+)\s*:\s*(.+?)\s*', fld, re.S)
                    if fm:
                        flds[fm.group(1)] = fm.group(2)
                where = f'{name}[{i}]'
                if 'anim_id' in flds:
                    ilines.append(f'        (*t)[{i}].anim_id = ({resolve(flds["anim_id"], where)}) as _;')
                if 'x4_flags' in flds:
                    ilines.append(f'        (*t)[{i}].x4_flags = ({resolve(flds["x4_flags"], where)}) as _;')
                um = re.search(r'_\s*:\s*(.+?)\s*,?\s*\}\s*$', flds.get('c2rust_unnamed', ''), re.S)
                if um:
                    ilines.append(f'        (*t)[{i}].anon_8._x0 = ({resolve(um.group(1), where)}) as u32;')
                for cb in ('anim_cb', 'input_cb', 'phys_cb', 'coll_cb', 'cam_cb'):
                    if cb not in flds:
                        continue
                    ex = gen.expr(flds[cb], f'{where}.{cb}')
                    if ex is None or ex.startswith('STRUCT:'):
                        continue
                    ilines.append(f'        (*t)[{i}].{cb} = {ex};')
                nrow += 1
        lines.append('}')
        lines.append('')
        text += lines
        inst += ilines
    inst += ['    }', '}', '']
    open(MS_OUT, 'w', newline='\n').write('\n'.join(text + inst))
    print(f'motion states: {ntab} tables, {nrow} rows')
    return seen


if __name__ == '__main__':
    gen = r.Gen()
    for _, path, s in ms_files():
        mod = re.sub(r'\W', '_', os.path.splitext(os.path.basename(path))[0]).lower()
        for m in TABLE_RE.finditer(s):
            gen.statics.setdefault(m.group(1), ['crate::retail_ms::' + mod + '::' + m.group(1)])
    gen.run()
    run_ms(gen)
    open(r.UNRES, 'w', newline='\n').write('\n'.join(sorted(set(gen.unres))) + '\n')
    print(len(set(gen.unres)), 'unresolved in total')
