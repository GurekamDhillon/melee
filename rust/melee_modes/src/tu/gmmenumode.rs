pub unsafe extern "C" fn onEnterDebug(arg0: *mut GameModeState) {
    let data = ext::gm_GetGameModeStateEnterData(arg0) as *mut DebugSoundTestData;
    (*data).x0 = &raw mut ext::un_803F9FA4 as *mut c_void;
    (*data).x4 = 0;
    ext::un_802FF7DC();
    ext::un_802FF884(c"/audio".as_ptr() as *mut i8);
}

/// Open the page `kind` with item `sel` selected.
#[inline(always)]
unsafe fn open(data: *mut MenuEnterData, kind: MenuKind, sel: u32) {
    (*data).menu_kind = kind as u8;
    (*data).hovered_selection = sel as u8;
}

pub unsafe extern "C" fn onEnter(scene: *mut GameModeState) {
    let data = (*scene).info.enter_data as *mut MenuEnterData;
    ext::lbCardNew_AllocWorkArea();
    ext::lbCardGame_LoadArchive(0);
    let a = ext::HSD_MemAlloc(ext::lbSnap_8001E204());
    let b = ext::HSD_MemAlloc(ext::lbSnap_8001E210());
    ext::lbSnap_8001E218(a, b);
    for i in 0..ext::mnSnap_804A0B90.len() {
        ext::mnSnap_804A0B90[i] =
            ext::HSD_MemAlloc(core::mem::size_of::<mnSnap_804A0B90_t>() as i32) as *mut mnSnap_804A0B90_t;
    }
    ext::lbDvd_80018C6C();
    ext::lbDvd_8001823C();
    ext::lbDvd_80018254();
    ext::mnGallery_80258940();
    // TARGET_PC: the frontend's menus asked for one of this tree's native screens (Rules, the
    // Event list, Options' screens...): open the menu at that item.
    {
        let mut kind: u8 = 0;
        let mut sel: u8 = 0;
        if ext::gmFrontend_NativeRequest(&mut kind, &mut sel) != 0 {
            (*data).menu_kind = kind;
            (*data).hovered_selection = sel;
            (*data).load_assets = 1;
            return;
        }
    }
    let rules = ext::gmMainLib_GetGameRules();
    if (*rules).force_main_menu != 0 {
        (*rules).force_main_menu = 0;
        open(data, MENU_KIND_MAIN, SEL_MAIN_1P as u32);
        (*data).load_assets = 1;
        return;
    }
    (*data).load_assets = 1;
    let mut previous_mode: GameModeKind = ext::gm_GetPreviousGameMode() as GameModeKind;
    if previous_mode == GM_CHALLENGER_APPROACH {
        previous_mode = ext::gm_801737D8() as GameModeKind;
    }
    let (kind, sel) = match previous_mode {
        GM_CLASSIC => (MENU_KIND_REG, SEL_REG_CLASSIC as u32),
        GM_ADVENTURE => (MENU_KIND_REG, SEL_REG_ADVENTURE as u32),
        GM_ALLSTAR => (MENU_KIND_REG, SEL_REG_ALLSTAR as u32),
        GM_CLASSIC_GOVER => (MENU_KIND_REG, SEL_REG_CLASSIC as u32),
        GM_ADVENTURE_GOVER => (MENU_KIND_REG, SEL_REG_ADVENTURE as u32),
        GM_ALLSTAR_GOVER => (MENU_KIND_REG, SEL_REG_ALLSTAR as u32),
        GM_EVENT => (MENU_KIND_EVENT, 0),
        GM_TARGET_TEST => (MENU_KIND_STADIUM, SEL_STADIUM_TARGET as u32),
        GM_10MAN_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_10MAN as u32),
        GM_100MAN_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_100MAN as u32),
        GM_3MIN_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_3MIN as u32),
        GM_15MIN_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_15MIN as u32),
        GM_ENDLESS_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_ENDLESS as u32),
        GM_CRUEL_VS => (MENU_KIND_MULTI_VS, SEL_MULTI_VS_CRUEL as u32),
        GM_HOME_RUN_CONTEST => (MENU_KIND_STADIUM, SEL_STADIUM_HOMERUN as u32),
        GM_TRAINING => (MENU_KIND_1P, SEL_1P_TRAINING as u32),
        GM_VS => (MENU_KIND_VS, SEL_VS_MELEE as u32),
        GM_TOURNAMENT => (MENU_KIND_VS, SEL_VS_TOURNAMENT as u32),
        GM_CAMERA_MODE => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_CAMERA as u32),
        GM_STAMINA_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_STAMINA as u32),
        GM_SUPER_SUDDEN_DEATH_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_SUDDEN_DEATH as u32),
        GM_GIANT_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_GIANT as u32),
        GM_TINY_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_TINY as u32),
        GM_INVISIBLE_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_INVISIBLE as u32),
        GM_SLOMO_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_SLOMO as u32),
        GM_LIGHTNING_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_LIGHTNING as u32),
        GM_CAMERA_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_FIXED_CAMERA as u32),
        GM_SINGLE_BUTTON_VS => (MENU_KIND_SPECIAL, SEL_SPECIAL_VS_SINGLE_BUTTON as u32),
        GM_TOY_GALLERY => (MENU_KIND_TOY, SEL_TOY_GALLERY as u32),
        GM_TOY_LOTTERY => (MENU_KIND_TOY, SEL_TOY_LOTTERY as u32),
        GM_TOY_COLLECTION => (MENU_KIND_TOY, SEL_TOY_COLLECTION as u32),
        GM_MENU => (MENU_KIND_SETTINGS, SEL_SETTINGS_LANG as u32),
        _ => (MENU_KIND_MAIN, SEL_MAIN_1P as u32),
    };
    open(data, kind, sel);
}

pub unsafe extern "C" fn onExit(arg0: *mut GameModeState) {
    let data = (*arg0).info.exit_data as *mut MenuExitData;

    ext::gm_SetPendingGameMode((*data).pending_mode as u8);
    ext::gm_SetNewGameModePending();
}
