//! src/melee/gm/gmopening.c: the orthographic 2D camera helper (`gm_801A9DD0`), the frame-time
//! debug label, and the Opening (attract movie MvOpen.mth) scene: sound cues keyed off the movie
//! frame, the title/menu/skip transitions. The only float math is int<->f32 conversions and
//! one `600.0f + (400.0f + frame)` (adds only, no fused multiply-add sites); `(u32)` casts of
//! floats saturate like gwtool's `fptoui.sat`.
//! Verified against the C by the TU state oracle (tests/tuo_gmopening.rs; oracle/tuo).
