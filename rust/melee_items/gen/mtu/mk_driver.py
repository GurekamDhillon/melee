# ------------------------------------------------------------------------------ argument binding
PTR = {  # pointee record -> (C expr, Rust expr)
    "HSD_GObj": ("&GO[rnd() % 4]", "&raw mut GO[(rnd() % 4) as usize]"),
    "Item": ("&IT[rnd() % 4]", "&raw mut IT[(rnd() % 4) as usize]"),
    "Fighter": ("&FT[rnd() % 3]", "&raw mut FT[(rnd() % 3) as usize]"),
    "HitCapsule": ("pick_hit()", "pick_hit()"),
    "HurtCapsule": ("pick_hurt()", "pick_hurt()"),
    "Vec": ("&VA[rnd() % 4]", "&raw mut VA[(rnd() % 4) as usize]"),
    "itECB": ("&EC[rnd() % 3]", "&raw mut EC[(rnd() % 3) as usize]"),
    "_itECB": ("&EC[rnd() % 3]", "&raw mut EC[(rnd() % 3) as usize]"),
    "CollData": ("&IT[rnd() % 4].x378_itemColl", "&raw mut IT[(rnd() % 4) as usize].x378_itemColl"),
    "SpawnItem": ("&SP", "&raw mut SP"),
}
FNK = {"void (struct HSD_GObj *)": 1, "int (struct HSD_GObj *)": 2, "void (struct HSD_GObj *, struct HSD_GObj *)": 3}


def bind(ptype):
    c = canon(ptype)
    k = c.kind
    if k == T.FLOAT:
        return "rw()", "rw()"
    if k in (T.POINTER,):
        pt = canon(c.get_pointee())
        if pt.kind in (T.FUNCTIONPROTO, T.FUNCTIONNOPROTO):
            kind = FNK.get(pt.spelling)
            if kind is None:
                raise SystemExit(f"no callback pool for {pt.spelling}")
            return (f"({ptype.spelling}) pick_cb({kind})", f"unsafe {{ core::mem::transmute::<usize, _>(pick_cb({kind})) }}")
        if pt.kind == T.RECORD:
            n = pt.get_declaration().spelling
            if n in PTR:
                return PTR[n]
        if pt.kind == T.VOID:
            return ("(void*) &IT[rnd() % 4]", "(&raw mut IT[(rnd() % 4) as usize]) as *mut c_void")
        if pt.kind == T.FLOAT:
            return ("&VA[rnd() % 4].x", "&raw mut VA[(rnd() % 4) as usize].x")
        if pt.kind == T.UCHAR:
            return ("U8A", "(&raw mut U8A) as *mut u8")
        if pt.kind == T.INT:
            return ("IA", "(&raw mut IA) as *mut i32")
        if pt.kind == T.UINT:
            return ("UA", "(&raw mut UA) as *mut u32")
        raise SystemExit(f"no binding for pointer to {pt.spelling}")
    if k in gen_tu.INTS or k == T.ENUM:
        return "fv()", "fv() as _"
    raise SystemExit(f"no binding for {ptype.spelling}")


def retcls(rt):
    c = canon(rt)
    if c.kind == T.VOID:
        return "void"
    if c.kind == T.FLOAT:
        return "f4"
    if c.kind == T.POINTER:
        return "ptr"
    return "i4"


def ops_of(tu, stem, cfg):
    ops = []
    for name, cur in tu.defs.items():
        if name in cfg.get("skip", ()):
            continue
        if cur.storage_class == ci.StorageClass.STATIC and name in cfg.get("skip_static", ()):
            continue
        params = list(cur.get_arguments())
        ov = cfg.get("ov", {}).get(name, {})
        pre_c, pre_r, args = [], [], []
        for i, p in enumerate(params):
            if i in ov:
                ce, re_ = ov[i]
            else:
                ce, re_ = bind(p.type)
            ct = p.type.spelling
            pre_c.append(f"{ct} a{i} = {ce};")
            pre_r.append(f"let a{i} = {re_};")
            args.append(f"a{i}")
        rc = retcls(cur.result_type)
        call_c = f"{name}({', '.join(args)})"
        call_r = f"m::{name}({', '.join(args)})"
        if rc == "void":
            sc, sr = f"{call_c};", f"{call_r};"
        elif rc == "f4":
            sc, sr = f"ret = B({call_c});", f"ret = {call_r}.to_bits();"
        elif rc == "ptr":
            sc, sr = f"ret = PI({call_c});", f"ret = pi({call_r});"
        else:
            sc, sr = f"ret = (u32) {call_c};", f"ret = {call_r} as u32;"
        post_c, post_r = cfg.get("post", {}).get(name, ("", ""))
        ops.append(dict(name=name, c=" ".join(pre_c) + " " + sc + " " + post_c, r="\n".join(pre_r) + "\n" + sr + "\n" + post_r,
                        n=cfg.get("n", {}).get(name, cfg.get("ncases", 300)),
                        ft=name in cfg.get("hash_ft", ()) or cfg.get("hash_ft_all", False)))
    return ops


