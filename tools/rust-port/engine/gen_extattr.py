#!/usr/bin/env python3
"""Generate rust/melee_engine/src/extattr.rs: which melee_types record a fighter's `ftData.ext_attr` (a `void*`) is.

Each character's main C file copies it with `COPY_ATTRS(gobj, T)` / `PUSH_ATTRS(fp, T)` (src/melee/ft/inlines.h) or
reads it as `T* x = ftdata->ext_attr`; the first such `T` of `src/melee/ft/kinds/ft<Name>/ft<name>.c` is the record
the public `ftData<Name>` of the fighter's Pl file carries there. The decoder reads it natively (a raw pointer into
the big-endian file would hand the port's float fields byte-swapped words).
Usage: gen_extattr.py
"""
import os, re, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
KINDS = os.path.join(ROOT, 'src', 'melee', 'ft', 'kinds')
GEN = os.path.join(ROOT, 'rust', 'melee_types', 'src', 'gen.rs')
OUT = os.path.join(ROOT, 'rust', 'melee_engine', 'src', 'extattr.rs')

gen = open(GEN, encoding='utf8').read()
known = set(re.findall(r'(?m)^pub (?:struct|type|union) (\w+)', gen))

PAT = [re.compile(r'(?:COPY_ATTRS|PUSH_ATTRS)\(\s*\w+\s*,\s*(\w+)\s*\)'),
       re.compile(r'(\w+)\s*\*\s*\w+\s*=\s*(?:\(\w+\s*\*\))?\s*[\w>\-\(\)]*ext_attr')]
# the clone characters' own files only forward to the base character's code (their attribute block has the base layout)
CLONES = {'falco': 'ftFox_DatAttrs', 'drmario': 'ftMario_DatAttrs', 'emblem': 'MarsAttributes', 'ganon': 'ftCaptain_DatAttrs',
          'pichu': 'ftPikachuAttributes'}
rows = []
skipped = []
for d in sorted(glob.glob(os.path.join(KINDS, 'ft*'))):
    name = os.path.basename(d)[2:]
    main = os.path.join(d, 'ft' + name.lower() + '.c')
    if not os.path.exists(main):
        continue
    text = open(main, encoding='utf8', errors='replace').read()
    ty = None
    for p in PAT:
        m = p.search(text)
        if m:
            ty = m.group(1)
            break
    if ty is None and name.lower() in CLONES:
        ty = CLONES[name.lower()]
    if ty is None:
        skipped.append(f'{name}: no ext_attr type found')
        continue
    if ty not in known:
        skipped.append(f'{name}: {ty} is not a melee_types record')
        continue
    rows.append((name.lower(), ty))

out = ['// @generated by tools/rust-port/engine/gen_extattr.py. Do not edit.',
       '//! `ftData.ext_attr` per fighter: the melee_types record the character code copies it as.',
       '#![allow(non_snake_case, clippy::all)]',
       'use core::ffi::c_void;',
       'use melee_core::gcdecode::GcDecoder;',
       'use melee_types::*;',
       '',
       '/// `sym` is the lowercase fighter name of the public `ftData<Name>`; the pointer word at `at` is decoded as that',
       '/// fighter\'s attribute record (None: no record known for the fighter).',
       'pub fn decode(sym: &str, d: &mut GcDecoder<\'_>, at: u32) -> Option<*mut c_void> {',
       '    Some(match sym {']
for n, t in rows:
    out.append(f'        "{n}" => d.ptr::<{t}>(at) as *mut c_void,')
out += ['        _ => return None,', '    })', '}', '']
if skipped:
    out += ['// not generated:'] + [f'//   {s}' for s in skipped] + ['']
open(OUT, 'w', newline='\n').write('\n'.join(out))
print(f'{len(rows)} fighters, {len(skipped)} skipped: {skipped}')
