//! src/melee/gm/gmscene.c: the scene loop (`gm_801A4D34`, the per-frame driver every scene runs
//! under), the per-scene setup (`gm_801A4BD4`), the debug-pause flags, and the port's TARGET_PC
//! additions: the loading-screen hold, the F9/toast/run-label overlay, `gm_OnePInterstage`.
//!
//! Ported against the shipping build (TARGET_PC on). The C is a long list of calls into TUs that
//! are not ported yet; each is an `ext` TODO stub named like the C function. The logic that lives
//! here is the control flow and the frame/counter state in `gm_80479D58`.
//!
//! Float arithmetic: only `OSSecondsToTicks(1.0F / GM_FPS)` (f32 divide, u32->f32, f32 multiply,
//! f32->u64); no `a*b+c`, so no fused sites (tools/rust-port/fma_sites.py lists none for this file).
//!
//! C semantics kept on purpose:
//! - `bool` is a 4-byte int; `gm_GetDbPauseFlag` returns `x0 & (1ULL << bit)` truncated to int.
//! - `1ULL << bit` follows gwtool (an amount >= 64 gives 0, `cabi`-style), see [`bit64`].
//! - unsigned frame counters compare against `-2` as 0xFFFFFFFE.
//!
//! Checked against the C by the state oracle `tests/s497_gmscene.rs` (rust/melee_modes/oracle/s497):
//! a trace of every callee call (with arguments) and a field-by-field dump of the written state.
