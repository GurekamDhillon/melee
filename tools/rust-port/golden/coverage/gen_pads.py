#!/usr/bin/env python3
"""Generate the coverage pad scripts (pads/*.lua). Deterministic: every input is a pure function of the
frame count (an LCG with a fixed seed). Re-run after editing; commit the output with this file.

Kinds:
  rand_<tag>        VS match, ports 1 and 2 driven by random human-style segments, quits after N match frames.
  randabs_<tag>     any mode (1P, Target Test, ...): port 1 random segments, counted in absolute logic frames
                    (gd.frame), quits at N. Never presses Start.
  zelda_sheik       Zelda human: Down+B transform, fight as Sheik, Down+B back, fight again.
  kirby_copy_*      Kirby inhales idle CPUs (copy abilities), uses the copied move.
  idle_<N>          no input, quits after N match frames (CPU fights).
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "pads")
os.makedirs(out, exist_ok=True)

HDR = "-- @name: %s\n-- @gameplay: true\n-- @rollback_safe: false\n-- Generated by gen_pads.py; do not edit.\n"

# One human-style action: {buttons, stickx, sticky, minlen, maxlen}
ACTIONS = """
local ACTIONS = {
  {0, 0, 0, 10, 40},        -- stand
  {0, 100, 0, 10, 45},      -- run right
  {0, -100, 0, 10, 45},     -- run left
  {0, 55, 0, 8, 30},        -- walk right
  {0, -55, 0, 8, 30},       -- walk left
  {'X', 0, 0, 3, 4},        -- jump
  {'X', 100, 0, 3, 4},      -- jump right
  {'X', -100, 0, 3, 4},     -- jump left
  {'A', 0, 0, 3, 5},        -- jab
  {'A', 100, 0, 3, 8},      -- forward tilt/smash
  {'A', 0, 127, 3, 8},      -- up smash/tilt
  {'A', 0, -127, 3, 8},     -- down smash/tilt
  {'B', 0, 0, 3, 40},       -- neutral special (held: charge)
  {'B', 100, 0, 3, 8},      -- side special
  {'B', 0, 127, 3, 8},      -- up special
  {'B', 0, -127, 3, 20},    -- down special
  {'R', 0, 0, 5, 30},       -- shield
  {'R', 100, 0, 3, 8},      -- shield, roll
  {'Z', 0, 0, 3, 5},        -- grab / z
  {'A', -100, 0, 3, 8},     -- back attack
  {0, 0, -100, 5, 25},      -- crouch
  {0, 0, 100, 3, 6},        -- up
}
"""
RAND = """
local function lcg(s) return (s * 48271) %% 2147483647 end
local function new_player(seed)
  return {s = seed, left = 0, cur = {buttons = 0, x = 0, y = 0}}
end
local function step(p)
  if p.left <= 0 then
    p.s = lcg(p.s); local i = math.floor(p.s / 64) %% #ACTIONS + 1
    local a = ACTIONS[i]
    p.s = lcg(p.s); p.left = a[4] + math.floor(p.s / 64) %% (a[5] - a[4] + 1)
    p.cur = {buttons = a[1], x = a[2], y = a[3]}
  end
  p.left = p.left - 1
  return p.cur
end
"""

def vs_rand(tag, seed1, seed2, frames):
    s = HDR % ("coverage rand pad " + tag)
    s += "local FRAMES = %d\nlocal n = 0\n" % frames + ACTIONS + RAND % ()
    s += """local p1, p2 = new_player(%d), new_player(%d)
function on_frame_pre()
    local m = gd.match()
    if not (m and m.active) then return end
    n = n + 1
    gd.input(1, step(p1), 2)
    gd.input(2, step(p2), 2)
    if n == FRAMES then
        gd.log("COVERAGE quit at frame " .. n)
        gd.quit()
    end
end
""" % (seed1, seed2)
    return s

def abs_rand(tag, seed, frames):
    s = HDR % ("coverage absolute-frame rand pad " + tag)
    s += "local FRAMES = %d\n" % frames + ACTIONS + RAND % ()
    s += """local p1 = new_player(%d)
-- Inside a live match: random human-style input. Anywhere else (intro movies, stage cards, result and
-- continue screens, menus): tap A / Start alternately so the mode moves on; never Start inside a match (pause).
gd.run(function()
  local k = 0
  while gd.frame() < FRAMES do
    local m = gd.match()
    if m and m.active then
      gd.input(1, step(p1), 1)
    else
      local ph = k %% 24
      if ph < 4 then gd.input(1, {buttons = 'A', x = 0, y = 0}, 1)
      elseif ph >= 12 and ph < 16 then gd.input(1, {buttons = 'START', x = 0, y = 0}, 1)
      else gd.input(1, {buttons = 0, x = 0, y = 0}, 1) end
      k = k + 1
    end
    gd.wait(1)
  end
  gd.log("COVERAGE quit at frame " .. gd.frame())
  gd.quit()
end)
""" % seed
    return s

def idle(frames):
    return HDR % ("coverage idle %d" % frames) + """local FRAMES = %d
local n = 0
function on_frame_pre()
    local m = gd.match()
    if not (m and m.active) then return end
    n = n + 1
    if n == FRAMES then
        gd.log("COVERAGE quit at frame " .. n)
        gd.quit()
    end
end
""" % frames

ZELDA = HDR % "coverage zelda/sheik transform" + """-- P1 Zelda (human): wait for GO, Down+B (transform to Sheik), fight, Down+B (back to Zelda), fight.
local FRAMES = 2400
local n = 0
local seq = {
  {150, 0, 0, 0}, {6, 'B', 0, -127},                  -- transform (Zelda -> Sheik)
  {120, 0, 0, 0}, {40, 0, 100, 0}, {4, 'X', 100, 0}, {20, 'A', 0, 0}, {30, 0, 100, 0},
  {6, 'B', 100, 0}, {40, 0, -100, 0}, {5, 'A', 0, -127}, {30, 0, 0, 0},
  {6, 'B', 0, 127}, {60, 0, 0, 0}, {5, 'A', 0, 0}, {40, 0, 60, 0},
  {6, 'B', 0, -127},                                  -- transform back (Sheik -> Zelda)
  {120, 0, 0, 0}, {30, 0, 100, 0}, {5, 'A', 0, 0}, {40, 0, 0, 0}, {6, 'B', 0, 0}, {40, 0, -80, 0},
  {6, 'B', 100, 0}, {60, 0, 0, 0}, {5, 'A', 100, 0}, {50, 0, 0, 0},
}
local total = 0
for _, p in ipairs(seq) do total = total + p[1] end
local function at(frame)
  frame = frame %% total
  for _, p in ipairs(seq) do
    if frame < p[1] then return {buttons = p[2], x = p[3], y = p[4]} end
    frame = frame - p[1]
  end
end
function on_frame_pre()
    local m = gd.match()
    if not (m and m.active) then return end
    n = n + 1
    gd.input(1, at(n), 2)
    if n == FRAMES then
        gd.log("COVERAGE quit at frame " .. n)
        gd.quit()
    end
end
""" % ()

KIRBY = HDR % "coverage kirby copy" + """-- P1 Kirby (human) runs at the idle CPUs, inhales (hold B), swallows (Down), uses the copied B, repeats.
local FRAMES = %d
local n = 0
local seq = {
  {140, 0, 0, 0},
  {25, 0, %d, 0}, {70, 'B', 0, 0}, {6, 0, 0, -127}, {30, 0, 0, 0},         -- inhale + swallow
  {8, 'B', 0, 0}, {30, 0, 0, 0}, {8, 'B', %d, 0}, {40, 0, 0, 0}, {8, 'B', 0, 127}, {40, 0, 0, 0},
  {8, 'B', 0, -127}, {40, 0, 0, 0}, {4, 'X', %d, 0}, {30, 0, %d, 0},
  {70, 'B', 0, 0}, {6, 0, 0, -127}, {30, 0, 0, 0}, {8, 'B', 0, 0}, {40, 0, 0, 0},
  {25, 0, %d, 0}, {70, 'B', 0, 0}, {6, 0, 0, -127}, {40, 0, 0, 0}, {10, 'A', 0, 0},
}
local total = 0
for _, p in ipairs(seq) do total = total + p[1] end
local function at(frame)
  frame = frame %% total
  for _, p in ipairs(seq) do
    if frame < p[1] then return {buttons = p[2], x = p[3], y = p[4]} end
    frame = frame - p[1]
  end
end
function on_frame_pre()
    local m = gd.match()
    if not (m and m.active) then return end
    n = n + 1
    gd.input(1, at(n), 2)
    if n == FRAMES then
        gd.log("COVERAGE quit at frame " .. n)
        gd.quit()
    end
end
"""

def w(name, text):
    with open(os.path.join(out, name), "w", newline="\n") as f:
        f.write(text)

w("idle_3600.lua", idle(3600))
w("idle_1800.lua", idle(1800))
w("idle_900.lua", idle(900))
for i, (a, b) in enumerate([(11, 97), (23, 41), (59, 7), (83, 131), (5, 65), (71, 19)]):
    w("rand_s%d.lua" % (i + 1), vs_rand("s%d" % (i + 1), a * 7919, b * 104729, 1800))
for i, a in enumerate([3, 17, 29, 43]):
    w("randabs_s%d_3600.lua" % (i + 1), abs_rand("s%d 3600" % (i + 1), a * 6151, 3600))
    w("randabs_s%d_1800.lua" % (i + 1), abs_rand("s%d 1800" % (i + 1), a * 6151, 1800))
w("zelda_sheik.lua", ZELDA)
w("kirby_copy_a.lua", KIRBY % (2400, 100, 100, 100, 100, 100))
w("kirby_copy_b.lua", KIRBY % (3000, -100, -100, -100, -100, -100))
print("pads written:", len(os.listdir(out)))
