"""Shard 497-504 generator (gm: gmscdata gmscene gmsinglebutton gmslomo gmstaffroll gmstamina
gmsupersudden gmtiny).

  python rust/melee_modes/oracle/s497/gen.py ext   [tu...]   # rewrite the `mod ext` block of src/tu/<tu>.rs
  python rust/melee_modes/oracle/s497/gen.py oracle [tu...]  # write out/<tu>/tu_part.c + scenario, tests/s497_<tu>.rs

(from the worktree root; Windows Python with libclang==18.1.1). See cfg.py for the per-TU tables
and scen.py for the scenario builders.
"""
import re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import model  # noqa: E402
from model import K, T, ROOT, rust_ty  # noqa: E402

NL = chr(10)
RS_SRC = ROOT / "rust/melee_modes/src/tu"
TESTS = ROOT / "rust/melee_modes/tests"
OUT = ROOT / "rust/target/s497"

KW = {"type", "match", "fn", "ref", "mod", "move", "loop", "in", "as", "box", "self", "impl", "use", "where"}

INTK = {T.CHAR_S, T.SCHAR, T.UCHAR, T.CHAR_U, T.SHORT, T.USHORT, T.INT, T.UINT, T.LONG, T.ULONG, T.LONGLONG,
        T.ULONGLONG, T.BOOL, T.ENUM}
UNS = {1: "unsigned char", 2: "unsigned short", 4: "unsigned int", 8: "unsigned long long"}
RUNS = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}


def pname(n):
    return n + "_" if n in KW else n


def kind(t):
    """tr/ret kind of a C type: i, f, d, p, s (char*), r4 (4-byte record), v."""
    c = t.get_canonical()
    k = c.kind
    if k == T.VOID:
        return "v"
    if k in INTK:
        return "i"
    if k == T.FLOAT:
        return "f"
    if k in (T.DOUBLE, T.LONGDOUBLE):
        return "d"
    if k == T.POINTER:
        pc = c.get_pointee().get_canonical()
        if pc.kind in (T.CHAR_S, T.SCHAR, T.UCHAR, T.CHAR_U):
            return "s"
        return "p"
    if k == T.RECORD and c.get_size() == 4:
        return "r4"
    raise ValueError(f"unsupported type {t.spelling}")


def c_param(t, name):
    sp = t.spelling
    if "(*)" in sp:
        return sp.replace("(*)", f"(*{name})", 1)
    return f"{sp} {name}"


def bits(t):
    return t.get_canonical().get_size() * 8


# ---------------------------------------------------------------- Rust `mod ext`
def rs_to_a(t, expr):
    c = t.get_canonical()
    k = kind(t)
    if k == "i":
        sz = c.get_size()
        return f"A::I({expr} as {RUNS[sz]} as u64)"
    if k == "f":
        return f"A::F({expr})"
    if k == "d":
        return f"A::D({expr})"
    if k == "s":
        return f"A::S({expr} as *const c_char)"
    if k == "p":
        if c.get_pointee().get_canonical().kind == T.FUNCTIONPROTO:
            return f"A::P({expr}.map_or(0, |f| f as usize))"
        return f"A::P({expr} as usize)"
    if k == "r4":
        return f"A::I(core::mem::transmute::<{rust_ty(t)}, u32>({expr}) as u64)"
    raise ValueError(t.spelling)


def rs_from_u64(t, expr):
    c = t.get_canonical()
    k = kind(t)
    rt = rust_ty(t)
    if k == "i":
        return f"{expr} as {rt}"
    if k == "f":
        return f"f32::from_bits({expr} as u32)"
    if k == "d":
        return f"f64::from_bits({expr})"
    if k in ("p", "s"):
        if k == "p" and c.get_pointee().get_canonical().kind == T.FUNCTIONPROTO:
            return f"core::mem::transmute::<usize, {rt}>({expr} as usize)"
        return f"{expr} as usize as {rt}"
    if k == "r4":
        return f"core::mem::transmute::<u32, {rt}>({expr} as u32)"
    raise ValueError(t.spelling)


def rs_ext_fn(f, forward=None, cfg=None):
    cfg = cfg or {}
    ps = [(pname(n), t) for n, t in f.params]
    sig = ", ".join(f"{n}: {rust_ty(t)}" for n, t in ps)
    rk = kind(f.ret)
    ret = "" if rk == "v" else f" -> {rust_ty(f.ret)}"
    def arg(i, n, t):
        if (f.name, i) in cfg.get("outarg", {}):
            return f"A::O({n} as usize)"
        if (f.name, i) in cfg.get("logmem", {}):
            return f"A::M({n} as usize, {cfg['logmem'][(f.name, i)]})"
        return rs_to_a(t, n)
    args = ", ".join(arg(i, n, t) for i, (n, t) in enumerate(ps))
    call = f'h("{f.name}", &[{args}])'
    if rk == "v":
        body = f"if let Some(h) = HOOK {{ {call}; return; }}"
    else:
        body = f"if let Some(h) = HOOK {{ let r = {call}; return {rs_from_u64(f.ret, 'r')}; }}"
    if forward and forward.startswith("|"):
        binds = "".join(f"let a{i} = {n}; " for i, (n, _) in enumerate(ps))
        tail = f"{{ {binds}{forward[1:]} }}"
    elif forward:
        tail = f"{forward}({', '.join(n for n, _ in ps)})"
    else:
        tail = f'panic!("TODO(group6): {f.name} is not ported")'
    return f'    pub unsafe extern "C" fn {f.name}({sig}){ret} {{ {body} {tail} }}'


def rs_ext_block(stem, callees, ext_vars, cfg):
    L = ["// @@ext-begin (generated by rust/melee_modes/oracle/s497/gen.py ext; do not edit by hand)",
         "/// Callees in TUs that are not ported yet (TODO stubs named like the C functions), and the",
         "/// globals the C file reads from other TUs. With [`HOOK`] set (state oracle, tests/s497_*.rs)",
         "/// every call is routed to the hook instead.",
         "pub mod ext {",
         "    #![allow(non_snake_case, non_upper_case_globals, unused_variables, unused_unsafe, dead_code, improper_ctypes_definitions)]",
         "    use core::ffi::{c_char, c_void};",
         "    use melee_types::*;",
         "    use crate::hook::{Hook, A};",
         "    pub static mut HOOK: Option<Hook> = None;"]
    L += cfg.get("ext_types", [])
    fwd = cfg.get("forward", {})
    skip = {k for k, v in model.mine().items() if v != stem and k not in fwd}
    for n in sorted(callees):
        f = callees[n]
        if f.variadic or n in skip or n in cfg.get("skip_callees", ()):
            continue
        L.append(rs_ext_fn(f, fwd.get(n), cfg))
    L += cfg.get("ext_extra", [])
    for n, v in sorted(ext_vars.items()):
        if n in cfg.get("ext_var_types", {}):
            rt = cfg["ext_var_types"][n]
        else:
            rt = rust_ty(v.type)
        L.append(f"    pub static mut {n}: {rt} = unsafe {{ core::mem::zeroed() }};")
    L.append("}")
    L.append("// @@ext-end")
    return "\n".join(L) + "\n"


def write_ext(stem, cfg):
    tu, defs, callees, ext_vars, own = model.load(cfg["path"])
    p = RS_SRC / f"{stem}.rs"
    s = p.read_text(encoding="utf-8")
    blk = rs_ext_block(stem, callees, ext_vars, cfg)
    if "// @@ext-begin" in s:
        s = re.sub(r"// @@ext-begin.*?// @@ext-end\n", lambda m: blk, s, flags=re.S)
    else:
        raise SystemExit(f"{p}: no @@ext markers")
    p.write_text(s, encoding="utf-8", newline="\n")
    print(f"{stem}: ext block with {sum(1 for f in callees.values() if not f.variadic)} callees, {len(ext_vars)} vars")


# ---------------------------------------------------------------- dumpers
class Leaf:
    def __init__(self, path, off, size, cls, bf=None):
        self.path, self.off, self.size, self.cls, self.bf = path, off, size, cls, bf


def leaves(t, prefix="", base=0, out=None, depth=0):
    out = [] if out is None else out
    c = t.get_canonical()
    k = c.kind
    if k == T.RECORD:
        d = c.get_declaration()
        if d.kind == K.UNION_DECL:
            out.append(Leaf(prefix or "u", base, c.get_size(), "blob"))
            return out
        for f in c.get_fields():
            off = base + c.get_offset(f.spelling) // 8 if f.spelling else None
            if f.spelling == "":
                # anonymous member: its offset is in the parent's field list by position
                raise ValueError(f"anonymous member in {c.spelling}")
            name = prefix + ("." if prefix else "") + f.spelling
            if f.is_bitfield():
                out.append(Leaf(name, c.get_offset(f.spelling) // 8 + base, 0, "bf",
                                (f.get_bitfield_width(), f.type.get_canonical().kind in (T.SCHAR, T.CHAR_S, T.SHORT, T.INT, T.LONG))))
                continue
            leaves(f.type, name, off, out, depth + 1)
        return out
    if k == T.CONSTANTARRAY:
        el = c.element_type.get_canonical()
        n = c.element_count
        if el.kind == T.RECORD and el.get_declaration().kind != K.UNION_DECL and n <= 16:
            for i in range(n):
                leaves(el, f"{prefix}[{i}]", base + i * el.get_size(), out, depth + 1)
        elif el.kind != T.RECORD and n <= 8 and el.kind not in (T.CHAR_S, T.SCHAR, T.UCHAR, T.CHAR_U):
            for i in range(n):
                leaves(el, f"{prefix}[{i}]", base + i * el.get_size(), out, depth + 1)
        else:
            out.append(Leaf(prefix, base, c.get_size(), "blob"))
        return out
    sz = c.get_size()
    if k in INTK:
        out.append(Leaf(prefix, base, sz, "i"))
    elif k == T.FLOAT:
        out.append(Leaf(prefix, base, 4, "f"))
    elif k in (T.DOUBLE, T.LONGDOUBLE):
        out.append(Leaf(prefix, base, 8, "d"))
    elif k == T.POINTER:
        out.append(Leaf(prefix, base, 8, "p"))
    else:
        raise ValueError(f"leaf {prefix}: {t.spelling} {k}")
    return out


def c_dumper(name, ct, lv, size):
    L = [f"static void dump_{name}(const unsigned char* b)", "{"]
    for l in lv:
        path = l.path
        if l.cls == "bf":
            w, signed = l.bf
            mask = (1 << w) - 1
            L.append(f'    d_i("{path}", (unsigned long long)(((const {ct}*) b)->{path}) & 0x{mask:x}ULL);')
        elif l.cls == "i":
            L.append(f'    d_i("{path}", (unsigned long long)*(const {UNS[l.size]}*)(b + {l.off}));')
        elif l.cls == "f":
            L.append(f'    d_f("{path}", *(const unsigned*)(b + {l.off}));')
        elif l.cls == "d":
            L.append(f'    d_d("{path}", *(const unsigned long long*)(b + {l.off}));')
        elif l.cls == "p":
            L.append(f'    d_p("{path}", *(const unsigned long long*)(b + {l.off}));')
        else:
            L.append(f'    d_blob("{path}", b + {l.off}, {l.size});')
    L.append("}")
    return "\n".join(L)


def rs_dumper(name, rt, lv, size):
    L = [f"unsafe fn dump_{name}(b: *const u8) {{"]
    for l in lv:
        path = l.path
        if l.cls == "bf":
            w, signed = l.bf
            mask = (1 << w) - 1
            L.append(f'    d_i("{path}", ((*(b as *const {rt})).{path}() as u64) & 0x{mask:x});')
        elif l.cls == "i":
            L.append(f'    d_i("{path}", core::ptr::read_unaligned(b.add({l.off}) as *const {RUNS[l.size]}) as u64);')
        elif l.cls == "f":
            L.append(f'    d_f("{path}", core::ptr::read_unaligned(b.add({l.off}) as *const u32));')
        elif l.cls == "d":
            L.append(f'    d_d("{path}", core::ptr::read_unaligned(b.add({l.off}) as *const u64));')
        elif l.cls == "p":
            L.append(f'    d_p("{path}", core::ptr::read_unaligned(b.add({l.off}) as *const u64));')
        else:
            L.append(f'    d_blob("{path}", b.add({l.off}), {l.size});')
    L.append("}")
    return "\n".join(L)


# Raw random bytes mean different things to a native C bitfield (LSB first) and to melee_types'
# GameCube-ordered accessors (MSB first), so objects holding bitfields get their bitfields set
# logically after the raw fill (op `bf`): the same splitmix64 stream drives both sides.
def bf_leaves(lv):
    return [l for l in lv if l.cls == "bf"]


def c_bffill(name, ct, lv):
    bl = bf_leaves(lv)
    if not bl:
        return None
    L = [f"static void bffill_{name}(unsigned char* b, unsigned long long* st)", "{"]
    for l in bl:
        mask = (1 << l.bf[0]) - 1
        L.append(f"    ((({ct}*) b)->{l.path}) = (unsigned long long) (s497_next(st) & 0x{mask:x}ULL);")
    L.append("}")
    return "\n".join(L)


def rs_bffill(name, rt, lv):
    bl = bf_leaves(lv)
    if not bl:
        return None
    L = [f"unsafe fn bffill_{name}(b: *mut u8, st: &mut u64) {{"]
    for l in bl:
        mask = (1 << l.bf[0]) - 1
        head, _, last = l.path.rpartition(".")
        L.append(f"    (*(b as *mut {rt})).{head + '.' if head else ''}set_{last}((s497_next(st) & 0x{mask:x}) as _);")
    L.append("}")
    return "\n".join(L)


def gen_oracle(stem):
    import cfg, emit, scen
    c = cfg.TUS[stem]
    oc = cfg.ORACLE[stem]
    tu, defs, callees, ext_vars, own = model.load(c["path"])
    d = OUT / stem
    d.mkdir(parents=True, exist_ok=True)
    (d / "tu_part.c").write_text(emit.build_tu_part(stem, c, oc), encoding="utf-8", newline=NL)
    builder = getattr(scen, oc.get("scenario", "build_vsmode"))
    text = builder(stem, c, oc, tu)
    (TESTS / "data").mkdir(parents=True, exist_ok=True)
    (TESTS / "data" / f"s497_{stem}_scen.txt").write_text(text, encoding="utf-8", newline=NL)
    (TESTS / f"s497_{stem}.rs").write_text(emit.build_rs_test(stem, c, oc), encoding="utf-8", newline=NL)
    print(f"{stem}: tu_part.c, scenario ({text.count('begin ')} blocks), tests/s497_{stem}.rs")


if __name__ == "__main__":
    import cfg
    mode = sys.argv[1]
    names = sys.argv[2:] or list(cfg.TUS)
    for n in names:
        if mode == "ext":
            write_ext(n, cfg.TUS[n])
        elif mode == "oracle":
            gen_oracle(n)
        else:
            raise SystemExit("usage: gen.py ext|oracle [tu...]")
