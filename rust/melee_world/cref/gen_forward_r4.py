"""Night-3 round-4 generator: the single-call forwarders of the per-stage gr TUs (every gr/*.c
except stage.c, ground.c, grlib.c) whose body is exactly one of
  grZakoGenerator_801CAE04(NULL);          (void fn(void))
  Ground_UpdateMapColl(<arg>);             (void fn(Ground_GObj* / HSD_GObj*))
  Ground_StartMapAnim(<arg>);              (gr/inlines.h: grAnime_801C8138(gobj, gp->map_id, 0))
  Ground_InitMapCollAndAnim(<arg>);        (inlines.h: Ground_InitMapColl(jobj, map_id); grAnime_...)
  Ground_UpdateWindAndMapColl(<arg>);      (inlines.h: lb_800115F4(); Ground_UpdateMapColl(gobj))

Writes:
  rust/melee_world/src/gr/forward.rs   the Rust ports (one module per TU), calling through
                                       `gr::forward::CALLEES` (the not-yet-ported callees)
  <out>/forward_r4_body.inc            the C bodies, verbatim, renamed TU__name
  <out>/forward_r4_driver.c            the oracle driver
Usage: python gen_forward_r4.py <repo root> <out dir>   (gen_forward_r4_ref.sh runs it)
"""
import glob, os, re, sys

root, out = sys.argv[1], sys.argv[2]
SKIP = {'stage.c', 'ground.c', 'grlib.c'}
PAT = [(re.compile(r'^grZakoGenerator_801CAE04\(NULL\);$'), 'zako'),
       (re.compile(r'^Ground_UpdateMapColl\((\w+)\);$'), 'umc'),
       (re.compile(r'^Ground_StartMapAnim\((\w+)\);$'), 'sma'),
       (re.compile(r'^Ground_InitMapCollAndAnim\((\w+)\);$'), 'imca'),
       (re.compile(r'^Ground_UpdateWindAndMapColl\((\w+)\);$'), 'uwmc')]
RUST = {
    'zako': 'c.grzakogenerator_801cae04(core::ptr::null_mut());',
    'umc': 'c.ground_update_map_coll(a0);',
    'sma': 'let gp = (*a0).user_data as *mut Ground; c.granime_801c8138(a0, (*gp).map_id as i32, 0);',
    'imca': 'let gp = (*a0).user_data as *mut Ground; let j = (*a0).hsd_obj as *mut HSD_JObj; '
            'c.ground_init_map_coll(j, (*gp).map_id as i32); c.granime_801c8138(a0, (*gp).map_id as i32, 0);',
    'uwmc': 'c.lb_800115f4(); c.ground_update_map_coll(a0);',
}
fns = []
for fn in sorted(glob.glob(os.path.join(root, 'src/melee/gr/*.c'))):
    base = os.path.basename(fn)
    if base in SKIP:
        continue
    tu = base[:-2]
    L = open(fn, encoding='utf8', errors='ignore').read().split('\n')
    i = 0
    while i < len(L):
        l = L[i]
        if re.match(r'^[A-Za-z].*\(.*\)\s*$', l) and ';' not in l and i + 1 < len(L) and L[i + 1].startswith('{'):
            j = i + 2
            body = []
            while j < len(L) and not L[j].startswith('}'):
                body.append(L[j])
                j += 1
            b = re.sub(r'\s+', ' ', '\n'.join(body)).strip()
            for p, kind in PAT:
                mm = p.match(b)
                if not mm:
                    continue
                m = re.match(r'^(?:static\s+)?(?:inline\s+)?void\s+(\w+)\s*\((.*)\)\s*$', l)
                if not m:
                    sys.exit(f'unmapped {base}: {l}')
                name, params = m.group(1), m.group(2).strip()
                if kind == 'zako':
                    if params != 'void':
                        sys.exit(f'params {base}:{name}')
                else:
                    pm = re.match(r'^(Ground_GObj|HSD_GObj)\s*\*\s*(\w+)$', params)
                    if not pm or pm.group(2) != mm.group(1):
                        sys.exit(f'params {base}:{name}: {params}')
                fns.append(dict(tu=tu, name=name, kind=kind, line=i + 1, sig=l, body='\n'.join(body)))
            i = j
        i += 1

with open(os.path.join(out, 'forward_r4_body.inc'), 'w', newline='\n') as f:
    for d in fns:
        sig = re.sub(r'^static\s+(inline\s+)?', '', d['sig'])
        sig = re.sub(r'\b%s\s*\(' % d['name'], '%s__%s(' % (d['tu'], d['name']), sig, count=1)
        f.write(f"{sig}\n{{\n{d['body']}\n}}\n")
with open(os.path.join(out, 'forward_r4_driver.c'), 'w', newline='\n') as f:
    f.write('#include "forward_r4_harness.h"\n')
    for d in fns:
        a = 'void' if d['kind'] == 'zako' else 'HSD_GObj*'
        f.write(f"void {d['tu']}__{d['name']}({a});\n")
    f.write('int main(void)\n{\n    static const int ids[] = { 0, 1, 31, 70, -1, 0x7FFFFFFF };\n'
            '    for (int k = 0; k < 6; k++) {\n        harness_set(ids[k]);\n')
    for d in fns:
        a = '' if d['kind'] == 'zako' else 'harness_gobj()'
        f.write(f"        printf(\"{d['tu']} {d['name']} %d:\", ids[k]); {d['tu']}__{d['name']}({a}); printf(\"\\n\");\n")
    f.write('    }\n    return 0;\n}\n')

o = ['//! Night 3 round 4: the single-call forwarders of the per-stage gr TUs (generated by',
     '//! `cref/gen_forward_r4.py`; do not edit by hand). Each body is one call:',
     '//! `grZakoGenerator_801CAE04(NULL)`, `Ground_UpdateMapColl(gobj)`, or one of the gr/inlines.h',
     '//! inlines `Ground_StartMapAnim` (grAnime_801C8138(gobj, gp->map_id, 0)),',
     '//! `Ground_InitMapCollAndAnim` (Ground_InitMapColl(jobj, map_id) then grAnime_801C8138) and',
     '//! `Ground_UpdateWindAndMapColl` (lb_800115F4() then Ground_UpdateMapColl), expanded here.',
     '//! The callees are not ported yet (ground.c rest, granime.c, grzakogenerator.c, group 1 lb);',
     '//! they go through [`CALLEES`], whose defaults panic: TODO(group2: gr/ground.c',
     '//! Ground_InitMapColl / Ground_UpdateMapColl, gr/granime.c grAnime_801C8138,',
     '//! gr/grzakogenerator.c grZakoGenerator_801CAE04), TODO(group1: lb/lb_00F9.c lb_800115F4).',
     '//! Checked against the C by `tests/forward_r4_vs_c.rs` (call traces through recorders).',
     '#![allow(non_snake_case, clippy::all)]', '',
     'use melee_types::{Ground, HSD_GObj, HSD_JObj};', 'use std::sync::RwLock;', '',
     '/// The callees of the forwarders. Each defaults to a panic until its port exists.',
     '#[derive(Clone, Copy)]', 'pub struct Callees {',
     '    /// grZakoGenerator_801CAE04 (gr/grzakogenerator.c), result discarded by every caller.',
     '    pub grzakogenerator_801cae04: unsafe fn(*mut core::ffi::c_void),',
     '    /// Ground_UpdateMapColl (gr/ground.c), result discarded by every caller.',
     '    pub ground_update_map_coll: unsafe fn(*mut HSD_GObj),',
     '    /// Ground_InitMapColl (gr/ground.c), result discarded.',
     '    pub ground_init_map_coll: unsafe fn(*mut HSD_JObj, i32),',
     '    /// grAnime_801C8138 (gr/granime.c).',
     '    pub granime_801c8138: unsafe fn(*mut HSD_GObj, i32, i32),',
     '    /// lb_800115F4 (lb/lb_00F9.c, group 1).',
     '    pub lb_800115f4: unsafe fn(),', '}', '',
     'unsafe fn todo_zako(_: *mut core::ffi::c_void) { unimplemented!("TODO(group2): grZakoGenerator_801CAE04") }',
     'unsafe fn todo_umc(_: *mut HSD_GObj) { unimplemented!("TODO(group2): Ground_UpdateMapColl") }',
     'unsafe fn todo_imc(_: *mut HSD_JObj, _: i32) { unimplemented!("TODO(group2): Ground_InitMapColl") }',
     'unsafe fn todo_anim(_: *mut HSD_GObj, _: i32, _: i32) { unimplemented!("TODO(group2): grAnime_801C8138") }',
     'unsafe fn todo_lb() { unimplemented!("TODO(group1): lb_800115F4") }', '',
     '/// The callee table the forwarders call through (C callbacks carry no context).',
     'pub static CALLEES: RwLock<Callees> = RwLock::new(Callees {',
     '    grzakogenerator_801cae04: todo_zako, ground_update_map_coll: todo_umc,',
     '    ground_init_map_coll: todo_imc, granime_801c8138: todo_anim, lb_800115f4: todo_lb,', '});', '',
     'struct C(Callees);', 'impl C {',
     '    unsafe fn grzakogenerator_801cae04(&self, a: *mut core::ffi::c_void) { (self.0.grzakogenerator_801cae04)(a) }',
     '    unsafe fn ground_update_map_coll(&self, g: *mut HSD_GObj) { (self.0.ground_update_map_coll)(g) }',
     '    unsafe fn ground_init_map_coll(&self, j: *mut HSD_JObj, m: i32) { (self.0.ground_init_map_coll)(j, m) }',
     '    unsafe fn granime_801c8138(&self, g: *mut HSD_GObj, m: i32, b: i32) { (self.0.granime_801c8138)(g, m, b) }',
     '    unsafe fn lb_800115f4(&self) { (self.0.lb_800115f4)() }', '}',
     'fn c() -> C { C(*CALLEES.read().unwrap_or_else(|e| e.into_inner())) }', '']
calls = []
cur = None
for d in fns:
    if d['tu'] != cur:
        if cur is not None:
            o.append('}\n')
        cur = d['tu']
        o.append(f'/// src/melee/gr/{cur}.c\npub mod {cur} {{\n    use super::*;')
    args = '' if d['kind'] == 'zako' else 'a0: *mut HSD_GObj'
    o.append(f"    /// {d['name']} (gr/{d['tu']}.c:{d['line']})")
    o.append(f"    pub unsafe extern \"C\" fn {d['name']}({args}) {{ let c = c(); {RUST[d['kind']]} }}")
    ca = '' if d['kind'] == 'zako' else 'g'
    calls.append(f'        ("{d["tu"]}", "{d["name"]}") => {d["tu"]}::{d["name"]}({ca}),')
o.append('}\n')
o.append(f'/// Number of functions in this module.\npub const COUNT: usize = {len(fns)};\n')
o.append('/// Test entry: call `tu::name` (with `g` for the gobj forwarders). `false` if unknown.')
o.append('#[doc(hidden)]\npub unsafe fn call_by_name(tu: &str, name: &str, g: *mut HSD_GObj) -> bool {')
o.append('    match (tu, name) {')
o += calls
o.append('        _ => return false,\n    }\n    true\n}')
open(os.path.join(root, 'rust/melee_world/src/gr/forward.rs'), 'w', newline='\n').write('\n'.join(o) + '\n')
print(len(fns))
