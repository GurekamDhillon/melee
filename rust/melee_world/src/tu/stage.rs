/// Fill the external ids past the vanilla initializer from mexData. Idempotent; a vanilla disc
/// leaves the whole tail zeroed, which reads as Gr_Kind_Unk00 exactly as the vanilla array's
/// implicit tail would.
pub unsafe extern "C" fn Stage_MexInitIds() {
    melee_core::ct!("Stage_MexInitIds");
    if done != 0 {
        return;
    }
    done = 1;
    let mut n = ext::Mex_GrExternalCount();
    if n > ST_MEX_EXT_MAX as i32 {
        ext::OSReport(
            c"stage: %d external stage ids but stage_id_map[] holds %d - ids %d and up will read off the end\n".as_ptr(),
            &[n as i64 as u64, ST_MEX_EXT_MAX as u64, ST_MEX_EXT_MAX as u64],
        );
        n = ST_MEX_EXT_MAX as i32;
    }
    let mut e = 0;
    while e < n {
        let k = ext::Mex_GrKindForExt(e);
        if k >= 0 {
            stage_id_map[e as usize].grkind = k as GrKind;
        }
        e += 1;
    }
}

