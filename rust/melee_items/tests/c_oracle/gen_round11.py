#!/usr/bin/env python3
"""Round 11 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round11.py

Round 11 (night 3, round 3) is hand-ported only (src/itkinds11.rs): functions whose only unported
callees are now native elsewhere in the workspace (jobj.h inline getters in melee_types::inline,
MSL sqrtf_accurate and HSD_Randi in melee_runtime). This writes tests/c_oracle/round11_bodies.h,
the verbatim decomp C bodies of the HAND list, #included by round11.c. Never edit the output by
hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """it_80272CC0 it_80274990 it_80271B60 it_80271F78 itLinkArrow_802A850C_inline_2
calc_dist_2d_accurate""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

b = ["/* @generated by gen_round11.py: verbatim copies of the decomp C bodies ported in round 11",
     " * (src/itkinds11.rs), grouped by source file. #included by round11.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        lastp = path
    b.append(body.strip())
    b.append('')
(OR / 'round11_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')
