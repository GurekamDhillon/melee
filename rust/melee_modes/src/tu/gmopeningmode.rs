pub unsafe extern "C" fn onExitTitle(arg0: *mut GameModeState) {
    let temp_r3 = ext::gm_GetGameModeStateExitData(arg0) as *mut i32;
    // TARGET_PC: no /develop.ini on retail ISOs, so DbLevel stays Master: let Y (or B) open the
    // debug menu.
    if *temp_r3 & (0x800 | 0x200) != 0 {
        ext::gm_SetPendingGameMode(GM_DEBUG as u8);
        ext::gm_SetNewGameModePending();
        return;
    }
    if ext::DbLevel >= DbLKind_DebugRom {
        if *temp_r3 & 0x100 != 0 {
            ext::gm_SetPendingGameMode(GM_DEBUG_VS as u8);
            ext::gm_SetNewGameModePending();
        } else if *temp_r3 & 0x1000 != 0 {
            ext::gm_SetPendingGameMode(GM_MENU as u8);
            ext::gm_SetNewGameModePending();
        } else if *temp_r3 & 0x400 != 0 {
            ext::gm_SetPendingGameMode(GM_DEBUG_SOUND_TEST as u8);
            ext::gm_SetNewGameModePending();
        } else if *temp_r3 & 0x800 != 0 {
            ext::gm_SetPendingGameMode(GM_DEBUG as u8);
            ext::gm_SetNewGameModePending();
        }
    } else if *temp_r3 & 0x1000 != 0 {
        ext::gm_80173EEC();
        ext::gm_80172898(0x100);
        if ext::gm_80173754(1, 0) == 0 {
            ext::gm_SetPendingGameMode(GM_MENU as u8);
        }
        ext::gm_SetNewGameModePending();
    }
}

