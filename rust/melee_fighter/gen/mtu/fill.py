#!/usr/bin/env python3
"""fill_<T> / hash_<T> generator (libclang Walk of rust/melee_items/gen/mtu/gen_tu.py) for the melee_fighter oracles.

  python rust/melee_fighter/gen/mtu/fill.py <name> <game .c> <pool types, comma separated> <state types, comma separated>

Writes gen/cref/tu/<name>_state.h (C) and tests/<name>_state/gen.rs (Rust): for every state type a field-by-field
random fill (bitfields by value, pointers to a pool type drawn from `pick_<Type>()`, other pointers left alone) and
a field-by-field hash (pointers by pool id), draw for draw the same on both sides. The including driver defines the
`pick_<Type>` functions, `pick_fn` and the shared harness first.
"""
import os, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "rust/melee_items/gen/mtu"))
os.chdir(ROOT)
import gen_tu as gt  # noqa: E402


def main():
    name, csrc, pools, types = sys.argv[1:5]
    tu = gt.Tu(csrc, (), (ROOT / csrc).parent)
    pools = [p for p in pools.split(",") if p]
    w = gt.Walk(tu, pools)
    c_out = [f"/* generated by gen/mtu/fill.py for {csrc}: do not edit */"]
    r_out = [f"// generated by rust/melee_fighter/gen/mtu/fill.py for {csrc}: do not edit",
             ""]
    fwd = []
    for t in types.split(","):
        cn = ("struct " + t) if t in tu.tagged else t
        fwd.append(f"static void fill_{t}({cn}* p);")
        fwd.append(f"static void hash_{t}(const {cn}* p);")
    c_out += fwd
    for t in types.split(","):
        cdef, rdef = w.gen(t)
        c_out.append(cdef)
        r_out.append(rdef)
    (ROOT / "rust/melee_fighter/gen/cref/tu" / f"{name}_state.h").write_text("\n".join(c_out) + "\n", encoding="utf-8", newline="\n")
    d = ROOT / "rust/melee_fighter/tests" / f"{name}_state"
    d.mkdir(parents=True, exist_ok=True)
    (d / "gen.rs").write_text("\n".join(r_out), encoding="utf-8", newline="\n")
    print(f"fill: {name}: {types}")


if __name__ == "__main__":
    main()
