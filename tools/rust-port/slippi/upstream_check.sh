#!/bin/bash
# Slippi upstream check: did project-slippi/slippi-ssbm-asm (and, when a clone exists, the Ishiiruka/Dolphin side) change
# anything that affects gameplay since we last looked? Our online play must stay byte-compatible with Slippi's ASM, so a new
# gameplay commit is something to read and port.
#
#   bash tools/rust-port/slippi/upstream_check.sh
#
# Clones (read-only apart from `git fetch -q origin`; never pull/checkout/reset):
#   $SLIPPI_SRC/ssbm-asm   the ASM, always checked. SLIPPI_SRC = E:/Projects/Melee Workspace/_build/slippi-src
#   $SLIPPI_SRC/<other>    any other git clone there is the Dolphin side (Ishiiruka / slippi-dolphin), checked the same way
#                          with its own marker; at the time of writing there is none, so only the ASM is checked.
# State: $SLIPPI_STATE = E:/Projects/Melee Workspace/scratch/slippi-upstream/
#   last-seen            SHA of origin/master the ASM check last looked at (first run: initialised to the current head, so
#                        the first run reports nothing)
#   last-seen-<clone>    the same for another clone (branch: its origin/HEAD)
#   log.md               a dated section appended per run that found new commits: commit, date, subject, files, GAMEPLAY yes/no
#
# A commit is GAMEPLAY (ASM) when it
#   * changes any file under Online/ or Common/ (Output/Netplay/ is a build artifact regenerated by nearly every
#     commit; a real code change there is caught through the source it was built from), or
#   * changes a line mentioning [affects-gameplay] in Output/InjectionLists/*.json, or
#   * changes an .asm/.s file that an InjectionLists entry tagged [affects-gameplay] hooks (the entry's Annotation is the
#     source path), as the lists stand at origin/master.
# Dolphin side: any change under Source/Core/Core/Slippi/, HW/EXI_DeviceSlippi*, or NetPlay* / Slippi* in Source/Core/Core.
#
# Output: one summary line. Exit 0: nothing new, or only non-gameplay commits. Exit 3: at least one new gameplay commit.
# Exit 1: a clone is missing or a git step failed. Not scheduled by this script; run it by hand.
# The marker moves to the checked head after each run, so a gameplay commit is reported once (it stays in log.md).

SRC="${SLIPPI_SRC:-E:/Projects/Melee Workspace/_build/slippi-src}"
STATE="${SLIPPI_STATE:-E:/Projects/Melee Workspace/scratch/slippi-upstream}"
mkdir -p "$STATE"
LOG="$STATE/log.md"
[ -d "$SRC/ssbm-asm/.git" ] || { echo "upstream_check: no clone at $SRC/ssbm-asm"; exit 1; }

# check_repo <dir> <kind asm|dolphin> <marker file>: prints "<new> <gameplay> <note>", appends to the log
check_repo() {
  local dir="$1" kind="$2" marker="$3" name
  name="$(basename "$dir")"
  git -C "$dir" fetch -q origin 2>/dev/null || { echo "ERR fetch failed in $name"; return 1; }
  local ref="origin/master"
  git -C "$dir" rev-parse -q --verify "$ref" >/dev/null || ref="origin/HEAD"
  local head; head="$(git -C "$dir" rev-parse "$ref")"
  if [ ! -s "$marker" ]; then
    echo "$head" > "$marker"
    echo "0 0 $name: first run, marker set to ${head:0:7}"
    return 0
  fi
  local last; last="$(cat "$marker")"
  if ! git -C "$dir" cat-file -e "$last^{commit}" 2>/dev/null; then
    echo "ERR $name: last-seen ${last:0:7} is not in the clone (history rewritten?); delete $marker to reset"
    return 1
  fi
  local n; n="$(git -C "$dir" rev-list --count "$last..$ref")"
  if [ "$n" = 0 ]; then echo "0 0 $name: up to date at ${head:0:7}"; return 0; fi
  # hooked sources of [affects-gameplay] entries, as the lists stand now
  local hooked=""
  if [ "$kind" = asm ]; then
    hooked="$(python -I -c '
import sys,json,subprocess
d,ref=sys.argv[1:3]
g=lambda *a: subprocess.run(["git","-C",d]+list(a),capture_output=True,text=True).stdout
out=set()
for f in g("ls-tree","-r","--name-only",ref,"Output/InjectionLists/").split():
    try: det=json.loads(g("show",ref+":"+f))["Details"]
    except Exception: continue
    for e in det:
        if "[affects-gameplay]" in e.get("Tags","") and e.get("Annotation"): out.add(e["Annotation"])
print(chr(10).join(sorted(out)))' "$dir" "$ref")"
  fi
  local gp=0 section="" sha date subj files g why
  while read -r sha; do
    date="$(git -C "$dir" log -1 --format=%cs "$sha")"
    subj="$(git -C "$dir" log -1 --format=%s "$sha")"
    files="$(git -C "$dir" diff-tree --no-commit-id --name-only -r -m --first-parent "$sha")"
    g=no; why=""
    if [ "$kind" = asm ]; then
      if echo "$files" | grep -qE '^(Online/|Common/)'; then g=yes; why="Online/Common path"; fi
      if [ $g = no ] && echo "$files" | grep -q '^Output/InjectionLists/' &&
         git -C "$dir" show -m --first-parent --format= -U0 "$sha" -- Output/InjectionLists/ | grep -E '^[+-]' | grep -q 'affects-gameplay'; then
        g=yes; why="injection list entry tagged affects-gameplay"
      fi
      if [ $g = no ] && [ -n "$hooked" ] && echo "$files" | grep -Fxq -f <(echo "$hooked"); then g=yes; why="hooked by an affects-gameplay entry"; fi
    else
      if echo "$files" | grep -qE '^Source/Core/Core/(Slippi/|HW/EXI_DeviceSlippi|.*(NetPlay|Slippi))'; then g=yes; why="Slippi/NetPlay path"; fi
    fi
    [ $g = yes ] && gp=$((gp+1))
    section+="- \`${sha:0:7}\` $date $subj — GAMEPLAY $g${why:+ ($why)}"$'\n'
    section+="  files: $(echo "$files" | tr '\n' ' ')"$'\n'
  done < <(git -C "$dir" rev-list --reverse "$last..$ref")
  {
    echo
    echo "## $(date +%Y-%m-%d) $name ${last:0:7}..${head:0:7} ($n new, $gp gameplay)"
    echo
    printf '%s' "$section"
  } >> "$LOG"
  echo "$head" > "$marker"
  echo "$n $gp $name: $n new commit(s) to ${head:0:7}, $gp gameplay"
}

rc=0; lines=()
r="$(check_repo "$SRC/ssbm-asm" asm "$STATE/last-seen")" || { echo "upstream_check: ${r#ERR }"; exit 1; }
lines+=("$r")
for d in "$SRC"/*/; do
  d="${d%/}"; [ "$(basename "$d")" = ssbm-asm ] && continue
  [ -e "$d/.git" ] || continue
  r="$(check_repo "$d" dolphin "$STATE/last-seen-$(basename "$d")")" || { echo "upstream_check: ${r#ERR }"; exit 1; }
  lines+=("$r")
done
gp=0; summary=""
for l in "${lines[@]}"; do
  read -r n g rest <<<"$l"; gp=$((gp+g)); summary+="${summary:+; }$rest"
done
[ -z "$(ls -d "$SRC"/*/ 2>/dev/null | grep -v ssbm-asm)" ] && summary+="; no Ishiiruka/Dolphin clone under $SRC (ASM only)"
echo "upstream_check: $summary"
[ "$gp" -gt 0 ] && exit 3
exit 0
