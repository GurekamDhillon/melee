// C oracle for melee_platform: the shipping C/C++ source of the PAD paths, compiled natively.
//  * pc/platform/gc_adapter_decode.h, #included verbatim (gw_w16 = plain store: the Rust port
//    keeps button in native order, the C stores it big-endian for game memory; same value).
//  * Aurora's ClampRegion + ClampTrigger/ClampCircle/ClampStick/PADClamp/PADClampCircle, cut
//    verbatim from extern/aurora/lib/dolphin/pad/pad.cpp by build.sh into aurora_clamp.inc.
// Integer code only (ClampCircle's std::sqrt is a double sqrt of an int): no FMA sites.
// Output: tests/data/pad_oracle.txt. Each section prints a line count and an FNV-1a-64 hash of
// its lines (the Rust test regenerates the same inputs and lines), plus the first lines verbatim.
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <cmath>
#include <algorithm>
#include <string>
#include "pad_types.h"
extern "C" int oracle_decode(const unsigned char *snap, void *status, int recal);
#include "aurora_clamp.inc"

static uint64_t H; static long N; static int SHOW;
static void line(const std::string &s) {
  for (unsigned char c : s) { H ^= c; H *= 0x100000001b3ULL; }
  H ^= '\n'; H *= 0x100000001b3ULL;
  if (SHOW-- > 0) printf("  %s\n", s.c_str());
  ++N;
}
static void begin(int show) { H = 0xcbf29ce484222325ULL; N = 0; SHOW = show; }
static void end(const char *name) { printf("%s %ld %016llx\n", name, N, (unsigned long long)H); }
static std::string st_str(const PADStatus &s) {
  char b[96];
  snprintf(b, sizeof b, "%04x %d %d %d %d %u %u %u %u %d", s.button, s.stickX, s.stickY, s.substickX,
           s.substickY, s.triggerLeft, s.triggerRight, s.analogA, s.analogB, s.err);
  return b;
}
static uint32_t rng = 12345;
static uint32_t next() { rng = rng * 1103515245u + 12345u; return rng >> 8; }

int main() {
  char b[128];
  printf("# generated by rust/melee_platform/oracle/build.sh; do not edit\n");
  // clamp_stick, both regions, every (x, y)
  begin(0);
  for (int r = 0; r < 2; ++r)
    for (int x = -128; x < 128; ++x)
      for (int y = -128; y < 128; ++y) {
        s8 px = (s8)x, py = (s8)y;
        if (r == 0) ClampStick(&px, &py, ClampRegion.maxStick, ClampRegion.xyStick, ClampRegion.minStick);
        else ClampStick(&px, &py, ClampRegion.maxSubstick, ClampRegion.xySubstick, ClampRegion.minSubstick);
        snprintf(b, sizeof b, "%d %d %d %d %d", r, x, y, px, py); line(b);
      }
  end("clamp_stick");
  begin(0);
  for (int r = 0; r < 2; ++r)
    for (int x = -128; x < 128; ++x)
      for (int y = -128; y < 128; ++y) {
        s8 px = (s8)x, py = (s8)y;
        if (r == 0) ClampCircle(&px, &py, ClampRegion.radStick, ClampRegion.minStick);
        else ClampCircle(&px, &py, ClampRegion.radSubstick, ClampRegion.minSubstick);
        snprintf(b, sizeof b, "%d %d %d %d %d", r, x, y, px, py); line(b);
      }
  end("clamp_circle");
  begin(0);
  for (int t = 0; t < 256; ++t) {
    u8 v = (u8)t; ClampTrigger(&v, ClampRegion.minTrigger, ClampRegion.maxTrigger);
    snprintf(b, sizeof b, "%d %u", t, v); line(b);
  }
  end("clamp_trigger");
  // decode: a stream of LCG reports; port types biased to connected; recal every 97th frame
  begin(8);
  for (int f = 0; f < 4000; ++f) {
    unsigned char snap[37];
    snap[0] = 0x21;
    for (int i = 1; i < 37; ++i) snap[i] = (unsigned char)next();
    for (int c = 0; c < 4; ++c) {
      uint32_t k = next() % 8;
      snap[1 + c * 9] = (unsigned char)((k < 3 ? 1 : k < 5 ? 2 : k == 5 ? 0 : (next() % 16)) << 4 | (next() & 15));
      if (next() % 4) { snap[2 + c * 9] &= (unsigned char)next(); snap[3 + c * 9] &= 0x0F; }
    }
    int recal = (f % 97) == 0;
    PADStatus st[4];
    memset(st, 0, sizeof st);
    for (int c = 0; c < 4; ++c) st[c].err = -1;
    int any = oracle_decode(snap, st, recal);
    std::string s = std::to_string(f) + " " + std::to_string(any);
    for (int c = 0; c < 4; ++c) s += " | " + st_str(st[c]);
    line(s);
  }
  end("decode");
  return 0;
}
