#!/usr/bin/env python3
"""Round 14 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round14.py

Round 14 (night 3, round 6) is hand-ported only (src/itkinds14.rs): functions whose callees are
all ported here (it_80272CC0, it_80272860, it_802AC5D8, swapVelocity,
lbVector_NormalizeXY, get_min_life, it_802B3368, it_80275594, pika_scale, it_8026B3A8, it_80275444,
it_80272828) or that call nothing.
This writes tests/c_oracle/round14_bodies.h, the verbatim decomp C bodies of the HAND list,
#included by round14.c, each source file's group preceded by that file's own verbatim
`#define GET_ATTRS` (when it has one). Never edit the output by hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """it_80285314 get_bone_by_id it_80279768 it_80279720 it_80279744 it_8028B08C
itYoshistar_UnkMotion0_Phys it_80291D38 it_802AB9C0 likelikeVelocity itSamusbomb_UnkMotion2_Phys
itNesspkfirepillar_Logic24_DmgReceived it_802B22B8_inline itPikachutjoltair_UnkMotion0_Anim_inline
itPikachuthunder_UnkMotion2_ScaleCall fn_80280974_inline it_8026C47C it_802D14D0 it_802F1340
it_802D472C_inline fn_802A33A0_GetFighter get_attrs itDosei_GetJObj jobj_child it_802C248C_joint24
it_802C248C_joint28""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

GA = re.compile(r'^#define GET_ATTRS\(.*?[^\\]\n', re.M | re.S)
b = ["/* @generated by gen_round14.py: verbatim copies of the decomp C bodies ported in round 13",
     " * (src/itkinds14.rs), grouped by source file. #included by round14.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        b.append("#undef GET_ATTRS")
        m = GA.search(open(path, encoding='utf-8').read())
        if m:
            b.append(m.group(0).rstrip())
        lastp = path
    b.append(body.strip())
    b.append('')
b.append("#undef GET_ATTRS")
(OR / 'round14_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')
