#!/usr/bin/env python3
"""Split the MotionState tables (the single-file text gen_retail_ms.py builds) into the crates melee_link_ms<N>.

Build speed (notes/buildspeed.md, crate split round 2): retail_ms.rs was one 12.9k-line crate whose install_ms() was a
single 12k-line function, so LLVM compiled it in one codegen unit (85 s on the critical path). Here the per-file modules
are cut into NPARTS contiguous groups of about equal size, one crate each, and every module's rows go in their own
#[inline(never)] install function. The rows, their order and the statics are unchanged: install_ms() calls the parts in
the original order. melee_link_retail/src/retail_ms.rs re-exports every module under its old path.
  split_retail_ms.py [monolithic.rs]   (default: the current retail_ms.rs, when it is still the single-file form)
gen_retail_ms.py calls split() with its text directly.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import gen_link as g

NPARTS = 4
CHUNK = 600  # install lines per function: LLVM compiles each function in one codegen unit
HDR = '// @generated by tools/rust-port/link/gen_retail_ms.py (split by split_retail_ms.py). Do not edit.'
ALLOW = '#![allow(non_snake_case, non_upper_case_globals, unused_unsafe, unused_variables, unused_imports, clippy::all)]'
MS_RS = os.path.join(g.RUST, 'melee_link_retail', 'src', 'retail_ms.rs')
CARGO = '''# @generated by tools/rust-port/link/split_retail_ms.py. Do not edit.
[package]
name = "melee_link_ms{n}"
version.workspace = true
edition.workspace = true
license.workspace = true
publish.workspace = true

[dependencies]
melee_types.workspace = true
melee_fighter.workspace = true
melee_chara.workspace = true
melee_link_abi.workspace = true
'''


def parse(text):
    """-> [(module name, module text, [install lines])] in file order."""
    i = text.index('/// Fill the callbacks of every MotionState table')
    defs, inst = text[:i], text[i:]
    mods = []
    for m in re.finditer(r'(?ms)^pub mod (\w+) \{\n.*?^\}\n', defs):
        mods.append([m.group(1), m.group(0), []])
    body = inst.split('    unsafe {\n', 1)[1].rsplit('    }\n}', 1)[0]
    idx = {m[0]: m for m in mods}
    cur = None
    for ln in body.split('\n'):
        if not ln:
            continue
        mm = re.match(r'        let t = &raw mut (\w+)::', ln)
        if mm:
            cur = idx[mm.group(1)]
        cur[2].append(ln)
    return mods


def split(text, nparts=NPARTS):
    mods = parse(text)
    sizes = [m[1].count('\n') + len(m[2]) for m in mods]
    total, parts, acc, cur = sum(sizes), [], 0, []
    for m, s in zip(mods, sizes):
        # close the part before a module that would carry it past its share (keeps a big module, ftmotionstates, alone)
        if cur and len(parts) < nparts - 1 and acc + s > total * (len(parts) + 1) / nparts + s / 2:
            parts.append(cur)
            cur = []
        cur.append(m)
        acc += s
    if cur:
        parts.append(cur)
    for n, part in enumerate(parts):
        d = os.path.join(g.RUST, f'melee_link_ms{n}')
        os.makedirs(os.path.join(d, 'src'), exist_ok=True)
        open(os.path.join(d, 'Cargo.toml'), 'w', newline='\n').write(CARGO.format(n=n))
        out = [HDR, ALLOW, 'pub(crate) use melee_link_abi::{cabi, cast};', 'use melee_types::*;', '']
        for name, mtext, _ in part:
            out.append(mtext)
        out.append(f'/// The MotionState rows of {", ".join(m[0] for m in part)} (part {n} of install_ms). Call once at boot.')
        fns = []  # (fn name, lines): a module's rows in chunks of about CHUNK lines, cut only where a row starts
        for name, _, lines in part:
            chunks, cur, let = [], [], None
            for ln in lines:
                if ln.startswith('        let t = '):
                    let = ln
                elif len(cur) >= CHUNK and re.match(r'        \(\*t\)\[\d+\]\.anim_id = ', ln):
                    chunks.append(cur)
                    cur = [let]
                cur.append(ln)
            chunks.append(cur)
            for c, ch in enumerate(chunks):
                fns.append((f'install_{name}' + (f'_{c}' if len(chunks) > 1 else ''), ch))
        out.append('pub fn install() {')
        for fn, _ in fns:
            out.append(f'    {fn}();')
        out.append('}')
        for fn, lines in fns:
            out += ['', '#[inline(never)]', f'fn {fn}() {{', '    unsafe {'] + lines + ['    }', '}']
        out.append('')
        open(os.path.join(d, 'src', 'lib.rs'), 'w', newline='\n').write('\n'.join(out))
    re_ = [HDR, '//! The MotionState tables live in the crates melee_link_ms<N> (built in parallel); this file keeps their old paths.', '']
    for n, part in enumerate(parts):
        re_.append(f'pub use melee_link_ms{n}::{{{", ".join(m[0] for m in part)}}};')
    re_ += ['', '/// Fill the callbacks of every MotionState table (the C static initialisers). Call once at boot.',
            'pub fn install_ms() {'] + [f'    melee_link_ms{n}::install();' for n in range(len(parts))] + ['}', '']
    open(MS_RS, 'w', newline='\n').write('\n'.join(re_))
    print(f'retail_ms split: {len(parts)} parts, ' + ', '.join(f'p{n} {sum(m[1].count(chr(10)) + len(m[2]) for m in p)} lines' for n, p in enumerate(parts)))
    return len(parts)


if __name__ == '__main__':
    src = sys.argv[1] if len(sys.argv) > 1 else MS_RS
    split(open(src, encoding='utf8').read())
