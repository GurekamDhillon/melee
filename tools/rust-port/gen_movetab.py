#!/usr/bin/env python3
"""Generates rust/melee/src/movetab.rs: `MotionState.move_id` (FtMoveId, the table's x8 byte) of every
motion state: the common table (ftmotionstates.c, ids 0..340) and each kind's own table (ids 341..).
Source of truth is the C tables; run from the repo root: python tools/rust-port/gen_movetab.py"""
import re, os, glob, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
fwd = open(os.path.join(root, 'src/melee/ft/forward.h'), encoding='utf-8').read()
m = re.search(r'typedef enum FtMoveId \{(.*?)\} FtMoveId;', fwd, re.S)
ids = {}
n = 0
for line in m.group(1).split('\n'):
    line = line.split('//')[0].strip().rstrip(',')
    if not line:
        continue
    if '=' in line:
        name, v = [s.strip() for s in line.split('=')]
        n = int(v, 0)
    else:
        name = line
    ids[name] = n
    n += 1

def table(path, sym_re):
    src = open(path, encoding='utf-8').read()
    m = re.search(sym_re + r'\[[^\]]*\]\s*=\s*\{', src)
    if not m:
        return None
    i = m.end()
    depth = 1
    ents = []
    cur = None
    # walk top-level entries
    j = i
    start = None
    while depth > 0:
        c = src[j]
        if c == '{':
            depth += 1
            if depth == 2:
                start = j
        elif c == '}':
            depth -= 1
            if depth == 1:
                ents.append(src[start:j + 1])
        j += 1
    out = []
    for e in ents:
        mm = re.search(r'(FtMoveId_\w+)\s*<<\s*24', e)
        if mm:
            out.append(ids[mm.group(1)])
        else:
            body = re.sub(r'//[^'+chr(92)+'n]*', '', e).strip('{} '+chr(92)+'n')
            fields = [f.strip() for f in body.split(',')]
            if not re.fullmatch(r'0[xX][0-9a-fA-F]+', fields[2]):
                raise SystemExit('no move id in entry: ' + e[:200])
            out.append((int(fields[2], 16) >> 24) & 0xFF)
    return out

kinds = {
    'ftMario': 'Mario', 'ftFox': 'Fox', 'ftCaptain': 'Captain', 'ftDonkey': 'Donkey', 'ftKirby': 'Kirby',
    'ftKoopa': 'Koopa', 'ftLink': 'Link', 'ftSeak': 'Seak', 'ftNess': 'Ness', 'ftPeach': 'Peach',
    'ftPopo': 'Popo', 'ftNana': 'Nana', 'ftPikachu': 'Pikachu', 'ftSamus': 'Samus', 'ftYoshi': 'Yoshi',
    'ftPurin': 'Purin', 'ftMewtwo': 'Mewtwo', 'ftLuigi': 'Luigi', 'ftMars': 'Mars', 'ftZelda': 'Zelda',
    'ftCLink': 'CLink', 'ftDrMario': 'DrMario', 'ftFalco': 'Falco', 'ftPichu': 'Pichu',
    'ftGameWatch': 'GameWatch', 'ftGanon': 'Ganon', 'ftEmblem': 'Emblem', 'ftMasterHand': 'MasterH',
    'ftCrazyHand': 'CrezyH', 'ftGigaKoopa': 'GKoops', 'ftSandbag': 'Sandbag',
}
common = table(os.path.join(root, 'src/melee/ft/ftmotionstates.c'), r'MotionState\s+ftData_MotionStateList')
out = ['//! GENERATED by tools/rust-port/gen_movetab.py from the C motion state tables. Do not edit.',
       '//! `MotionState.move_id` (`FtMoveId`) of motion state `msid` (`Fighter_ChangeMotionState` ->',
       '//! `ft_800890D0(fp, move_id)`).', '']
out.append('pub const COMMON_COUNT: i32 = %d;' % len(common))
out.append('static COMMON: [u8; %d] = [%s];' % (len(common), ','.join(map(str, common))))
arms = []
for d, k in sorted(kinds.items()):
    p = glob.glob(os.path.join(root, 'src/melee/ft/kinds', d, (d.lower() if d != 'ftGigaKoopa' else 'ftgkoopa') + '.c'))
    if not p:
        print('skip', d, file=sys.stderr)
        continue
    t = table(p[0], r'MotionState\s+\w+_Init_MotionStateTable')
    if t is None:
        print('no table', d, file=sys.stderr)
        continue
    out.append('static T_%s: [u8; %d] = [%s];' % (k.upper(), len(t), ','.join(map(str, t))))
    arms.append('        melee_types::Ft_Kind_%s => &T_%s,' % (k, k.upper()))
out.append('''
/// The move id of motion state `msid` of fighter kind `kind` (1 = `FtMoveId_Default` when unknown).
pub fn move_id(kind: u32, msid: i32) -> u32 {
    if msid < 0 {
        return 1;
    }
    if msid < COMMON_COUNT {
        return COMMON[msid as usize] as u32;
    }
    let t: &[u8] = match kind {''')
out += arms
out.append('''        _ => return 1,
    };
    t.get((msid - COMMON_COUNT) as usize).map_or(1, |&v| v as u32)
}''')
open(os.path.join(root, 'rust/melee/src/movetab.rs'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('common', len(common))
