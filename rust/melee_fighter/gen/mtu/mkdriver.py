def main():
    spec = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    stem = spec["stem"]
    pkc, pkrs = pk_lines()
    ops = spec["ops"]
    c_cases = "\n".join(f"                case {i}: {c}; break;" for i, (c, r) in enumerate(ops))
    rs_cases = "\n".join(f"                    {i} => {{ {r} }}" for i, (c, r) in enumerate(ops))
    sub = {
        "@CSRC@": spec["csrc"], "@RMOD@": spec["rmod"], "@STEM@": stem, "@RFILE@": spec.get("rfile", stem),
        "@C_INCLUDES@": "\n".join(spec.get("c_includes", [])), "@C_HEAD@": spec.get("c_head", ""), "@C_PRE@": spec.get("c_pre", ""),
        "@C_WORLD@": spec.get("c_world", ""), "@C_HASH@": spec.get("c_hash", ""), "@PK_C@": pkc,
        "@NOPS@": str(len(ops)), "@CASES@": str(spec.get("cases", 500)), "@C_CASES@": c_cases, "@RS_CASES@": rs_cases,
        "@RS_HEAD@": spec.get("rs_head", ""), "@RS_HOOKS@": spec.get("rs_hooks", ""), "@RS_WORLD@": spec.get("rs_world", ""),
        "@RS_HASH@": spec.get("rs_hash", ""), "@PK_RS@": pkrs,
        "@POOLS@": ("," + spec["fill_pools"]) if spec.get("fill_pools") else "",
        "@FILLT@": ("," + spec["fill_types"]) if spec.get("fill_types") else "",
        "@STUBS@": spec.get("stubs", ""),
    }
    for name, tmpl, path in (
        ("c", C_TMPL, FD / f"gen/cref/tu/{stem}_ops.c"),
        ("rs", RS_TMPL, FD / f"tests/tu_{stem}_vs_c.rs"),
        ("sh", SH_TMPL, FD / f"gen/mtu/regen_{stem}.sh"),
    ):
        t = tmpl
        for k, v in sub.items():
            t = t.replace(k, v)
        if name == "c" and "@" in t.replace("@CSRC", ""):
            pass
        path.write_text(t, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
