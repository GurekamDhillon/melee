#!/usr/bin/env bash
# Regenerate src/pure_ref.rs from the C reference (native clang, no FMA contraction).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="${TMPDIR:-/tmp}/melee_chara_ref.exe"
CLANG="${CLANG:-/c/Program Files/LLVM/bin/clang}"
"$CLANG" -O2 -ffp-contract=off -fno-fast-math -w "$here/ref_pure.c" -o "$out"
{ echo "// @generated by rust/melee_chara/gen/run_ref.sh from gen/ref_pure.c (C, clang -O2 -ffp-contract=off)."
  "$out"; } > "$here/../src/pure_ref.rs"
echo "wrote $here/../src/pure_ref.rs"
