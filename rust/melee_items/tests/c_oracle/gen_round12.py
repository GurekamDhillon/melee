#!/usr/bin/env python3
"""Round 12 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round12.py

Round 12 (night 3, round 4) is hand-ported only (src/itkinds12.rs): functions whose only unported
callees are ported (it_80272CC0, it_80277040) or native elsewhere in the workspace (MSL sqrtf /
sqrtf_accurate in melee_runtime::gekko). This writes tests/c_oracle/round12_bodies.h,
the verbatim decomp C bodies of the HAND list, #included by round12.c. Never edit the output by
hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """it_8026B1D4 it_8026B7D8 it_8026B7E0 it_8026C1D4 it_8026C258 Item_8026784C it_8026F9A0
it_80272C90 it_802746F8 it_80274ED8 it_80274EE8 it_80274F28 it_80277544 it_802775F0
it_8027B070""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

b = ["/* @generated by gen_round12.py: verbatim copies of the decomp C bodies ported in round 12",
     " * (src/itkinds12.rs), grouped by source file. #included by round12.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        lastp = path
    b.append(body.strip())
    b.append('')
(OR / 'round12_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')
