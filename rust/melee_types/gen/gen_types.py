def write_probe():
    """Regenerate gen/all_types.c: group 0's headers plus every header the fighter (g3),
    character (g4) and item/trophy/vi (g5) crates need, so ONE generator covers all of them."""
    import glob
    os.chdir(ROOT)
    def g(pat, excl_static=True):
        return sorted(f.replace("\\", "/")[4:] for f in glob.glob(pat, recursive=True)
                      if not (excl_static and f.endswith(".static.h")) or "baselib" in f)
    base = g("src/sysdolphin/baselib/*.h", False)
    fwd = [f"melee/{m}/forward.h" for m in "cm ef ft gm gr if it lb mn mp pl sc ty vi".split()]
    tys = [f"melee/{m}/types.h" for m in "cm ef ft gm gr if it lb mn mp pl sc ty vi".split()]
    ft = g("src/melee/ft/*.h") + g("src/melee/ft/kinds/**/*.h") + g("src/melee/pl/*.h")
    it = g("src/melee/it/**/*.h") + g("src/melee/ty/**/*.h") + g("src/melee/vi/**/*.h")
    # Single headers whose records other groups' TU ports need (appended, never removed).
    extra = ["melee/lb/lbanim.h", "melee/gm/gmresultplayer.static.h", "melee/gm/gmfrontend_items.h", "melee/gm/gmtoulib.static.h"]
    seen, lines = set(), []
    for h in base + fwd + tys + ft + it + extra:
        if h not in seen:
            seen.add(h); lines.append(f"#include <{h}>")
    nl = chr(10)
    hdr = ("/* Layout probe for melee_types (generated by gen_types.py write_probe): group 0 + fighter," + nl +
           " * characters, items/trophies/vi headers, so every record they define gets laid out. */" + nl)
    # TU-private records also belong to the one type generator. Extract the exact
    # declaration rather than maintaining a second description of its fields.
    lab_source = (ROOT / "pc/geno/geno_lab_mode.c").read_text(encoding="utf-8")
    fly_cursor = re.search(r"typedef struct \{\s*Fighter\* fighter;.*?\} FlyCursor;", lab_source, re.S)
    assert fly_cursor, "geno_lab_mode.c FlyCursor declaration moved"
    SRC.write_text(hdr + nl.join(lines) + nl + fly_cursor.group(0) + nl, newline=nl)
    return len(lines)

