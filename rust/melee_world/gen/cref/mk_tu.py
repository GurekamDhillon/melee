#!/usr/bin/env python3
"""Writes the two mirrored halves of one TU oracle from drivers.py:

  python rust/melee_world/gen/cref/mk_tu.py <stem>      (from the worktree root)

  gen/cref/tu/<stem>.c          the C driver (the game's .c included verbatim, see gen_tu.py)
  tests/tu_<stem>.rs            the Rust test: same draws, same state, same hashing

A driver is a dict (drivers.py):
  state   [(name, type, count)]  state records: declared, zeroed, filled (fill_<type>), hashed after each op
  decl_c / decl_r                extra declarations (C after the TU include / Rust statics)
  regs    [(C ptr expr, C size expr, Rust ptr expr, Rust size expr)]  extra pointer-id regions
                                  (the state records are registered first, in order)
  setup_c / setup_r              statements after the state is zeroed and filled (links, pools)
  post_c / post_r                extra hash statements after each op (TU statics, pools)
  cases                          cases per op (default 200)
  ops     [dict(name, c, r, usel, pre_c, pre_r)]  one per function / datum under test:
          c / r are the statements that call it ('ret' is the u32 result slot; both sides share the
          fv() draws, which the pre_ statements make so a call never holds two draws)
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))


def build(stem):
    from drivers import DRV
    from specs import SPECS
    d = DRV[stem]
    spec = SPECS[stem]
    ops = d["ops"]
    n = d.get("cases", 200)
    st = d.get("state", [])
    unions = spec.get("unions", {})
    # ---- C
    c = [f"/* TU: {spec['src']} */",
         "/* C oracle for src/tu/%s.rs: the whole TU included verbatim; every callee out of it is a" % stem,
         " * recording stub. Each line: op case ret state-hash trace-hash. (generated by mk_tu.py from drivers.py) */",
         "#include TU_SRC", '#include "mtu_common.h"']
    ctys = {nm: ty for nm, ty, cnt in st}
    st = [(nm, ty.replace("struct ", ""), cnt) for nm, ty, cnt in st]
    for nm, ty, cnt in st:
        cn = ctys[nm]
        c.append(f"static {cn} {nm}[{cnt}];" if cnt > 1 else f"static {cn} {nm};")
    c.append(d.get("decl_c", ""))
    c.append(f'#include "{stem}_gen.h"')
    c.append(d.get("helpers_c", ""))
    c.append("static const int OPUSEL[%d] = { %s };" % (len(ops), ", ".join(str(o.get("usel", 0)) for o in ops)))
    c.append("static const int NC[%d] = { %s };" % (len(ops), ", ".join(str(o.get("cases", n)) for o in ops)))
    c.append("int main(void)\n{\n    int op, k, i, j;\n    (void) j;")
    for nm, ty, cnt in st:
        c.append(f"    preg({'' if cnt > 1 else '&'}{nm}, sizeof {nm});")
    for ce, cs, re_, rs in d.get("regs", []):
        c.append(f"    preg({ce}, {cs});")
    c.append("    freg_all();")
    c.append(f"    for (op = 0; op < {len(ops)}; op++) {{\n        for (k = 0; k < NC[op]; k++) {{\n            u32 ret = 0;")
    c.append("            tu_case(op, k);\n            USEL = OPUSEL[op];")
    for nm, ty, cnt in st:
        if cnt > 1:
            c.append(f"            zero({nm}, sizeof {nm}); for (i = 0; i < {cnt}; i++) fill_{ty}(&{nm}[i]);")
        else:
            c.append(f"            zero(&{nm}, sizeof {nm}); fill_{ty}(&{nm});")
    c.append(d.get("setup_c", ""))
    c.append("            switch (op) {")
    for i, o in enumerate(ops):
        c.append(f"            case {i}: {{ {o.get('pre_c', '')} {o['c']} break; }}")
    c.append("            }")
    for nm, ty, cnt in st:
        if cnt > 1:
            c.append(f"            for (i = 0; i < {cnt}; i++) hash_{ty}(&{nm}[i]);")
        else:
            c.append(f"            hash_{ty}(&{nm});")
    c.append(d.get("post_c", ""))
    c.append('            printf("%d %d %08X %08X %08X\\n", op, k, ret, H, TR);\n        }\n    }\n    return 0;\n}')
    (HERE / "tu" / f"{stem}.c").write_text("\n".join(c) + "\n", encoding="utf-8", newline="\n")
    # ---- Rust
    r = [f"//! tu::{stem} vs the C (gen/cref/tu/{stem}.c: the whole TU, shipping contraction;",
         f"//! regenerate with `python rust/melee_world/gen/cref/run_tu.py {stem}`). Generated by mk_tu.py from drivers.py.",
         "#![allow(static_mut_refs, non_snake_case, unused_mut, unused_variables, unused_unsafe, unused_assignments, unused_imports)]",
         "mod mtu_harness;", "use core::ffi::c_void;", "use melee_types::*;",
         f"use melee_world::tu::{stem} as m;", "use mtu_harness::*;",
         f'#[path = "mtu/{stem}_gen.rs"]', "mod g;", ""]
    for nm, ty, cnt in st:
        r.append(f"static mut {nm}: [{ty}; {cnt}] = unsafe {{ core::mem::zeroed() }};" if cnt > 1 else
                 f"static mut {nm}: {ty} = unsafe {{ core::mem::zeroed() }};")
    r.append(d.get("decl_r", ""))
    r.append("const OPUSEL: [i32; %d] = [%s];" % (len(ops), ", ".join(str(o.get("usel", 0)) for o in ops)))
    r.append("const NC: [u32; %d] = [%s];" % (len(ops), ", ".join(str(o.get("cases", n)) for o in ops)))
    r.append(f"#[test]\nfn {stem}_matches_c() {{\n    unsafe {{\n        g::install();")
    for nm, ty, cnt in st:
        r.append(f"        preg(&raw const {nm}, core::mem::size_of_val(&{nm}));")
    for ce, cs, re_, rs in d.get("regs", []):
        r.append(f"        preg({re_}, {rs});")
    r.append("        g::freg_all();")
    r.append(f'        let mut c = Check::new(include_str!("data/mtu_{stem}.txt"));')
    r.append(f"        for op in 0..{len(ops)}u32 {{\n            for k in 0..NC[op as usize] {{\n                let mut ret = 0u32;")
    r.append("                case(op, k);\n                USEL = OPUSEL[op as usize];")
    for nm, ty, cnt in st:
        r.append(f"                {nm} = core::mem::zeroed(); for i in 0..{cnt} {{ g::fill_{ty}(&mut {nm}[i]); }}" if cnt > 1 else
                 f"                {nm} = core::mem::zeroed(); g::fill_{ty}(&mut {nm});")
    r.append(d.get("setup_r", ""))
    r.append("                match op {")
    for i, o in enumerate(ops):
        r.append(f"                    {i} => {{ {o.get('pre_r', '')} {o['r']} }}")
    r.append("                    _ => unreachable!(),\n                }")
    for nm, ty, cnt in st:
        r.append(f"                for i in 0..{cnt} {{ g::hash_{ty}(&{nm}[i]); }}" if cnt > 1 else f"                g::hash_{ty}(&{nm});")
    r.append(d.get("post_r", ""))
    r.append(f"                c.line(op, k, ret);\n            }}\n        }}\n        assert_eq!(c.done(), {sum(o.get('cases', n) for o in ops)});\n    }}\n}}")
    (ROOT / "rust/melee_world/tests" / f"tu_{stem}.rs").write_text("\n".join(r) + "\n", encoding="utf-8", newline="\n")
    print(f"mk_tu: {stem}: {len(ops)} ops x {n} cases")


if __name__ == "__main__":
    for s in sys.argv[1:]:
        build(s)
