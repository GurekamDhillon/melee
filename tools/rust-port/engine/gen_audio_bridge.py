#!/usr/bin/env python3
"""Generate rust/melee/src/engine_audio_gen.rs: point every TU's `ext::hook::lbAudioAx_*` at melee/src/engine_audio.rs.

The (TU, hook) pairs come from the generated link table and the engine's fallback seams; the parameter types of each bridge
function are parsed from engine_audio.rs, so adding a bridge function is enough (rerun this script)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[3] / 'rust'
bridge = (root / 'melee/src/engine_audio.rs').read_text()
fns = {}
for m in re.finditer(r'^pub fn (ax_[0-9A-F]{8})\(([^)]*)\)(?:\s*->\s*([\w\*\s]+?))?\s*\{', bridge, re.M):
    params = [p.split(':', 1)[1].strip() for p in m.group(2).split(',') if p.strip()]
    fns[m.group(1)] = (params, m.group(3))
text = (root / 'melee_engine/src/seams_gen.rs').read_text() + (root / 'melee_link/src/gen_table.rs').read_text()
hooks = set(re.findall(r'(melee_\w+::tu::[\w:]+::ext::hook)::(lbAudioAx_[0-9A-F]{8})', text))
# the fighter TUs' statics are spelled `ext::LBAUDIOAX_XXXXXXXX` (and `melee_fighter::hooks::LBAUDIOAX_XXXXXXXX`, set by hand in install)
hooks_up = set(re.findall(r'(melee_\w+::tu::[\w:]+::ext)::(LBAUDIOAX_[0-9A-F]{8})', text))
# TUs whose audio hooks neither table names: their `ext` default reaches melee_runtime's own lbaudio_ax / axdriver / synth, a sound
# stack nobody mixes (the sound plays silent). Scan the TU sources for every declared lbAudioAx hook. The menus (mn*, the title) are
# left to the retail-menu flow, which owns when the sound library is on there.
MENU = re.compile(r'^(mn|gmtitle$|gmtou_|gm_17c0$|hsd$)')  # gmtou_*, gm_17c0, hsd: their ext macros make no hook statics for these
for crate in sorted(root.glob('melee_*/src/tu')):
    for f in sorted(crate.glob('*.rs')):
        if MENU.match(f.stem):
            continue
        src = f.read_text(encoding='utf-8', errors='replace')
        if 'mod ext' not in src or 'hook' not in src:  # an ext! block without settable hooks (todo_fns!, gmtou_ext!) cannot be bridged
            continue
        # declarations inside the ext! block: `fn name(a: T) -> R => default;`, `name(a: T) -> R = default;`, `fn name();` (not calls)
        for m in re.finditer(r'^\s*(fn\s+)?(lbAudioAx_[0-9A-F]{8})\s*\(([^)]*)\)\s*(->\s*[^=;{]+?)?\s*(=>|=|;)', src, re.M):
            if m.group(1) or ':' in m.group(3) or m.group(4) or m.group(5) != ';':
                if not m.group(1) and m.group(5) == ';' and ':' not in m.group(3):
                    continue
                if re.search(rf'static mut H_{m.group(2)}', src):
                    continue  # the extern "C" spelling, below
                hooks.add((f'{crate.parent.parent.name}::tu::{f.stem}::ext::hook', m.group(2)))
        # hand-written ext modules: `pub static mut LBAUDIOAX_XXXXXXXX` (melee_chara's master/crazy hand shards)
        for name in re.findall(r'pub static mut (LBAUDIOAX_[0-9A-F]{8})', src):
            hooks_up.add((f'{crate.parent.parent.name}::tu::{f.stem}::ext', name))
# the extern "C" hook spelling `ext::H_lbAudioAx_XXXXXXXX` (wrapped like melee_link's table does)
hooks_c = sorted(set(re.findall(r'(melee_\w+::tu::[\w:]+::ext)::H_(lbAudioAx_[0-9A-F]{8})', text)))
hooks_c = [(p_, n_) for p_, n_ in hooks_c if not MENU.match(p_.split('::')[-2])]
hooks = sorted(hooks)
PRIM = {'u8', 'u16', 'u32', 'i32', 'i8', 'f32', 'usize', 'u64'}
out = ['// @generated by tools/rust-port/engine/gen_audio_bridge.py. Do not edit.', '#![allow(non_snake_case, unused_unsafe, clippy::all)]', 'use melee_types::HSD_GObj;', '',
       "/// Point every TU's lbAudioAx hook at the sound bridge (after `melee_link::install` and the seams).", 'pub fn install_gen() {']
n = 0
for path, name in hooks:
    bn = 'ax_' + name[len('lbAudioAx_'):]
    if bn not in fns:
        continue
    params, ret = fns[bn]
    args = [f'a{i} as {t}' if (t in PRIM or t.startswith('*')) else f'a{i}' for i, t in enumerate(params)]
    ps = ', '.join(f'a{i}' for i in range(len(params)))
    call = f'crate::engine_audio::{bn}({", ".join(args)})'
    if ret:
        call = f'crate::engine_audio::cast({call})'
    out.append(f'    unsafe {{ {path}::{name} = Some(|{ps}| unsafe {{ {call} }}); }}')
    n += 1
for path, name in sorted(hooks_up):
    bname = 'ax_' + name[len('LBAUDIOAX_'):]
    if bname not in fns:
        continue
    params, ret = fns[bname]
    args = [f'a{i} as {t}' if (t in PRIM or t.startswith('*')) else f'a{i}' for i, t in enumerate(params)]
    ps = ', '.join(f'a{i}' for i in range(len(params)))
    call = f'crate::engine_audio::{bname}({", ".join(args)})'
    if ret:
        call = f'crate::engine_audio::cast({call})'
    else:
        call = f'{call}'
    out.append(f'    unsafe {{ {path}::{name} = Some(|{ps}| unsafe {{ {call} }}); }}')
    n += 1
for path, name in hooks_c:
    bn = 'ax_' + name[len('lbAudioAx_'):]
    if bn not in fns:
        continue
    params, ret = fns[bn]
    args = [f'a{i} as {t}' if (t in PRIM or t.startswith('*')) else f'a{i}' for i, t in enumerate(params)]
    ps = ', '.join(f'a{i}' for i in range(len(params)))
    call = f'crate::engine_audio::{bn}({", ".join(args)})'
    if ret:
        call = f'crate::engine_audio::cast({call})'
    out.append(f'    unsafe {{ {path}::H_{name} = Some(melee_link::cabi::c{len(params)}(|{ps}| unsafe {{ {call} }})); }}')
    n += 1
out.append('}')
(root / 'melee/src/engine_audio_gen.rs').write_text('\n'.join(out) + '\n')
print(f'{n} hooks bridged; unbridged: ' + ', '.join(sorted({h[1] for h in hooks if 'ax_' + h[1][len('lbAudioAx_'):] not in fns})))
