#!/usr/bin/env python3
"""Regenerate rust/melee/src/diff_layout.rs: the field tables `melee diff` names differences with.

For `Fighter` and every record reachable from it by value, one table of fields:
(name, GameCube offset, native offset, native size, kind). The GC offsets and the field order come
from melee_types' generated `GcDecode` impls (the single generator, rust/melee_types/gen); the
native offsets/sizes are `offset_of!` / `size_of` evaluated by rustc, so they cannot drift.
Bitfield descriptors (`GcField::bitfield`) are kept so a changed `bf_*` byte is reported as the
named bits that changed.

    python tools/rust-port/diff/gen_layout.py
"""
import re, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[3] / "rust"
SRC = (ROOT / "melee_types/src/gen.rs").read_text(encoding="utf8")
ROOTS = sys.argv[1:] or ["Fighter"]

# type -> (gc_bytes, [(field, type, gc_off)])
decls = {}
for m in re.finditer(r'impl GcDecode for (\w+) \{\n\s*const GC_BYTES: u32 = (0x[0-9A-Fa-f]+);(.*?)\n    \}\n\}', SRC, re.S):
    name, size, body = m.group(1), int(m.group(2), 16), m.group(3)
    fields = [(f.removeprefix("r#"), t, int(o, 16)) for f, t, o in
              re.findall(r'v\.(\w+(?:#\w+)?) = <(.*?) as GcDecode>::gc_decode\(d, at \+ (0x[0-9A-Fa-f]+)\);', body)]
    decls[name] = (size, fields)
unions = set(re.findall(r'pub union (\w+) \{', SRC))
alias = dict(re.findall(r'pub type (\w+) = (\w+);', SRC))
# bitfield descriptors per type: GcField::bitfield("name", gc_byte, size, bit, width, "ty")
bitf = {}
for m in re.finditer(r'impl GcLayout for (\w+) \{(.*?)\n\}', SRC, re.S):
    bs = re.findall(r'GcField::bitfield\("(\w+)", (0x[0-9A-Fa-f]+), (\d+), (\d+), (\d+),', m.group(2))
    if bs:
        bitf[m.group(1)] = [(n, int(o, 16), int(b), int(w)) for n, o, _s, b, w in bs]

PRIMS = {"u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64", "f32", "f64", "bool"}


def prim(t):
    seen = 0
    while t not in PRIMS and t in alias and seen < 10:
        t = alias[t]
        seen += 1
    return t if t in PRIMS else None


def kind(t, owner_tables):
    """Rust expression for the Kind of type text `t`."""
    t = t.strip()
    if t.startswith("*") or "fn(" in t or "fn (" in t or t.startswith("Option<") or t.startswith("unsafe extern"):
        return "Kind::Ptr"
    m = re.fullmatch(r'\[(.*); (\d+)\]', t)
    if m:
        e, n = m.group(1), int(m.group(2))
        if e in ("u8", "i8"):
            return "Kind::Blob"
        if e not in decls and prim(e) is None and not e.startswith("["):
            return "Kind::Blob"
        gs = elem_gc(e)
        if gs is None:
            return "Kind::Blob"
        return f"Kind::Arr({n}, {gs}, ::core::mem::size_of::<{e}>(), &{kind(e, owner_tables)})"
    p = prim(t)
    if p == "f32":
        return "Kind::F32"
    if p == "f64":
        return "Kind::Blob"
    if p:
        return f"Kind::Int({'true' if p[0] == 'i' else 'false'})"
    if t in decls and t not in unions:
        owner_tables.add(t)
        return f'Kind::Struct("{t}", &T_{t})'
    if t in unions:
        return "Kind::Union"
    return "Kind::Blob"


def elem_gc(e):
    p = prim(e)
    if p in ("u8", "i8", "bool"): return 1
    if p in ("u16", "i16"): return 2
    if p in ("u32", "i32", "f32"): return 4
    if p in ("u64", "i64", "f64"): return 8
    if e.startswith("*"): return 4
    if e in decls: return decls[e][0]
    m = re.fullmatch(r'\[(.*); (\d+)\]', e)
    if m:
        g = elem_gc(m.group(1))
        return None if g is None else g * int(m.group(2))
    return None


todo, done, out = list(ROOTS), set(), []
while todo:
    name = todo.pop()
    if name in done or name not in decls:
        continue
    done.add(name)
    size, fields = decls[name]
    rows = []
    sub = set()
    for i, (f, t, o) in enumerate(fields):
        k = kind(t, sub)
        rows.append(f'    F {{ name: "{f}", gc: {o:#x}, nat: ::core::mem::offset_of!({name}, {f}), size: ::core::mem::size_of::<{t}>(), kind: {k} }},')
    todo.extend(sorted(sub - done))
    bits = ", ".join(f'("{n}", {o:#x}, {b}, {w})' for n, o, b, w in bitf.get(name, []))
    out.append(f"pub static T_{name}: &[F] = &[\n" + "\n".join(rows) + "\n];\n"
               f"pub static B_{name}: &[(&str, u32, u32, u32)] = &[{bits}];\n")

hdr = ("//! Generated by tools/rust-port/diff/gen_layout.py: field tables (name, GC offset, native offset,\n"
       "//! size, kind) for `Fighter` and the records inside it, for `melee diff` (diff.rs).\n"
       "#![allow(non_upper_case_globals, unused_imports)]\n"
       "use melee_types::*;\n"
       "use core::ffi::c_void;\n"
       "use crate::diff::{F, Kind};\n\n")
tables = "pub fn bitfields(ty: &str) -> &'static [(&'static str, u32, u32, u32)] {\n    match ty {\n" + \
    "".join(f'        "{n}" => B_{n},\n' for n in sorted(done)) + "        _ => &[],\n    }\n}\n"
(ROOT / "melee/src/diff_layout.rs").write_text(hdr + "\n".join(out) + "\n" + tables, encoding="utf8")
print(len(done), "tables:", ", ".join(sorted(done)))
