pub unsafe fn mnOverlay_Frame() {
    melee_core::ct!("mnOverlay_Frame");
    mnOverlay_Reshow();

    // The run label shows only while the F9 panel is open.
    let label = if ext::Overlay_GetPanelOpen() != 0 { ext::Overlay_GetRunLabel() } else { null_mut() };
    mnOverlay_Line(mnOverlay_caption, label);
    mnOverlay_Line(mnOverlay_toast, ext::Overlay_GetToast());

    if mnOverlay_panel.is_null() {
        return;
    }
    if ext::Overlay_GetPanelOpen() == 0 {
        ext::DevText_HideText(mnOverlay_panel);
        ext::DevText_HideBackground(mnOverlay_panel);
        return;
    }
    ext::DevText_Erase(mnOverlay_panel);
    let mut rows = ext::Overlay_GetPanelLineCount();
    if rows > OVERLAY_PANEL_ROWS as i32 {
        rows = OVERLAY_PANEL_ROWS as i32;
    }
    let mut i: i32 = 0;
    while i < rows {
        let line = ext::Overlay_GetPanelLine(i);
        if line.is_null() {
            i += 1;
            continue;
        }
        ext::DevText_SetCursorXY(mnOverlay_panel, 0, i);
        let c = if ext::Overlay_GetPanelLineDim(i) != 0 { OVERLAY_COLOR_DIM } else { OVERLAY_COLOR_NORMAL };
        ext::DevText_StoreColorIndex(mnOverlay_panel, c);
        ext::DevText_Print(mnOverlay_panel, line);
        i += 1;
    }
    ext::DevText_StoreColorIndex(mnOverlay_panel, OVERLAY_COLOR_NORMAL);
    ext::DevText_ShowText(mnOverlay_panel);
    ext::DevText_ShowBackground(mnOverlay_panel);
}

