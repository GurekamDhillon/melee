"""Generate the inert GPU implementation used by the state/TEV oracle tests."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
source = (ROOT / "rust/melee_runtime/src/tu/state.rs").read_text()
trait = source.split("pub trait GxBackend {", 1)[1].split("\n}", 1)[0]
names = [
    "set_cull_mode", "set_blend_mode", "set_z_mode", "set_alpha_compare",
    "set_color_update", "set_alpha_update", "set_dst_alpha", "set_z_comp_loc",
    "set_dither", "set_num_chans", "set_chan_amb_color", "set_chan_mat_color",
    "set_chan_ctrl", "set_num_tex_gens", "set_num_tev_stages", "set_tev_order",
    "set_tev_op", "set_tev_swap_mode", "set_tev_color_in", "set_tev_alpha_in",
    "set_tev_color_op", "set_tev_alpha_op", "set_tev_kcolor_sel", "set_tev_kalpha_sel",
    "clear_vtx_desc", "set_line_width", "set_point_size", "set_tev_color_s10", "setup_lobj",
]
out = ["// Generated by oracle/gen_state_tev_backend.py.\n#![allow(unused_variables)]\n",
       "use melee_runtime::tu::state::*;\nuse melee_runtime::mtx::Mtx;\n",
       "#[derive(Default)] pub struct Trace { pub words: Vec<u32> }\nimpl GxBackend for Trace {\n"]
for match in re.finditer(r"    fn (\w+)\(([^\n]*?)\)(?:;| \{)", trait):
    name, args = match.groups()
    code = []
    if name in names:
        code.append(f"self.words.push({names.index(name) + 1});")
        for arg in args.split(", ")[1:]:
            key, ty = arg.split(": ")
            if ty in ("u32", "u8", "i32", "bool"):
                code.append(f"self.words.push({key} as u32);")
            elif ty == "f32":
                code.append(f"self.words.push({key}.to_bits());")
            elif ty == "Rgba":
                code.append(f"self.words.extend({key}.map(u32::from));")
            elif ty == "[i16; 4]":
                code.append(f"self.words.extend({key}.map(|v| v as i32 as u32));")
            elif ty == "&ActiveLight":
                code.append(f"self.words.push({key}.id);")
            else:
                raise RuntimeError((name, arg))
    out.append(f"    fn {name}({args}) {{ {' '.join(code)} }}\n")
out.append("}\n")
path = ROOT / "rust/melee_runtime/tests/state_tev_backend/mod.rs"
path.parent.mkdir(exist_ok=True)
path.write_text("".join(out), newline="\n")
