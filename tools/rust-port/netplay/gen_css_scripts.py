#!/usr/bin/env python3
"""Write the pad scripts of the --np-css netplay test (css_pair.sh): two matches picked on the retail character select.

np_css_host.txt (port 1, the host): Mario on the CSS, START, Battlefield on the SSS, the fight of np_fight.txt, START
through the results, back on the CSS START, the SSS (the cursor stays on Battlefield) A, the fight again, the results.
np_css_guest.txt (port 2, the guest): Fox, then the fight of np_fight2.txt, START through the results, twice.
Cursor moves were measured on screenshots (the hands' start positions differ per port). The scripts start on the CSS:
`--np-css` boots straight into VS mode."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else here


def fight(name, frames):
    segs = []
    for l in open(os.path.join(here, name)):
        l = l.split('#')[0].split()
        if len(l) >= 4:
            segs.append(l)
    segs = segs[1:]  # the boot wait
    res, n, i = [], 0, 0
    while n < frames:
        s = segs[i % len(segs)]
        k = min(int(s[0]), frames - n)
        # no START in a fight (it would pause)
        res.append(f"{k} {int(s[1], 16) & ~0x1000:04x} {s[2]} {s[3]}")
        n += k
        i += 1
    return res


def results():
    # START every second through the results (and its "NEW CHALLENGER"-free path back to the CSS)
    return ["3 1000 0 0", "57 0000 0 0"] * 20


MATCH = 4100

host = ["# --np-css host, port 1 (generated by gen_css_scripts.py)", "300 0000 0 0",
        "6 0000 127 0", "34 0000 0 127", "3 0100 0 0", "150 0000 0 0",
        "# START: the stage select", "3 1000 0 0", "120 0000 0 0",
        "# SSS: up-right to Battlefield, A", "3 0000 25 127", "15 0000 0 0", "3 0100 0 0"]
host += fight("np_fight.txt", MATCH) + results()
host += ["# the CSS again (the picks stay): START, A on the SSS", "60 0000 0 0", "3 1000 0 0", "120 0000 0 0", "15 0000 0 0", "3 0100 0 0"]
host += fight("np_fight.txt", MATCH) + results() + ["600 0000 0 0"]

guest = ["# --np-css guest, port 2 (generated by gen_css_scripts.py)", "300 0000 0 0",
         "6 0000 127 0", "29 0000 0 127", "12 0000 -127 0", "5 0000 0 0", "3 0100 0 0",
         "# wait through the host's START and stage pick", "400 0000 0 0"]
guest += fight("np_fight2.txt", MATCH - 140) + results()
guest += ["# the CSS and the SSS are the host's", "350 0000 0 0"]
guest += fight("np_fight2.txt", MATCH - 140) + results() + ["600 0000 0 0"]

for n, t in (("np_css_host.txt", host), ("np_css_guest.txt", guest)):
    with open(os.path.join(out, n), "w", newline="\n") as f:
        f.write("\n".join(t) + "\n")
print("written to", out)
