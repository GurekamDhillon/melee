#!/usr/bin/env python3
"""Generate rust/melee_engine/src/dat_types.rs from dat_symbols.tsv.

The table maps an archive public symbol to the melee_types record the C casts it to. Every type is checked
against rust/melee_types/src/gen.rs (must be a struct that implements GcDecode). `--coverage` scans the C tree
for symbol literals passed to lbArchive_LoadSymbols / HSD_ArchiveGetPublicAddress / lbArchive_* and lists the
ones the table does not cover (those hard-stop in the engine when the game asks for them).

  python tools/rust-port/engine/gen_dat_types.py            # write dat_types.rs
  python tools/rust-port/engine/gen_dat_types.py --check    # fail if dat_types.rs is stale
  python tools/rust-port/engine/gen_dat_types.py --coverage # symbol literals at C call sites without an entry
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
TSV = ROOT / "tools/rust-port/engine/dat_symbols.tsv"
OUT = ROOT / "rust/melee_engine/src/dat_types.rs"
GEN = ROOT / "rust/melee_types/src/gen.rs"


def load_rows():
    rows = []
    for ln, line in enumerate(TSV.read_text().split("\n"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) < 3 or f[0] not in ("sym", "prefix", "suffix"):
            sys.exit(f"{TSV}:{ln}: bad row {line!r}")
        rows.append((f[0], f[1], f[2], f[3] if len(f) > 3 else ""))
    return rows


def decodable_types():
    out = set()
    for f in (GEN, GEN.parent / "decode.rs"):  # decode.rs: the hand-written decoders (unions, HSD_Joint...)
        out |= set(re.findall(r"^impl GcDecode for (\w+) \{", f.read_text(encoding="utf-8", errors="replace"), re.M))
    return out


def render(rows):
    ok = decodable_types()
    types = sorted({r[2].lstrip("*").removesuffix("[]") for r in rows if r[2] != "raw"})
    for t in types:
        if t not in ok:
            sys.exit(f"dat_symbols.tsv: type {t} has no GcDecode impl in melee_types")
    o = ["//! GENERATED by tools/rust-port/engine/gen_dat_types.py from tools/rust-port/engine/dat_symbols.tsv. Do not edit.",
         "//! Archive public symbol -> the melee_types record the C casts it to (see the .tsv for the call-site evidence).",
         "#![allow(clippy::all)]",
         "use core::ffi::c_void;",
         "use melee_core::gcdecode::{GcDecode, GcDecoder};",
         "use melee_types::*;",
         "",
         "/// How a symbol's root is read.",
         "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
         "pub enum RootType {",
         "    /// A melee_types record (index into the match in `decode_root`).",
         "    Record(&'static str),",
         "    /// The symbol is a pointer to a record (C `T**`).",
         "    PtrTo(&'static str),",
         "    /// The symbol is an array of records running to the next public (or the end of the data section).",
         "    Array(&'static str),",
         "    /// Bytes read straight from the raw image (C `void*`).",
         "    Raw,",
         "}",
         "",
         "fn rt(t: &'static str) -> RootType {",
         "    if let Some(a) = t.strip_suffix(\"[]\") { return RootType::Array(a); }",
         "    match t.strip_prefix('*') { Some(r) => RootType::PtrTo(r), None => RootType::Record(t) }",
         "}",
         "",
         "/// The root type of public symbol `name`; None = not in the table (the engine stops and names the symbol).",
         "pub fn type_of(name: &str) -> Option<RootType> {"]
    for k, s, t, _ in rows:
        if k == "sym":
            v = "RootType::Raw" if t == "raw" else f'rt("{t}")'
            o.append(f'    if name == "{s}" {{ return Some({v}); }}')
    for k, s, t, _ in rows:
        if k == "prefix":
            v = "RootType::Raw" if t == "raw" else f'rt("{t}")'
            o.append(f'    if name.starts_with("{s}") {{ return Some({v}); }}')
    for k, s, t, _ in sorted((r for r in rows if r[0] == "suffix"), key=lambda r: -len(r[1])):
        v = "RootType::Raw" if t == "raw" else f'rt("{t}")'
        o.append(f'    if name.ends_with("{s}") {{ return Some({v}); }}')
    o += ["    None", "}", "",
          "/// Decode the record or pointer root at data offset `off` into the decoder's shared graph; the result is",
          "/// the native address of the root (a record pointer, or a pointer to the decoded pointer cell).",
          "pub fn decode_root(d: &mut GcDecoder<'_>, ty: RootType, off: u32, extent: u32) -> *mut c_void {",
          "    match ty {",
          "        RootType::Raw => core::ptr::null_mut(),",
          "        RootType::Record(n) => match n {"]
    for t in types:
        if not any(r[2] == t or r[2] == t + "[]" for r in rows):
            continue
        o.append(f'            "{t}" => d.object::<{t}>(off) as *mut c_void,')
    o += ['            _ => panic!("dat_types: no decoder for record {n}"),', "        },",
          "        RootType::Array(n) => match n {"]
    for t in sorted({r[2][:-2] for r in rows if r[2].endswith("[]")}):
        o.append(f'            "{t}" => d.array::<{t}>(off, (extent / <{t} as GcDecode>::GC_BYTES) as usize) as *mut c_void,')
    o += ['            _ => panic!("dat_types: no decoder for array of {n}"),', "        },",
          "        RootType::PtrTo(n) => match n {"]
    for t in sorted({r[2][1:] for r in rows if r[2].startswith("*")}):
        o.append(f'            "{t}" => d.object::<*mut {t}>(off) as *mut c_void,')
    o += ['            _ => panic!("dat_types: no decoder for pointer to {n}"),', "        },", "    }", "}", ""]
    # Record decoders are needed for pointer-less types too: the match above lists the record types only.
    return "\n".join(o)


def coverage(rows):
    syms = set()
    pat = re.compile(r'(?:lbArchive_LoadSymbols|lbArchive_8001\w+|lbArchive_800\w+|HSD_ArchiveGetPublicAddress)\s*\([^;]*?"([A-Za-z_][\w]*)"', re.S)
    for p in (ROOT / "src").rglob("*.c"):
        t = p.read_text(encoding="utf-8", errors="replace")
        for m in pat.finditer(t):
            s = m.group(1)
            if not s.endswith((".dat", ".usd")):
                syms.add(s)
    covered = lambda n: any((k == "sym" and n == s) or (k == "prefix" and n.startswith(s)) or (k == "suffix" and n.endswith(s)) for k, s, _, _ in rows)
    miss = sorted(s for s in syms if not covered(s))
    print(f"{len(syms)} symbol literals at C call sites, {len(syms) - len(miss)} covered, {len(miss)} not:")
    for s in miss:
        print("  " + s)


if __name__ == "__main__":
    rows = load_rows()
    if "--coverage" in sys.argv:
        coverage(rows)
    else:
        text = render(rows)
        if "--check" in sys.argv:
            if not OUT.exists() or OUT.read_text() != text:
                sys.exit("dat_types.rs is stale: run gen_dat_types.py")
        else:
            OUT.write_text(text, newline="\n")
            print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} rows")
