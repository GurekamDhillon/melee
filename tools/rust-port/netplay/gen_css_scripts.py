#!/usr/bin/env python3
"""Write the pad scripts of the --np-css netplay test (css_pair.sh): two matches picked on the retail character select.

np_css_host.txt (port 1, the host): Mario on the CSS, START, Battlefield on the SSS, the fight of np_fight.txt, START
through the results, back on the CSS START, the SSS (the cursor resets: up-right to Battlefield again) A, the fight again, the results.
np_css_guest.txt (port 2, the guest): Fox, then the fight of np_fight2.txt, START through the results, twice.
Cursor moves were measured on screenshots (the hands' start positions differ per port). The scripts start on the CSS:
`--np-css` boots straight into VS mode."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else here


def fight(name, frames):
    segs = []
    for l in open(os.path.join(here, name)):
        l = l.split('#')[0].split()
        if len(l) >= 4:
            segs.append(l)
    segs = segs[1:]  # the boot wait
    res, n, i = [], 0, 0
    while n < frames:
        s = segs[i % len(segs)]
        k = min(int(s[0]), frames - n)
        # no START in a fight (it would pause)
        res.append(f"{k} {int(s[1], 16) & ~0x1000:04x} {s[2]} {s[3]}")
        n += k
        i += 1
    return res


def results():
    # START every second through the results (and its "NEW CHALLENGER"-free path back to the CSS)
    return ["3 1000 0 0", "57 0000 0 0"] * 20


MATCH = 4100


def frames(lines):
    return sum(int(l.split()[0]) for l in lines if l and not l.startswith("#"))


# the guest's fight starts GUEST_LAG frames after the host's stage pick (the A on the SSS) of each match, whatever the
# stage's SSS moves take (open-loop scripts: a fixed wait let a long pick (dl, fod) drift the guest's fight inputs onto the
# SSS and the CSS, whose B went back to the CSS and the main menu); 131 = the Battlefield pick's measured margin

host = ["# --np-css host, port 1 (generated by gen_css_scripts.py)", "300 0000 0 0",
        "6 0000 127 0", "34 0000 0 127", "3 0100 0 0", "150 0000 0 0",
        "# START: the stage select", "3 1000 0 0", "120 0000 0 0",
        "# SSS: up-right to Battlefield, A", "3 0000 25 127", "15 0000 0 0", "3 0100 0 0"]
# NP_CSS_STAGES=fd,bf,ps,ys,dl,fod (cold-stage test, css_pair.sh NP_MATCHES): one match per stage, each picked with the
# SSS moves of play/fastpick_<stage>.txt (from the cursor's start, Random); default: Battlefield twice
stages = [x for x in os.environ.get("NP_CSS_STAGES", "").split(",") if x]


# the stage kinds the stage select hovers (the `sss hover` log lines; the same ids as `stage ext` at the match start)
SEEK = {"fd": 32, "bf": 31, "fod": 2, "dl": 28, "ys": 8, "ps": 3}


def sss_moves(st):
    # closed loop: from the cursor's start (the Random row, next to Battlefield) each row is swept right and
    # left until the stage is under the cursor (`seek` lines), and one tap up (a seek capped at one tap, so it does not
    # move off a found stage) goes to the next row. The fastpick moves alone missed Dreamland in netplay (ended on
    # Battlefield or a neighbour); a pick is checked by the `stage ext` log line, not by the hashes.
    t = SEEK[st]
    m = ["30 0000 0 0"]
    for _ in range(8):
        m += [f"seek {t} 100 0 1 12 360", f"seek {t} -100 0 1 12 720", f"seek {t} 0 100 3 30 30"]
    return m + ["10 0000 0 0", "3 0100 0 0"]


def sss_moves_open(st):
    # the fastpick script's moves after its last START (stage select) and wait, up to and including the A
    ls = [l.split('#')[0].strip() for l in open(os.path.join(here, "..", "play", f"fastpick_{st}.txt"))]
    ls = [l for l in ls if l]
    i = max(k for k, l in enumerate(ls) if l.split()[1] == "1000") + 2
    j = next(k for k in range(i, len(ls)) if ls[k].split()[1] == "0100")
    return ls[i:j] + ["3 0100 0 0"]


picks = []  # the frame each match's stage pick (A) ends on the host (only for the default scripts' timing note)
# scene kinds the `until` lines wait for (melee_platform::script, MELEE_PAD_SCRIPT): the engine's scene flow ids
CSS, VS = 8, 2  # the SSS moves keep their START-relative timing (the fastpick scripts were measured that way)


def results_until_css():
    # START once a second through the results and whatever follows them (an unlock notice: a scene of its own that only
    # some matches show), until the CSS: the open-loop START list ran out early or spilled onto the CSS and the SSS, so
    # the third pick drifted (wrong stage, then the guest's script ended a match early)
    return [f"until {CSS} 1000 3 60"]


if stages:
    host = host[:host.index("# START: the stage select")] + ["# START: the stage select", "3 1000 0 0", "120 0000 0 0",
                                                           f"# SSS: {stages[0]}"] + sss_moves(stages[0])
    for k, st in enumerate(stages):
        host += [f"until {VS}"] + fight("np_fight.txt", MATCH) + results_until_css()
        if k + 1 < len(stages):
            host += [f"# the CSS again: START, the SSS (cursor at Random), {stages[k + 1]}", "60 0000 0 0", "3 1000 0 0",
                     "120 0000 0 0"]
            host += sss_moves(stages[k + 1])
    host += ["600 0000 0 0"]
else:
    host += fight("np_fight.txt", MATCH) + results()
    host += ["# the CSS again (the picks stay): START; the SSS cursor is back at its start (Random), so up-right to Battlefield, A (START is dropped on the SSS: MELEE_NP_SCRIPT_NO_START, so a results press that opened it picks nothing)",
             "60 0000 0 0", "3 1000 0 0", "120 0000 0 0", "3 0000 25 127", "60 0000 0 0", "3 0100 0 0"]
    host += fight("np_fight.txt", MATCH) + results() + ["600 0000 0 0"]

GUEST_LAG = 131  # fd,bf: 755 - 624
guest = ["# --np-css guest, port 2 (generated by gen_css_scripts.py)", "300 0000 0 0",
         "6 0000 127 0", "29 0000 0 127", "12 0000 -127 0", "5 0000 0 0", "3 0100 0 0"]
if stages:
    for k in range(len(stages)):
        guest += ["# the CSS and the SSS are the host's: wait for the match", f"until {VS}", f"{GUEST_LAG - 120} 0000 0 0"]
        guest += fight("np_fight2.txt", MATCH - 140) + results_until_css()
else:
    guest += ["# wait through the host's START and stage pick", "400 0000 0 0"]
    guest += fight("np_fight2.txt", MATCH - 140) + results()
    guest += ["# the CSS and the SSS are the host's", "395 0000 0 0"]
    guest += fight("np_fight2.txt", MATCH - 140) + results()
guest += ["600 0000 0 0"]

for n, t in (("np_css_host.txt", host), ("np_css_guest.txt", guest)):
    with open(os.path.join(out, n), "w", newline="\n") as f:
        f.write("\n".join(t) + "\n")
print("written to", out)
