#!/usr/bin/env python3
"""C oracle for the neutral-hash words: rust/melee_types/tests/data/nh_expected.txt.

  python rust/melee_types/gen/nh_oracle.py        (worktree root, Windows, LLVM clang)

Extracts ftRb_Bits and nh_Mix .. nh_Fighter VERBATIM from src/melee/ft/fighter.c, compiles them
natively (x86_64, -DTARGET_PC, the real struct Fighter / CpuFighter from ft/types.h) with a fill
routine that tests/neutral_hash.rs mirrors field for field, and records the words. The item word
is RB_NeutralHash's item loop body, also extracted verbatim.
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CLANG = r"C:\Program Files\LLVM\bin\clang.exe"
GALE = (ROOT / "../../melee/build/GALE01/include").resolve()
SCRATCH = ROOT / "rust/target/nh_oracle"
src = (ROOT / "src/melee/ft/fighter.c").read_text()


def between(a, b):
    i = src.index(a); j = src.index(b, i)
    return src[i:j]


bits = between("static u32 ftRb_Bits(f32 f)", "static u32 ftRb_Hash")  if "static u32 ftRb_Hash" in src else None
if bits is None or len(bits) > 400:
    i = src.index("static u32 ftRb_Bits(f32 f)"); bits = src[i:src.index("\n}\n", i) + 3]
nh = between("static u32 nh_Mix(u32 h, u32 v)", "/* Kept in game memory")
loop = between("ih = nh_Mix(0x4954454Du, (u32) ip->kind);", "item_sum") if "item_sum" in src[src.index("ih = nh_Mix(0x4954454Du"):][:2000] else None
i = src.index("ih = nh_Mix(0x4954454Du, (u32) ip->kind);")
item_body = src[i:src.index("ih = nh_Mix(ih, ftRb_Bits(ip->x40_vel.z));", i)] + "ih = nh_Mix(ih, ftRb_Bits(ip->x40_vel.z));"

harness = r'''
#include <melee/ft/types.h>
#include <melee/it/types.h>
int printf(const char*, ...);
static int g_cpu;
/* referenced by unused static inlines in the headers; never called */
void __assert(const char* a, u32 b, const char* c) { for (;;) {} }
double __frsqrte(double x) { return 0; }
static int Player_GetStocks(int p) { return 3 + p; }
static bool ftCo_IsCpuControlled(Fighter* fp) { return g_cpu; }
''' + bits + "\n" + nh + r'''
static u32 nh_Item(Item* ip) { u32 ih; ''' + item_body + r''' return ih; }
static Fighter F; static Item I;
static const char* const FLAGS[] = {0};
static void fill(int k)
{
    struct CpuFighter* c = &F.cpu;
    u32 pat = 0xA5C30F96u ^ ((u32) k * 0x01010101u);
    int i;
    F.player_id = (u8) (k % 4);
    F.motion_id = 0x10 + k * 7;
    F.cur_pos.x = (float) k * 1.5f; F.cur_pos.y = -(float) k * 0.25f; F.cur_pos.z = (float) k * 0.1f;
    F.self_vel.x = (float) k * 0.5f; F.self_vel.y = -1.0f - (float) k;
    F.dmg.x1830_percent = (float) k * 12.5f;
    F.facing_dir = (k & 1) ? -1.0f : 1.0f;
    F.ground_or_air = k & 1;
    F.x8c_kb_vel.x = (float) k * 3.0f; F.x8c_kb_vel.y = (float) k * -2.0f;
    F.gr_vel = (float) k * 0.75f;
    F.dmg.x195c_hitlag_frames = (float) k;
    F.x2219_b5 = k & 1;
    F.shield_health = 60.0f - (float) k;
    F.x3E4_fighterCmdScript.frame_count = (float) k * 2.0f;
    F.x1968_jumpsUsed = (u8) k; F.x67F = (u8) (k + 1); F.x680 = (u8) (k + 2);
    c->buttons = 0x1000u + (u32) k;
    c->lstick.x = (s8) -k; c->lstick.y = (s8) k; c->cstick.x = (s8) (k * 9); c->cstick.y = (s8) (-k * 13);
    c->ltrigger = (u8) (k * 10); c->rtrigger = (u8) (255 - k);
    c->kind = k; c->level = 9;
    c->x14 = k * 100 + 0; c->x18 = k * 100 + 1; c->x1C = k * 100 + 2; c->x20 = k * 100 + 3; c->x24 = k * 100 + 4;
    c->x28 = k * 100 + 5; c->x2C = k * 100 + 6; c->x30 = k * 100 + 7; c->x34 = k * 100 + 8;
    c->x38 = (float) k * 0.5f + 0.0f; c->x3C = (float) k * 0.5f + 1.0f; c->x40 = (float) k * 0.5f + 2.0f;
    c->x7C = -k; c->x80 = -k - 1; c->x84 = -k - 2;
    c->xC8 = (u8) k; c->xEC = (u8) (k * 2);
    c->command_duration = 30u + (u32) k;
    c->csP = c->buffer + k * 3;
#define B(f, w) c->f = pat & ((1u << (w)) - 1u); pat = (pat >> (w)) | (pat << (32 - (w)));
    B(xF8_b0, 1) B(xF8_b12, 2) B(xF8_b34, 2) B(xF8_b5, 1) B(xF8_b6, 1) B(xF8_b7, 1)
    B(xF9_b0, 1) B(xF9_b1, 1) B(xF9_b2, 1) B(xF9_b3, 1) B(xF9_b4, 1) B(xF9_b5, 1) B(xF9_b6, 1) B(xF9_b7, 1)
    B(xFA_b0, 1) B(xFA_b1, 1) B(xFA_b2, 1) B(xFA_b34, 2) B(xFA_b5, 1) B(xFA_b6, 1) B(xFA_b7, 1)
    B(xFB_b0, 1) B(xFB_b1, 1) B(xFB_b2, 1) B(xFB_b3, 1) B(xFB_b4, 1) B(xFB_b5, 1) B(xFB_b6, 1) B(xFB_b7, 1)
    I.kind = k * 5; I.msid = k + 3;
    I.pos.x = (float) k * 4.0f; I.pos.y = (float) k * -0.5f; I.pos.z = 0.0f;
    I.x40_vel.x = (float) k * 0.125f; I.x40_vel.y = -(float) k; I.x40_vel.z = (float) k * 1e-3f;
}
int main(void)
{
    int k;
    printf("# k cpu nh_CpuFlags nh_Fighter(slot=k) nh_Item  -- generated by gen/nh_oracle.py from src/melee/ft/fighter.c\n");
    for (k = 0; k < 8; k++) {
        fill(k);
        g_cpu = k & 1;
        printf("%d %d %08X %08X %08X\n", k, g_cpu, nh_CpuFlags(&F.cpu), nh_Fighter(&F, k), nh_Item(&I));
    }
    return 0;
}
'''
SCRATCH.mkdir(parents=True, exist_ok=True)
(SCRATCH / "nh_oracle.c").write_text(harness)
flags = ["--target=x86_64-pc-windows-msvc", "-std=c99", "-DTARGET_PC", "-fno-strict-aliasing", "-fwrapv",
         "-ffp-contract=off", "-fno-fast-math", "-D_Static_assert(a,b)=", "-Dsize_t=gc_size_t", "-w",
         "-nostdinc", "-fno-builtin", "-DLINT",
         "-Isrc", "-Ipc", "-Ipc/gameworld", "-isystem", "src/MSL", "-isystem", "libs/dolphin/include",
         "-isystem", "libs/dolphin/src", "-isystem", str(GALE), "-include", "src/MSL/math_ppc.h"]
exe = SCRATCH / "nh_oracle.exe"
subprocess.run([CLANG, *flags, str(SCRATCH / "nh_oracle.c"), "-o", str(exe)], cwd=ROOT, check=True)
out = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout
dst = ROOT / "rust/melee_types/tests/data/nh_expected.txt"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text(out, newline="\n")
print(out)
