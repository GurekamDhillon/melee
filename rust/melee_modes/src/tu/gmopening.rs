/// `sprintf(dst, "...")`: the text then a NUL.
unsafe fn sprint(dst: *mut i8, s: &str) {
    for (i, b) in s.bytes().enumerate() {
        *dst.add(i) = b as i8;
    }
    *dst.add(s.len()) = 0;
}

