    melee_core::ct!("gm_MexVanillaKind");
    let native_base = if character_kind != 0 { ext::Geno_DefineBaseCK(kind) } else { ext::Geno_DefineBaseKind(kind) };
    if native_base >= 0 {
        return native_base;
    }
    let fk = if character_kind != 0 { kind - ChKind_Mex0 as i32 + Ft_Kind_Mex0 as i32 } else { kind };
    if if character_kind != 0 {
        kind < ChKind_Mex0 as i32 || kind >= ChKind_Cap as i32
    } else {
        kind < Ft_Kind_Mex0 as i32 || kind >= Ft_Kind_Max as i32
    } {
        return kind;
    }
