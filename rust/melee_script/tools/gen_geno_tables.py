#!/usr/bin/env python3
"""Generates rust/melee_script/src/geno/{consts,tables}.rs from pc/geno/geno.h and the game half's name tables
(geno_game.c: attrs + hooks; geno_game_v2.inc: params, behaviours, callbacks). Run from the repo root."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[3]
out = root / "rust/melee_script/src/geno"
h = (root / "pc/geno/geno.h").read_text()
# the v5.1 behaviour parameter set: X(FAMILY, field, type, default, "name") rows, ids in list order
bph = (root / "pc/geno/geno_behaviour_params.h").read_text()
bph_nc = re.sub(r"/\*.*?\*/", "", bph, flags=re.S)
bp_lists = {}
_cur = None
for _l in bph_nc.splitlines():
    _m = re.match(r"#define (GENO_BP_\w+_LIST)\(X\)", _l)
    if _m: _cur = _m.group(1); bp_lists[_cur] = ""
    if _cur: bp_lists[_cur] += _l + " "
    if _cur and not _l.rstrip().endswith("\\"): _cur = None
bp_order = bp_lists.pop("GENO_BP_ALL_LIST")
bp_rows = []
for ln in [x for x in re.findall(r"(GENO_BP_\w+_LIST)\(X\)", bp_order) if x != "GENO_BP_ALL_LIST"]:
    for m in re.finditer(r'X\((\w+),\s*(\w+),\s*(\w+),\s*([-\d.]+)f?,\s*"(\w+)"\)', bp_lists[ln]):
        bp_rows.append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)))
h = re.sub(r"/\*.*?\*/", "", h, flags=re.S)
h = re.sub(r"//.*", "", h)
consts = []   # (name, expr)
seen = set()
def expr(e):
    e = e.strip()
    e = re.sub(r"\b(\d+|0x[0-9A-Fa-f]+)u\b", r"\1", e)
    e = re.sub(r"\(unsigned\)\s*", "", e)
    return e
# enums
for m in re.finditer(r"enum\s*\w*\s*\{(.*?)\};", h, flags=re.S):
    nxt = 0
    for item in m.group(1).split(","):
        item = item.strip()
        if not item: continue
        if "=" in item:
            n, e = [x.strip() for x in item.split("=", 1)]
            consts.append((n, expr(e))); nxt_expr = n
        else:
            n = item; 
            consts.append((n, None))
# resolve enum auto-increment by re-walking
resolved = []
for m in re.finditer(r"enum\s*\w*\s*\{(.*?)\};", h, flags=re.S):
    prev = None
    for item in m.group(1).split(","):
        item = item.strip()
        if not item: continue
        if "=" in item:
            n, e = [x.strip() for x in item.split("=", 1)]
            e = expr(e)
        else:
            n = item
            e = "0" if prev is None else f"{prev} + 1"
        resolved.append((n, e)); prev = n
# simple defines (no parameters)
defs = []
for m in re.finditer(r"^#define[ \t]+(\w+)[ \t]+(.+)$", h, flags=re.M):
    n, e = m.group(1), m.group(2).strip()
    if n in ("GENO_H",) or "(" in n: continue
    if re.search(r"[A-Za-z_]\w*\(", e): continue  # macro calls
    defs.append((n, expr(e)))
# order: keep source order of appearance in the file text
order = {}
for n, _ in resolved + defs:
    order[n] = h.find(n)
allc = sorted(resolved + defs, key=lambda x: (order[x[0]], 0))
names = {n for n, _ in allc}
lines = ["// @generated by tools/gen_geno_tables.py from pc/geno/geno.h - do not edit.",
         "#![allow(dead_code)]", ""]
for n, e in allc:
    if n in seen: continue
    seen.add(n)
    e2 = e
    # float/odd constants
    if re.search(r"[^\w\s+\-*|&<>()x]", e2): continue
    if "GENO_ART_KIND" in e2 and "(" in e2 and "IS" in e2: continue
    # parenthesised casts like (GENO_MAX_PROFILES - 32) are fine
    e2 = re.sub(r"\b([A-Z][A-Z0-9_]+)\b", lambda m: m.group(1) if m.group(1) in names else m.group(1), e2)
    if e2.strip().startswith("(-"):
        lines.append(f"pub const {n}: i32 = {e2};"); continue
    lines.append(f"pub const {n}: u32 = ({e2}) as u32;")
lines.append("// v5.1 behaviour parameter ids (pc/geno/geno_behaviour_params.h)")
lines.append("pub const GENO_PARAMS: u32 = (%s) as u32;" % re.search(r"#define GENO_PARAMS (\d+)", bph_nc).group(1))
for i, (F, n, ty, d, nm) in enumerate(bp_rows):
    lines.append(f"pub const GENO_BP_{F}_{n}: u32 = {i};")
lines.append(f"pub const GENO_BP_COUNT: u32 = {len(bp_rows)};")
(out / "consts.rs").write_text("\n".join(lines) + "\n")

# ---- tables
g = (root / "pc/geno/geno_game.c").read_text()
v2 = (root / "pc/geno/geno_game_v2.inc").read_text()
t = ["// @generated by tools/gen_geno_tables.py from pc/geno/geno_game.c and geno_game_v2.inc - do not edit.",
     "use super::consts::*;", ""]
attrs = re.findall(r"GENO_ATTR\((\w+),\s*(\d)\)", g[g.index("geno_attrs[] = {"):])
t.append("/// (name, is_int): ftCo_DatAttrs fields by name; the index is the stable profile index (append only).")
t.append("pub const ATTRS: &[(&str, bool)] = &[")
for n, i in attrs: t.append(f'    ("{n}", {"true" if i=="1" else "false"}),')
t.append("];\n")
hooks = re.findall(r'\{\s*(GENO_HOOK_\w+),\s*"([\w.]+)",\s*hook_\w+\s*\}', g)
t.append("pub const HOOKS: &[(u32, &str)] = &[")
for i, n in hooks: t.append(f'    ({i}, "{n}"),')
t.append("];\n")
t.append("/// (family, name, id, default): the v5.1 set of pc/geno/geno_behaviour_params.h")
t.append("pub const PARAMS: &[(&str, &str, u32, f32)] = &[")
for F, n, ty, d, nm in bp_rows:
    if "." not in d: d += ".0"
    t.append(f'    ("{F.lower()}", "{nm}", GENO_BP_{F}_{n}, {d}),')
t.append("];\n")
cbs = re.findall(r'\{\s*(GENO_CBID_\w+),\s*(GENO_CB_\w+),\s*"([\w.]+)",', v2)
cbid = {}
for m in re.finditer(r"(GENO_CBID_\w+)\s*=\s*(\d+)", v2): cbid[m.group(1)] = int(m.group(2))
t.append("pub const CBID_NAMES: &[(&str, u32)] = &[")
for n, v in cbid.items(): t.append(f'    ("{n}", {v}),')
t.append("];\n")
t.append("/// (callback id, slot, name)")
t.append("pub const CALLBACKS: &[(u32, u32, &str)] = &[")
for i, s, n in cbs: t.append(f'    ({cbid[i]}, {s}, "{n}"),')
t.append("];\n")
bs = re.findall(r'\{\s*(GENO_BHV_\w+),\s*"([\w.]*)",', v2[v2.index("geno_bhvs[] = {"):])
t.append("pub const BEHAVIORS: &[(u32, &str)] = &[")
for i, n in bs: t.append(f'    ({i}, "{n}"),')
t.append("];\n")
(out / "tables.rs").write_text("\n".join(t) + "\n")
print(len(allc), "consts;", len(attrs), "attrs;", len(hooks), "hooks;", len(bp_rows), "params;", len(cbs), "callbacks;", len(bs), "behaviours")
