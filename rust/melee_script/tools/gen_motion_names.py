"""Regenerates src/motion_names.rs from pc/platform/gw_motion_names.inc (itself generated from the decomp's motion
enums by pc/geno/tools/gen_motion_names.py). Run from anywhere: python rust/melee_script/tools/gen_motion_names.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[3]
src = (root / "pc/platform/gw_motion_names.inc").read_text()
arrays = {}
for m in re.finditer(r"static const char \*const (gw_motion_\w+)\[\d+\] = \{[^\n]*\n(.*?)\n\};", src, re.S):
    arrays[m.group(1)] = re.findall(r'"([^"]*)"', m.group(2))
common = arrays.pop("gw_motion_common")
table = re.search(r"gw_motion_special\[\d+\] = \{(.*?)\n\};", src, re.S).group(1)
rows = []
for line in table.strip().splitlines():
    m = re.match(r"\s*\{(\w+), (\d+)\}", line)
    name, n = m.group(1), int(m.group(2))
    rows.append(None if name == "NULL" else (name, n))
out = ["//! GENERATED by rust/melee_script/tools/gen_motion_names.py from pc/platform/gw_motion_names.inc - do not edit.",
       "//! Common action states 0-340, then each vanilla fighter's special states from 341 (indexed by `name_kind`).",
       "pub const COMMON_COUNT: usize = %d;" % len(common),
       "pub static COMMON: [&str; %d] = [" % len(common)]
out += ['    "%s",' % n for n in common] + ["];"]
for name, names in arrays.items():
    out.append("static %s: [&str; %d] = [%s];" % (name.upper(), len(names), ", ".join('"%s"' % n for n in names)))
out.append("pub static SPECIAL: [&[&str]; %d] = [" % len(rows))
for r in rows:
    out.append("    &[]," if r is None else "    &%s," % r[0].upper())
out.append("];")
(root / "rust/melee_script/src/motion_names.rs").write_text("\n".join(out) + "\n")
print(len(common), len(rows))
