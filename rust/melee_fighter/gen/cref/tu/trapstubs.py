#!/usr/bin/env python3
"""Write trap stubs for a TU driver's unresolved callees.

  python rust/melee_fighter/gen/cref/tu/trapstubs.py <stem> NAME...

For each NAME, the prototype is looked up in the game headers (src/melee, src/sysdolphin) and a
body that aborts is written to gen/cref/tu/<stem>_traps.h (include it after the TU). A stub
here is a callee the oracle's cases never reach; reaching it aborts the oracle loudly.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parent


def proto(name):
    pat = re.compile(r"^\s*(?:/\*[^*]*\*/\s*)?(?:extern\s+)?([A-Za-z_][\w \*]*?[\s\*])" + re.escape(name) + r"\s*\(([^;{]*?)\)\s*;", re.M | re.S)
    for d in ("src/melee", "src/sysdolphin", "pc"):
        for h in (ROOT / d).rglob("*.h"):
            try:
                t = h.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            if name not in t:
                continue
            m = pat.search(t)
            if m:
                return m.group(1).strip(), " ".join(m.group(2).split())
    raise SystemExit(f"no prototype for {name}")


def main():
    stem, names = sys.argv[1], sys.argv[2:]
    out = [f"/* generated by trapstubs.py: callees of {stem} the oracle never reaches */",
           "void abort(void);"]
    for n in names:
        ret, args = proto(n)
        # name unnamed parameters so the definition is valid C
        ps = [] if args in ("", "void") else [p.strip() for p in args.split(",")]
        named = []
        for i, p in enumerate(ps):
            if p == "...":
                named.append(p)
            elif re.search(r"[\w\]]\s*$", p) and len(re.findall(r"\w+", p.replace("*", " "))) >= 2 and not p.endswith("*"):
                named.append(p)
            else:
                named.append(f"{p} a{i}")
        body = "abort();" + ("" if ret == "void" else f" {{ static {ret} z; return z; }}")
        out.append(f"{ret} {n}({', '.join(named) or 'void'}) {{ {body} }}")
    (HERE / f"{stem}_traps.h").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
