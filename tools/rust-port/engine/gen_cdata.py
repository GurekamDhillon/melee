#!/usr/bin/env python3
"""Generate rust/melee_engine/src/cdata.rs from cdata.tsv: C string literals copied into the zeroed `ext` statics of the tu
ports that declare data owned by a TU nobody ported. Usage: gen_cdata.py"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
TSV = ROOT / "tools/rust-port/engine/cdata.tsv"
OUT = ROOT / "rust/melee_engine/src/cdata.rs"


def c_string(src, name):
    bs = chr(92)
    lit = '"(?:[^"' + bs + bs + ']|' + bs + bs + '.)*"'
    m = re.search(r'\b' + re.escape(name) + r'\s*\[\s*\d*\s*\]\s*=\s*((?:' + lit + r'\s*)+);', src)
    if not m:
        sys.exit(f"gen_cdata: no string initialiser for {name}")
    parts = re.findall('"((?:[^"' + bs + bs + ']|' + bs + bs + '.)*)"', m.group(1))
    s = "".join(parts)
    return s


def main():
    rows = []
    for line in TSV.read_text().split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        rows.append((f[0], f[1], f[2]))
    out = ["// @generated by tools/rust-port/engine/gen_cdata.py from cdata.tsv. Do not edit.",
           "#![allow(non_upper_case_globals, clippy::all)]", "",
           "/// Copy `s` plus a NUL into the static array at `dst` (capacity `cap`).",
           "unsafe fn put(dst: *mut i8, cap: usize, s: &[u8]) {",
           "    assert!(s.len() < cap, \"cdata: string too long\");",
           "    core::ptr::copy_nonoverlapping(s.as_ptr() as *const i8, dst, s.len());",
           "    *dst.add(s.len()) = 0;",
           "}", "",
           "/// The C string data the ports leave zeroed. Call once at boot.", "pub fn install_cdata() {", "    unsafe {"]
    for path, cfile, csym in rows:
        src = (ROOT / cfile).read_text(encoding="utf-8", errors="replace")
        lit = c_string(src, csym)
        out.append(f'        put((&raw mut {path}) as *mut i8, core::mem::size_of_val(&{path}), b"{lit}");')
    out += ["    }", "}", ""]
    OUT.write_text("\n".join(out), newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} strings")


main()
