#!/usr/bin/env python3
"""Round 10 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round10.py

Round 10 is hand-ported only (src/itkinds10.rs): functions whose only unported callees were
lbVector_* / atan2f / MSL sinf, cosf (now native in melee_runtime) and HSD_Randi / HSD_Randf.
This writes tests/c_oracle/round10_bodies.h, the verbatim decomp C bodies of the HAND list,
#included by round10.c. Never edit the output by hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """it_80271830 it_8027649C it_8027649C_ref it_80277040 it_8027770C it_8027B798
it_8027BB1C it_802E628C it_802863BC itFlipper_Repel_inline itFoxBlaster_SetShotAngle
it_80293DCC it_802D61C8 it_802D4494 it_802D4510 itKoopaFlame_UnkMotion0_Phys
itLgunbeam_UnkMotion0_Phys it_802A2320 it_2725_Logic101_ShieldBounced it_802D6740
itPikachutjoltground_UnkMotion0_Phys itSamuschargeshot_UnkMotion8_Phys it_802EC870""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

b = ["/* @generated by gen_round10.py: verbatim copies of the decomp C bodies ported in round 10",
     " * (src/itkinds10.rs), grouped by source file. #included by round10.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        lastp = path
    b.append(body.strip())
    b.append('')
(OR / 'round10_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')

# The callees, verbatim from the game TUs the shipping build links (lbvector.c, and mtx_pc.c's
# PSVECCrossProduct): only the functions round 10 reaches, so lbVector_WorldToScreen's CObj / GX
# dependencies stay out of the oracle.
CALLEES = [('src/melee/lb/lbvector.c', """lbVector_Len_xy_accurate lbVector_Normalize lbVector_NormalizeXY
lbVector_CrossprodNormalized lbVector_Angle lbVector_AngleXY lbvector_sin lbvector_cos
lbVector_RotateAboutUnitAxis lbVector_Mirror""".split()),
           ('pc/gameworld/mtx_pc.c', ['PSVECCrossProduct'])]
c = ["/* @generated by gen_round10.py: verbatim copies of the game functions round 10's bodies call",
     " * (lbvector.c, mtx_pc.c). #included by round10.c before round10_bodies.h. */"]
for rel, names in CALLEES:
    fs = funcs(str(ROOT / rel))
    c.append(f"/* ---- {rel} */")
    for n in names:
        c.append(fs[n][0].strip())
        c.append('')
(OR / 'round10_callees.h').write_text('\n'.join(c) + '\n', encoding='utf-8', newline='\n')
print(f'{sum(len(n) for _, n in CALLEES)} callee bodies')
