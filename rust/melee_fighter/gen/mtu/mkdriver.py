#!/usr/bin/env python3
"""Fighter-world oracle driver generator for a src/tu/<stem>.rs port (the ftcoll / ftanim / ftaction pattern).

  python rust/melee_fighter/gen/mtu/mkdriver.py <spec.json>

The spec names the game TU, the port module, the ops and a few extension snippets; the generator writes
  gen/cref/tu/<stem>_ops.c        the C driver (the whole TU included verbatim, recording stubs, a random fighter world)
  tests/tu_<stem>_vs_c.rs         the Rust half (same world, same draws, same hash)
  gen/mtu/regen_<stem>.sh         fill + stubs + C expected output
Each case: tu_case(op, k); world(); g = &GO[rnd() % NG]; fp = its fighter; the op; hash of the world. Spec keys:
  stem, csrc ("src/melee/ft/ft_0D4D.c"), rmod ("melee_fighter::tu::ft_0d4d"), cases (per op)
  ops: [[c expression, rust expression], ...]   (variables g: gobj pointer, fp: fighter pointer, gi: index)
  stubs: extra stubs.py arguments (a string); fill_types: extra state types; fill_pools: extra pool types
  c_head / rs_head: code after the includes / after the use lines (hand-defined stubs, statics)
  c_world / rs_world: code at the end of world() (after the common world)
  rs_hooks: code in install_hooks()
  c_includes: extra #include lines
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
FD = ROOT / "rust/melee_fighter"

PK_C = None
PK_RS = None


def pk_lines():
    f = (FD / "gen/cref/tu/fighter_ops.c").read_text(encoding="utf-8")
    c = [l for l in f.split("\n") if "int pk = i * 24" in l][0].strip()
    r = (FD / "tests/tu_ftaction_vs_c.rs").read_text(encoding="utf-8")
    a = r.index("// the ftData pointer words")
    b = r.index("    }\n    for i in 0..NJ {", a)
    return c, r[a:b]


