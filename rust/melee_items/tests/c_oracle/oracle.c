static unsigned bits(f32 f) { unsigned u; memcpy(&u, &f, 4); return u; }
static f32 fbits(unsigned u) { f32 f; memcpy(&f, &u, 4); return f; }

/* fighter.c nh_Mix + the item loop body of RB_NeutralHash */
static u32 nh_Mix(u32 h, u32 v) { h ^= v; h *= 0x01000193u; h ^= h >> 15; return h; }
static u32 item_word(Item* ip)
{
    u32 ih = nh_Mix(0x4954454Du, (u32) ip->kind);
    ih = nh_Mix(ih, (u32) ip->msid);
    ih = nh_Mix(ih, bits(ip->pos.x)); ih = nh_Mix(ih, bits(ip->pos.y)); ih = nh_Mix(ih, bits(ip->pos.z));
    ih = nh_Mix(ih, bits(ip->x40_vel.x)); ih = nh_Mix(ih, bits(ip->x40_vel.y)); ih = nh_Mix(ih, bits(ip->x40_vel.z));
    return ih;
}

/* item.c */
static void Item_80269CA0(Item* item_data, s32 damage)
{
    item_data->xC9C += damage;
    if (item_data->xC9C > 999) { item_data->xC9C = 999; }
}
/* itparasol.c */
static inline void decelerateItemX(Item* item, f32 decel_x)
{
    if (ABS(item->x40_vel.x) > decel_x) {
        if (item->x40_vel.x > decel_x) { item->x40_vel.x -= decel_x; }
        if (item->x40_vel.x < -decel_x) { item->x40_vel.x += decel_x; }
    } else {
        item->x40_vel.x = 0.0F;
    }
}
/* itsamusmissile.c */
static inline void itSamusMissile_ClampTurn(Item* ip, itSamusMissileAttributes* sa)
{
    f32 turn = ip->xDD4_itemVar.samusmissile.x8;
    f32 abs_turn; f32 max_turn;
    if (turn < 0.0f) { abs_turn = -turn; } else { abs_turn = turn; }
    max_turn = sa->x1C;
    if (abs_turn > max_turn) {
        if (turn > 0.0f) { ip->xDD4_itemVar.samusmissile.x8 = max_turn; }
        else { ip->xDD4_itemVar.samusmissile.x8 = -max_turn; }
    }
}
/* itlinkboomerang.c */
static inline void norm_xF74(Item* ip)
{
    f64 angle;
    if (ip->facing_dir == 1.0f) { angle = ip->xDD4_itemVar.linkboomerang.xF74; }
    else { angle = ip->xDD4_itemVar.linkboomerang.xF74 - M_PI; }
    ip->xDD4_itemVar.linkboomerang.xF78 = angle;
}

