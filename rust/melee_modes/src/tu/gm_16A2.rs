/// `fn_801695BC` (TARGET_PC): shuffle a character's costumes over the queue entries holding it.
pub unsafe fn fn_801695BC(arg0: u8, arg1: u8, arg2: u8, arg3: *const u8, arg4: *mut i8) {
    let mut colors = [0i8; 254];
    let mut ncolors = ext::gm_GetNumCostumesForCKind(arg0);
    // Legacy Classic queues use signed bytes with -1/-2 sentinels: exclude id 254 (= the -2 terminator).
    if ncolors > 254 {
        ncolors = 254;
    }
    if arg0 as i8 as i32 != ChKind_None as i32 {
        let ncolors_s32 = ncolors as i32;
        for i in 0..ncolors as usize {
            colors[i] = i as i8;
        }
        if arg1 as i8 == arg0 as i8 && arg2 < ncolors {
            colors[arg2 as usize] = -1;
        }
        for i in 0..ncolors_s32 as usize {
            let o = ext::HSD_Randi(ncolors_s32) as usize;
            let tmp = colors[o];
            colors[o] = colors[i];
            colors[i] = tmp;
        }
        let mut color_i: i32 = 0;
        let mut i = 0usize;
        while *arg4.add(i) != -2 {
            if arg0 as i8 == *arg3.add(i) as i8 {
                if colors[(color_i % ncolors_s32) as usize] == -1 {
                    color_i += 1;
                }
                *arg4.add(i) = colors[(color_i % ncolors_s32) as usize];
                color_i += 1;
            }
            i += 1;
        }
        i = 1;
        while *arg4.add(i) != -2 {
            if arg0 as i8 == *arg3.add(i) as i8 && arg0 as i8 == *arg3.add(i - 1) as i8 {
                if ext::HSD_Randi(2) != 0 {
                    let tmp2 = *arg4.add(i);
                    *arg4.add(i) = *arg4.add(i - 1);
                    *arg4.add(i - 1) = tmp2;
                }
            }
            i += 1;
        }
    }
}

/// `fn_801697FC` (TARGET_PC): give every queue entry one costume.
pub unsafe fn fn_801697FC(character: i8, mut costume: i8, new_character: i8, new_costume: i8, buf: *mut i8) {
    let mut ncolors = ext::gm_GetNumCostumesForCKind(character as u8);
    if character as i32 == ChKind_None as i32 {
        return;
    }
    if costume as u8 == 254 {
        costume = 0;
    }
    if ncolors > 254 {
        ncolors = 254;
    }
    if new_character == character && costume == new_costume {
        costume = ((costume as u8 as i32 + 1) % ncolors as i32) as i8;
    }
    let mut i = 0usize;
    while *buf.add(i) != -2 {
        *buf.add(i) = costume;
        i += 1;
    }
}

