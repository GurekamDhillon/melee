#!/usr/bin/env python3
"""Generate rust/melee/src/retail/mn_tables.rs from src/melee/mn/mnmain.c: the main menu's animation
loop tables (AnimLoopSettings), per-kind descriptors (MenuKindData) and description string ids."""
import re, sys
src = open(sys.argv[1]).read()

def block(name):
    m = re.search(r'(?:static\s+)?(?:AnimLoopSettings|u16|float|GXColor|MenuKindData)\s+' + re.escape(name) + r'\s*(\[[^\]]*\])*\s*=\s*\{', src)
    assert m, name
    i = m.end() - 1
    d = 0
    j = i
    while True:
        if src[j] == '{': d += 1
        elif src[j] == '}':
            d -= 1
            if d == 0: break
        j += 1
    return src[i:j + 1]

def nums(b):
    return [float(x) for x in re.findall(r'-?\d+\.?\d*(?:[eE][-+]?\d+)?|0x[0-9A-Fa-f]+', b.replace('F', 'f').replace('f', '')) ]

def triples(name):
    b = block(name)
    vals = re.findall(r'\{\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\}', b)
    return [tuple(float(x) for x in v) for v in vals]

def u16s(name):
    b = block(name)
    return [int(x, 16) if x.lower().startswith('0x') else int(x) for x in re.findall(r'0x[0-9A-Fa-f]+|\b\d+\b', b)]

out = ["// @generated by tools/rust-port/menus/gen_mn_tables.py from src/melee/mn/mnmain.c; do not edit.",
       "use super::AnimLoop;",
       "const fn al(start: f32, end: f32, loop_to: f32) -> AnimLoop { AnimLoop { start, end, loop_to } }", ""]
def emit_loops(rname, vals):
    out.append("pub static %s: [AnimLoop; %d] = [%s];" % (rname, len(vals), ", ".join("al(%r, %r, %r)" % v for v in vals)))
    out.append("")
panel = triples('mn_803EAE8C')
assert len(panel) == 0x22 * 3, len(panel)
emit_loops("PANEL", panel)
for nm in ['mn_803EB354', 'mn_803EB360', 'mn_803EB378', 'mn_803EB390', 'mn_803EB39C', 'mn_803EB3A8', 'mn_803EB3B4', 'mn_803EB3C0',
           'mn_803EB3FC', 'mn_803EB438', 'mn_803EB444', 'mn_803EB480', 'mn_803EB48C', 'mn_803EB4C8', 'mn_803EB4F8', 'mn_803EB540',
           'mn_803EB57C', 'mn_803EB5A0', 'mn_803EB5C4', 'mn_803EB5E8']:
    b = block(nm)
    v = re.findall(r'\{\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\}', b)
    if not v:
        v = re.findall(r'(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)', b.strip('{}'))
    emit_loops(nm.upper().replace('MN_', 'L_'), [tuple(float(x) for x in t) for t in v])
for nm in ['mn_803EB660', 'mn_803EB66C', 'mn_803EB678', 'mn_803EB684', 'mn_803EB690', 'mn_803EB69C', 'mn_804D4B30', 'mn_804D4B38', 'mn_804D4B40', 'mn_804D4B48', 'mn_803EAE68', 'mn_803EAE7C']:
    v = u16s(nm)
    out.append("pub static %s: [u16; %d] = %r;" % (nm.upper().replace('MN_', 'D_'), len(v), v))
out.append("")
open(sys.argv[2], 'w').write("\n".join(out) + "\n")

# ---- the SIS default kerning table (hsd_3A76.c HSD_SisLib_8040CB00)
src2 = open(sys.argv[3]).read() if len(sys.argv) > 3 else None
if src2:
    m = re.search(r'u8 HSD_SisLib_8040CB00\[0x240\]\s*=\s*\{(.*?)\};', src2, re.S)
    vals = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
    assert len(vals) == 0x240, len(vals)
    open(sys.argv[4], 'w').write("// @generated by tools/rust-port/menus/gen_mn_tables.py from src/sysdolphin/baselib/hsd_3A76.c; do not edit.\npub static KERNING: [u8; 0x240] = %r;\n" % vals)
