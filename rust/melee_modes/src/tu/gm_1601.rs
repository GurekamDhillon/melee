/// An m-ex fighter's name converted to the full-width forms the game's own name strings use.
unsafe fn gm_MexName(ckind: u8) -> *const c_char {
    let out = MEX_NAMES[(ckind as u32 - ChKind_Mex0) as usize].as_mut_ptr();
    let mut n = 0usize;
    if *out != 0 {
        return out as *const c_char;
    }
    let src: *const c_char = if ext::Geno_DefineName(ckind as i32, MEX_NATIVE_NAME.as_mut_ptr() as *mut i8, 48) != 0 {
        MEX_NATIVE_NAME.as_ptr() as *const c_char
    } else {
        ext::Mex_FighterName(ext::Mex_PortCKindToExt(ckind as i32)) as *const c_char
    };
    if src.is_null() {
        return b"?\0".as_ptr() as *const c_char;
    }
    let mut p = src as *const u8;
    while *p != 0 && n < 96 - 4 {
        let c = *p as u32;
        if c > 0x20 && c < 0x7F {
            let u = 0xFF01 + (c - 0x21);
            *out.add(n) = 0xEF;
            n += 1;
            *out.add(n) = (0x80 | ((u >> 6) & 0x3F)) as u8;
            n += 1;
            *out.add(n) = (0x80 | (u & 0x3F)) as u8;
            n += 1;
        } else {
            *out.add(n) = c as u8;
            n += 1;
        }
        p = p.add(1);
    }
    *out.add(n) = 0;
    out as *const c_char
}

