#!/usr/bin/env python3
"""Generate rust/melee_engine/src/seams_gen.rs: the "feature off" body of every unlinked host-seam hook.

Consolidation step 6.  Reads the `ext_fns!` entries with gen_link.parse_hooks (same parser), keeps those that
gen_link left unlinked and whose name matches a regex in tools/rust-port/engine/seams.txt, and emits
`if hook::NAME.is_none() { hook::NAME = Some(|..| off) }`.  The engine installs explicit host functions first, so
only the hooks nobody set are filled.  Usage: gen_seams.py [--report]
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'link'))
import gen_link as g

HERE = os.path.dirname(__file__)


def ret_types():
    """(file, name) -> return type text, read from the ext_fns entries again (gen_link keeps only has-return)."""
    out = {}
    for crate, f, rel in g.tu_files():
        raw = open(f, encoding='utf8', errors='replace').read()
        if 'ext_fns' not in raw and 'stubs!' not in raw and 'hooks!' not in raw: continue
        t = g.blank(raw)
        for im in re.finditer(r'\b(?:ext_fns(?:_[ch])?|hooks)!\s*\{', t):
            cl = g.match_close(t, im.end() - 1)
            if cl < 0: continue
            for ent in g.split_top(t[im.end():cl], ';'):
                m = g.ENTRY_HEAD.match(ent)
                if not m: continue
                p1 = g.match_close(ent, m.end() - 1, '(', ')')
                if p1 < 0: continue
                rm = re.match(r'\s*->\s*(.+?)\s*(?:=|$)', ent[p1 + 1:], re.S)
                out[(rel, m.group('name'))] = rm.group(1).strip() if rm else None
    return out


def linked_hook_paths():
    """Hook paths (`tu::<file>::ext::hook::<name>`, no crate) that melee_link installs: the `linked = true` rows of the
    HOOKS table in gen_table.rs, the table the engine really runs. linked_keys.txt is not used: it is only rewritten by a
    full gen_link run and went stale when TUs were renamed (camera.rs was cmcamera, ftCo_0A01 was ftCo_0A01_ai), so hooks
    gen_table links were emitted here again."""
    out = set()
    txt = open(os.path.join(g.RUST, 'melee_link', 'src', 'gen_table.rs'), encoding='utf8').read()
    for m in re.finditer(r'^    \("\w+", "(\w+)::([^"]+)", true, (?:true|false)\),$', txt, re.M):
        out.add(m.group(2))
    return out


def off_body(ty, name):
    if name.endswith('_Iterations'): return 'a0'
    if ty is None: return '()'
    if ty.startswith('*'): return 'core::ptr::null_mut()'
    if ty == 'bool': return 'false'
    if ty.startswith('Option<'): return 'None'
    if ty in ('f32', 'f64'): return '0.0'
    if re.fullmatch(r'[iu](8|16|32|64|size)', ty): return '0'
    if re.fullmatch(r'(?:::)?(?:core::ffi|std::os::raw|libc)::c_(?:u?(?:char|short|int|long|longlong)|schar)', ty): return '0'
    if re.fullmatch(r'(?:::)?core::ffi::c_(?:float|double)', ty): return '0.0'
    return None


def main():
    pats = []
    for l in open(os.path.join(HERE, 'seams.txt')):
        if not l.strip() or l.startswith('#'): continue
        f = l.rstrip(chr(10)).split(chr(9))
        force = f[0].startswith('!')
        pats.append((re.compile(f[0].strip().lstrip('!')), f[1].strip() if len(f) > 1 else None, force))
    skip = {l.split()[0] for l in open(os.path.join(HERE, '..', 'link', 'link_skip.txt')) if l.strip() and not l.startswith('#')}
    defs = g.index_defs()
    hooks = g.parse_hooks()
    rts = ret_types()
    linked_paths = linked_hook_paths()
    out = ['// @generated by tools/rust-port/engine/gen_seams.py. Do not edit.',
           '#![allow(non_snake_case, unused_unsafe, unused_variables, clippy::all)]', '',
           '/// Fill every still-unset host-seam hook with its "feature off" body. Call after the explicit installs.',
           'pub fn install_gen() {',
           '    unsafe { melee_modes::tu::ext_hook::EXT_FALLBACK = Some(ext_fallback); }']
    seen = set(); n = 0; bad = []
    for h in hooks:
        if h['path'] is None or (h.get('cabi') and h.get('ref')): continue
        hit = [(o, fo) for p, o, fo in pats if p.fullmatch(h['name'])]
        if not hit: continue
        force = hit[0][1]
        if h['path'] in linked_paths and not force: continue
        if not h['todo'] and not force: continue  # a real default body (the vanilla behaviour) stays
        hit = [o for o, _ in hit]
        key = h['crate'] + '::' + h['path']
        if key in seen: continue
        seen.add(key)
        rty = h['ret'] if 'ret' in h else rts.get((h['file'], h['name']))
        body = off_body(rty, h['name'])
        if hit[0] is not None and rty is not None: body = hit[0]
        if body is None:
            bad.append((key, rty)); continue
        named = body == 'a0' or '$ARGS' in body
        args = ', '.join(f'a{i}' if (body == 'a0' and i == 0) or ('$ARGS' in body) else '_' for i in range(h['npar']))
        body = body.replace('$ARGS', ', '.join(f'a{i}' for i in range(h['npar'])))
        clo = f'melee_link::cabi::c{h["npar"]}(|{args}| {body})' if h.get('cabi') else f'|{args}| {body}'
        out.append(f'    unsafe {{ {key} = Some({clo}); }}' if force else f'    unsafe {{ if {key}.is_none() {{ {key} = Some({clo}); }} }}')
        n += 1
    out.append('}')
    # hooks that exist only by name: `crate::ext_fns!` functions of melee_modes consult one global fallback
    names = {}
    for h in hooks:
        if not h.get('byname') or not h['todo']: continue
        hit = [o for p, o, fo in pats if p.fullmatch(h['name'])]
        if not hit: continue
        rty = h.get('ret')
        body = hit[0] if (hit[0] is not None and rty is not None) else ('0')
        try:
            names[h['name']] = int(body, 0) & 0xFFFFFFFFFFFFFFFF
        except ValueError:
            names[h['name']] = 0
    out.append('')
    out.append('/// `melee_modes::tu::ext_hook::EXT_FALLBACK`: the by-name `ext_fns!` callees answered "feature off".')
    out.append('pub unsafe fn ext_fallback(name: &str, args: &[u64]) -> u64 {')
    out.append('    if let Some(v) = crate::seams::ext_real(name, args) {')
    out.append('        return v;')
    out.append('    }')
    out.append('    match name {')
    by_val = {}
    for k, v in sorted(names.items()): by_val.setdefault(v, []).append(k)
    for v, ks in sorted(by_val.items()):
        for i in range(0, len(ks), 6):
            out.append('        ' + ' | '.join(f'"{k}"' for k in ks[i:i + 6]) + f' => {v:#x},')
    out.append('        _ if melee_core::ct::render_stub() => 0, // retail draw callbacks run headless: display calls answer zero')
    out.append('        _ => panic!("TODO ext: {name} is in a TU that is not ported yet"),')
    out.append('    }')
    out.append('}')
    out.append('')
    print(f'{len(names)} by-name fallbacks')
    print(f'{n} seam hooks; {len(bad)} with an unsupported return type: {bad[:5]}')
    if '--report' in sys.argv: return
    open(os.path.join(g.RUST, 'melee_engine', 'src', 'seams_gen.rs'), 'w', newline='\n').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
