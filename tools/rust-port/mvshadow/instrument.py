"""Instrument a SCRATCH copy of the Rust port for the union-drift checker (rust/melee_core/src/mvshadow.rs, feature mvshadow).

Never run it on a working tree you commit from: it rewrites sources in place.
    python tools/rust-port/mvshadow/instrument.py SCRATCH_REPO [--unchecked OUT.tsv]
then build SCRATCH_REPO/rust with `--features melee_core/mvshadow` and run scenarios / replays; drifted reads are logged on
stderr as `MVSHADOW <file:line> <path> ...`, once per (caller, path).

What it does:
- the table: every leaf of `union Fighter_MotionVars` under the native (the oracle's flags, gen/chref.py) and GameCube
  (powerpc-eabi) layouts, and every prefix of a leaf path (a struct read or written whole covers its leaves), written to
  melee_core/src/mvshadow_table.rs;
- the transform, in the crates that touch `mv`: each `X.mv.<path>` (X: `(*fp)`, `fp`, `fp(g)`) whose longest resolvable
  prefix is in the table becomes `(*mvshadow::r(unsafe { addr_of!(..) }, ID))` (a union field's address is unsafe even
  where writing the field is not) when read, `(*mvshadow::w(addr_of_mut!(..), ID))`
  when assigned, borrowed `&mut` / `&raw mut` / addr_of_mut!, or passed to a `.set_*` bitfield setter, and `rw` for a
  compound assignment (it reads the old value). Rust evaluates an assigned value before its place, so the reads on the
  right-hand side see the shadow before the write;
- Fighter_Create's `write_bytes` of the whole Fighter: `mvshadow::reset` (both shadows agree from there); the engine's
  per-frame NHV1 row: `mvshadow::tick` (a hit is logged with the golden frame it happened in);
- what it cannot check is listed by file:line (--unchecked): a dynamic array index, a path not in the table, a `.mv`
  it did not match (another base expression), a raw pointer formed from `mv` (cast or offset).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
CRATES = ["melee_chara", "melee_fighter", "melee_modes", "melee_items", "melee_world"]
UNION = "union Fighter_MotionVars"


def table():
    import os
    import clang.cindex as ci
    import mv_layout_audit as A
    ci.Config.set_library_file(os.environ.get("LIBCLANG") or str(Path(A.chref.CLANG).parent / "libclang.dll"))
    nat, _ = A.union_views(A.parse(None))
    gc, _ = A.union_views(A.parse("powerpc-unknown-eabi"))
    nat, gc = nat[UNION], gc[UNION]
    leaves = {}
    for v in nat:
        if v == "_":
            continue
        for p, (n, nz, k) in nat[v].items():
            if k == "bf" or p not in gc[v]:
                continue
            g, gz, _ = gc[v][p]
            leaves[f"{v}{p}"] = (n, g, nz, gz)
    paths = {}
    for full, seg in leaves.items():
        toks = re.findall(r"\.?\w+|\[\d+\]", full)
        for i in range(1, len(toks) + 1):
            paths.setdefault("".join(toks[:i]).lstrip("."), []).append(seg)
    nsz = max(n + nz for n, g, nz, gz in leaves.values())
    gsz = max(g + gz for n, g, nz, gz in leaves.values())
    return paths, nsz, gsz


def write_table(repo, paths, nsz, gsz):
    names = sorted(paths)
    rows = []
    for name in names:
        segs = sorted(set(paths[name]))
        base = min(n for n, _, _, _ in segs)
        rows.append(f'    ("{name}", {base}, &[{", ".join(f"({n}, {g}, {nz}, {gz})" for n, g, nz, gz in segs)}]),')
    (repo / "rust/melee_core/src/mvshadow_table.rs").write_text(
        "//! @generated by tools/rust-port/mvshadow/instrument.py (scratch tree only).\n"
        "pub static PATHS: &[(&str, u16, &[(u16, u16, u16, u16)])] = &[\n" + "\n".join(rows) + "\n];\n"
        f"pub const MV_NATIVE_SIZE: usize = {nsz};\npub const MV_GC_SIZE: usize = {gsz};\n", encoding="utf-8")
    return {n: i for i, n in enumerate(names)}


PLACE = re.compile(r"(\(\*\w+\)|\b[a-z_]\w*\(\w+\)|\b[a-z_]\w*)\.mv((?:\.\w+|\[\d+\])+)")
MUT_BEFORE = re.compile(r"(&\s*mut\s*|&raw\s+mut\s+|addr_of_mut!\(\s*)$")
COMPOUND = re.compile(r"\s*(\+|-|\*|/|%|&|\||\^|<<|>>)=")
ASSIGN = re.compile(r"\s*=(?!=)")
SH = "melee_core::mvshadow"


def transform(text, ids, rel, unchecked):
    out = []
    for ln, line in enumerate(text.split("\n"), 1):
        code = line.split("//", 1)[0]
        pieces, pos = [], 0
        for m in PLACE.finditer(code):
            toks = re.findall(r"\.\w+|\[\d+\]", m.group(2))
            # the longest prefix in the table: what follows may be a method (`.abs()`) or a bitfield accessor
            k = len(toks)
            while k and "".join(toks[:k]).lstrip(".") not in ids:
                k -= 1
            if not k:
                unchecked.append((rel, ln, "path not in the table", m.group(0)))
                continue
            path = "".join(toks[:k]).lstrip(".")
            place = m.group(1) + ".mv." + path
            end = m.start() + len(place)
            tail = code[end:]
            if tail.startswith("["):
                unchecked.append((rel, ln, "dynamic index", m.group(0) + tail[:12]))
                continue
            if k < len(toks) and not re.match(r"\.\w+\s*\(", tail):
                # the chain goes on with a field the table does not name (a Rust-only name, a bitfield struct): checking
                # the coarser prefix would compare bytes this access never touches
                unchecked.append((rel, ln, "path partly in the table", m.group(0)))
                continue
            i = ids[path]
            before = code[:m.start()]
            if MUT_BEFORE.search(before) or re.match(r"\.set_\w+\(", tail) or ASSIGN.match(tail):
                rep = f"(*{SH}::w(unsafe {{ core::ptr::addr_of_mut!({place}) }}, {i}))"
            elif COMPOUND.match(tail):
                rep = f"(*{SH}::rw(unsafe {{ core::ptr::addr_of_mut!({place}) }}, {i}))"
            else:
                rep = f"(*{SH}::r(unsafe {{ core::ptr::addr_of!({place}) }}, {i}))"
            pieces.append(line[pos:m.start()] + rep)
            pos = end
        # what the pattern did not take: another base expression, or a raw pointer made from mv
        for m in re.finditer(r"\.mv\b", code):
            if not any(p.start() <= m.start() < p.start() + len(p.group(0)) for p in PLACE.finditer(code)):
                unchecked.append((rel, ln, "base not matched", code[max(0, m.start() - 30):m.start() + 30].strip()))
        if re.search(r"\.mv\)?\s*as\s*\*(const|mut)|\.mv\b[^;]*\.(add|offset|byte_add)\(", code):
            unchecked.append((rel, ln, "raw pointer from mv", code.strip()[:90]))
        out.append("".join(pieces) + line[pos:])
    return "\n".join(out)


def main():
    repo = Path(sys.argv[1]).resolve()
    if (repo / ".git").is_dir():
        raise SystemExit("instrument: refusing a primary checkout; give it a scratch copy")
    paths, nsz, gsz = table()
    ids = write_table(repo, paths, nsz, gsz)
    unchecked, n = [], 0
    for crate in CRATES:
        for f in sorted((repo / "rust" / crate / "src").rglob("*.rs")):
            s = f.read_text(encoding="utf-8")
            if ".mv" not in s:
                continue
            t = transform(s, ids, str(f.relative_to(repo)), unchecked)
            n += t.count(f"{SH}::")
            if t != s:
                f.write_text(t, encoding="utf-8", newline="\n")
    fc = repo / "rust/melee_fighter/src/tu/fighter.rs"
    s = fc.read_text(encoding="utf-8")
    z = "    core::ptr::write_bytes(fp, 0, 1);"
    assert s.count(z) == 1, "instrument: Fighter_Create's zeroing moved"
    s = s.replace(z, z + f" {SH}::reset(core::ptr::addr_of!((*fp).mv) as usize);")
    fc.write_text(s, encoding="utf-8", newline="\n")
    eng = repo / "rust/melee_engine/src/engine.rs"
    s = eng.read_text(encoding="utf-8")
    z = "FRAME_ROW = Some(Engine::compute_row());"
    assert s.count(z) == 1, "instrument: the engine's per-frame row moved"
    eng.write_text(s.replace(z, z + f" {SH}::tick();"), encoding="utf-8", newline="\n")
    print(f"instrument: {len(ids)} paths, {n} access sites wrapped, {len(unchecked)} unchecked")
    if "--unchecked" in sys.argv:
        Path(sys.argv[sys.argv.index("--unchecked") + 1]).write_text(
            "file\tline\twhy\tcode\n" + "".join(f"{a}\t{b}\t{c}\t{d}\n" for a, b, c, d in unchecked), encoding="utf-8")


if __name__ == "__main__":
    main()
