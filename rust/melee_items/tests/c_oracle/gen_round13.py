#!/usr/bin/env python3
"""Round 13 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round13.py

Round 13 (night 3, round 5) is hand-ported only (src/itkinds13.rs): functions whose callees are
all ported (it_8027C794, it_802DDBE8, it_802E37A4, itFlipper_Repel_inline) or that call nothing.
This writes tests/c_oracle/round13_bodies.h, the verbatim decomp C bodies of the HAND list,
#included by round13.c, each source file's group preceded by that file's own verbatim
`#define GET_ATTRS` (when it has one). Never edit the output by hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """checkHitLag it_ResetStageArticleTable itClimbersBlizzard_UnkMotion0_Phys
itDosei_UnkMotion4_GetAttrs itFlipper_Repel itFreeze_ClearLinkedItem itFreeze_Logic17_Destroyed
it_80299FB4_get itHeart_Logic8_Destroyed it_80293660 itKyasarin_GetCollData
itKyasarin_UnkMotion9_Coll itLeadead_UnkMotion16_Coll itLikelike_UnkMotion21_Coll
itOctarock_UnkMotion8_Coll itOldkuri_UnkMotion11_Coll itOldkuri_UnkMotion7_Coll
itWhitebea_UnkMotion11_Coll itSwapVelocity swapVelocity it_802D9B78 it_80295748
itMball_Destroyed it_802BDA40 it_80291CCC it_80291CF4 it_80285300 itTomato_Logic9_Destroyed
itZrshell_UnkMotion4_Anim""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

GA = re.compile(r'^#define GET_ATTRS\(.*?[^\\]\n', re.M | re.S)
b = ["/* @generated by gen_round13.py: verbatim copies of the decomp C bodies ported in round 13",
     " * (src/itkinds13.rs), grouped by source file. #included by round13.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        b.append("#undef GET_ATTRS")
        m = GA.search(open(path, encoding='utf-8').read())
        if m:
            b.append(m.group(0).rstrip())
        lastp = path
    b.append(body.strip())
    b.append('')
b.append("#undef GET_ATTRS")
(OR / 'round13_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')
