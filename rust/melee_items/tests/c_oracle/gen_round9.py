#!/usr/bin/env python3
"""Round 9 body extractor (run from the worktree root): python rust/melee_items/tests/c_oracle/gen_round9.py

Round 9 is hand-ported only (src/itkinds9.rs): functions whose single unported callee was
HSD_Randi / HSD_Randf (now melee_runtime::random::HsdRand) or __frsqrte (melee_core::fp::frsqrte,
via the MSL Newton steps). This writes tests/c_oracle/round9_bodies.h, the verbatim decomp C
bodies of the HAND list, #included by round9.c. Never edit the output by hand."""
import glob, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OR = ROOT / "rust/melee_items/tests/c_oracle"
src = (OR / 'gen_round8.py').read_text(encoding='utf-8')
exec(src[src.index('defre'):src.index('ported = set()')])  # defre, NOTFN, funcs()

HAND = """sqrtf_store itzako_sqrtf _tyDisplay_80318CB4_sqrt_store sqrtf_accurate_store
sqrtf_accurate_local sqrtf_accurate_sp18 my_sqrtf my_sqrtf_accurate _Toy_80309338
randi_perm randi_perm_int itKyasarin_Randi attrRand it_8026C65C itTaru_RandCheck
it_80278800_rand_vec it_802CBAA8_inline it_802CBD24_inline samus_grapple_calc_grav
it_802B9328_grav it_8026F53C it_80286340 it_8028A114 it_80289BE8_inline it_802E61C4
it_802BD32C""".split()

allf = {}
for d in ('it', 'ty', 'vi'):
    for p in sorted(glob.glob(str(ROOT / f'src/melee/{d}/**/*.c'), recursive=True)):
        for k, v in funcs(p).items():
            allf.setdefault(k, v)

b = ["/* @generated by gen_round9.py: verbatim copies of the decomp C bodies ported in round 9",
     " * (src/itkinds9.rs), grouped by source file. #included by round9.c. */"]
lastp = None
for name in sorted(HAND, key=lambda n: (allf[n][1], HAND.index(n))):
    body, path, _ = allf[name]
    if path != lastp:
        b.append(f"/* ---- {Path(path).resolve().relative_to(ROOT).as_posix()} */")
        lastp = path
    b.append(body.strip())
    b.append('')
(OR / 'round9_bodies.h').write_text('\n'.join(b) + '\n', encoding='utf-8', newline='\n')
print(f'{len(HAND)} hand bodies')
