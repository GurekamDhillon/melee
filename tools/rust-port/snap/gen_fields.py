#!/usr/bin/env python3
"""Regenerate rust/melee/src/fighter_fields.rs: the native offset of every top-level `Fighter` field,
so the snapshot debug diff can name the field a byte difference falls in.
    python tools/rust-port/snap/gen_fields.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[3] / "rust"
t = (root / "melee_types/src/gen.rs").read_text(encoding="utf8")
m = re.search(r'pub struct Fighter \{\n(.*?)\n\}', t, re.S)
names = [mm.group(1) for line in m.group(1).split("\n") if (mm := re.match(r'\s*pub (\w+): ', line))]
out = "//! Generated by tools/rust-port/snap/gen_fields.py: native field offsets of `Fighter` (debug diffs).\nuse melee_types::Fighter;\npub const FIGHTER_FIELDS: &[(&str, usize)] = &[\n"
for n in names:
    out += f'    ("{n}", core::mem::offset_of!(Fighter, {n})),\n'
out += "];\n"
(root / "melee/src/fighter_fields.rs").write_text(out)
print(len(names), "fields")
