#!/usr/bin/env bash
# Regenerate src/pure_ref.rs from the C reference, compiled the way the shipping build compiles
# game code: clang contraction ON (default -ffp-contract=on, _build/masstest/pipe_win.sh), then
# gwtool's lowering redone on the IR by melee_runtime/oracle/lower.py (f32 fmuladd -> fmadds,
# f64 fmuladd -> true fma). Sites: python tools/rust-port/fma_sites.py <tu> --func my_sqrtf.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
tmp="${TMPDIR:-/tmp}/melee_chara_ref"; mkdir -p "$tmp"
CLANG="${CLANG:-/c/Program Files/LLVM/bin/clang}"
"$CLANG" -O2 -Xclang -disable-llvm-passes -ffp-contract=on -ftrivial-auto-var-init=zero -fno-builtin \
  -S -emit-llvm -w "$here/ref_pure.c" -o "$tmp/ref_pure.ll"
python "$root/rust/melee_runtime/oracle/lower.py" "$tmp/ref_pure.ll" "$tmp/ref_pure.lo.ll"
"$CLANG" -O2 -w "$tmp/ref_pure.lo.ll" -o "$tmp/ref.exe"
{ echo "// @generated by rust/melee_chara/gen/run_ref.sh from gen/ref_pure.c (C, clang contraction on + gwtool lowering)."
  "$tmp/ref.exe"; } > "$here/../src/pure_ref.rs"
echo "wrote $here/../src/pure_ref.rs"
