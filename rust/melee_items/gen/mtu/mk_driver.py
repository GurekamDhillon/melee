#!/usr/bin/env python3
"""Writes both halves of the melee_items::tu state-oracle driver from one description, so the C driver
(gen/mtu/tu/<stem>.c) and the Rust test (tests/tu_<stem>.rs) cannot drift apart:

  python rust/melee_items/gen/mtu/mk_driver.py <stem> [...]      (worktree root)

Both halves share a "world" (gen/mtu/tu/world.h  <->  tests/mtu_harness/world.rs, written here from one
description): pools of gobjs / items / fighters / jobjs / attributes with every pointer field linked into
the pools by the generated fill functions, a few forced links the functions need, and a fresh seeded draw
of every field per case. Each function of the TU becomes one op whose arguments are drawn from the pools by
parameter type (overrides per function below); after the call the whole world, the data globals the TU
uses, the return value and the call trace of the recording stubs are hashed. Then
  python rust/melee_items/gen/mtu/run_tu.py <stem>      (C reference output)
  cargo test -p melee_items --test tu_<stem>
"""
