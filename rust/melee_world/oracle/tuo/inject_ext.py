#!/usr/bin/env python3
"""inject_ext.py <stem>: replace the text between `// @ext-begin` and `// @ext-end` in
src/tu/<stem>.rs with the `pub mod ext` generated by gen_tuo.py (rust/target/tuo/<stem>/ext.rs.txt)."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[4]
stem = sys.argv[1]
f = ROOT / f"rust/melee_world/src/tu/{stem}.rs"
t = f.read_text(encoding="utf-8")
a, b = t.index("// @ext-begin"), t.index("// @ext-end")
ext = (ROOT / f"rust/target/tuo/{stem}/ext.rs.txt").read_text(encoding="utf-8")
f.write_text(t[:a] + "// @ext-begin (generated by oracle/tuo/gen_tuo.py, injected by inject_ext.py; edit the spec, not this block)\n" + ext + t[b:], encoding="utf-8", newline="\n")
print("ext injected into", f)
