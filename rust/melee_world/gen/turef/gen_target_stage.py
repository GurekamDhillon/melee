#!/usr/bin/env python3
"""Writes the C oracle driver and the Rust test of the three target-test stage TUs
(grtcaptain, grtclink, grtdonkey): same shape, different names.

  python rust/melee_world/gen/turef/gen_target_stage.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
TESTS = HERE.parents[0] / "tests"
TESTS = HERE.parent.parent / "tests"

STAGES = {
    "grtcaptain": dict(
        tbl="grTCa_StageCallbacks", data="grTCa_StageData", create="grTCaptain_8021FD04", init="grTCaptain_OnInit",
        load="grTCaptain_OnLoad", start="grTCaptain_OnStart", demo="grTCaptain_OnDemoInit", pred4="grTCaptain_8021FCFC",
        touch="grTCaptain_OnTouchLine", shadow="grTCaptain_OnCheckShadowRender",
        ents=[("stageGObj0_OnInit", "grTCaptain_8021FE18", "grTCaptain_8021FE20", "grTCaptain_8021FE24"),
              ("stageGObj1_OnInit", "grTCaptain_8021FF08", "stageGObj1_GObjProc", "grTCaptain_8021FF30"),
              ("stageGObj2_OnInit", "grTCaptain_8021FE78", "stageGObj2_GObjProc", "grTCaptain_8021FEB4")]),
    "grtclink": dict(
        tbl="grTCLink_StageCallbacks", data="grTCLink_StageData", create="grTCLink_8021FFE8", init="grTCLink_OnInit",
        load="grTclink_UnkStage0_OnLoad", start="grTclink_UnkStage0_OnStart", demo="grTCLink_8021FF44",
        pred4="grTCLink_8021FFE0", touch="grTCLink_80220218", shadow="grTCLink_80220220",
        ents=[("grTCLink_802200D0", "grTCLink_802200FC", "grTCLink_80220104", "grTCLink_80220108"),
              ("stageGObj1_OnInit", "grTCLink_802201EC", "stageGObj1_GObjProc", "grTCLink_80220214"),
              ("stageGObj2_OnInit", "grTCLink_8022015C", "stageGObj2_GObjProc", "grTCLink_80220198")]),
    "grtdonkey": dict(
        tbl="grTDk_StageCallbacks", data="grTDk_StageData", create="grTDonkey_802202CC", init="grTDonkey_OnInit",
        load="grTdonkey_UnkStage0_OnLoad", start="grTdonkey_UnkStage0_OnStart", demo="grTDonkey_80220228",
        pred4="grTDonkey_802202C4", touch="grTDonkey_802204FC", shadow="grTDonkey_80220504",
        ents=[("stageGObj0_OnInit", "grTDonkey_802203E0", "grTDonkey_802203E8", "grTDonkey_802203EC"),
              ("stageGObj1_OnInit", "grTDonkey_802204D0", "stageGObj1_GObjProc", "grTDonkey_802204F8"),
              ("stageGObj2_OnInit", "grTDonkey_80220440", "stageGObj2_GObjProc", "grTDonkey_8022047C")]),
}
NL = "\\n"  # a backslash and an n, as written in C and Rust sources


def fns(s):
    out = [s["demo"], s["init"], s["load"], s["start"], s["pred4"], s["create"], s["touch"], s["shadow"]]
    for e in s["ents"]:
        out += list(e)
    seen = []
    for f in out:
        if f not in seen:
            seen.append(f)
    return seen


def c_driver(stem, s):
    L = []
    a = L.append
    a(f'/* State oracle for src/tu/{stem}.rs (generated by gen_target_stage.py): the game TU #included verbatim')
    a(' * (shipping contraction via run.py), every callee outside it a tracing stub, cases on a synthetic')
    a(f' * state from the shared seeded stream. tests/tu_{stem}.rs replays them. */')
    a(f'#include "melee/gr/{stem}.c"')
    a('#include "oracle.h"')
    a('#include "tu_gr_common.h"')
    a(f'#include "tu_{stem}_stubs.inc"')
    a('')
    a('static void state(void)')
    a('{')
    a(f'    printf("rs %u{NL}", ORS);')
    a(f'    printf("si %d %d{NL}", (int) stage_info.unk8C.b4, (int) stage_info.unk8C.b5);')
    a('    DUMPARENA();')
    a('    state_end();')
    a('}')
    a('')
    a('#define FN(x) fnreg(#x, (void*) x)')
    a('int main(void)')
    a('{')
    a('    int c;')
    a('    arena_init();')
    for t in ("Ground", "HSD_GObj", "HSD_JObj", "StageCallbacks", "StageData"):
        a(f'    SIZE({t});')
    a(f'    reg("cb", {s["tbl"]}, sizeof({s["tbl"]}));')
    a(f'    reg("sd", &{s["data"]}, sizeof({s["data"]}));')
    a(f'    reg("dat", {s["data"]}.data1, 16);')
    for f in fns(s):
        a(f'    FN({f});')
    a('    fnreg("grDisplay_801C5DB0", (void*) grDisplay_801C5DB0);')
    a(f'    DUMP("cb", {s["tbl"]});')
    a(f'    DUMP("sd", {s["data"]});')
    a('    state_end();')
    a('')
    a(f'    for (c = 0; c < 60; c++) {{ /* {s["create"]} and the callbacks it installs */')
    a('        CASE(c);')
    a('        rseed(100 + c);')
    a('        gr_reset();')
    a('        stage_info.unk8C.b4 = rnd() & 1;')
    a('        stage_info.unk8C.b5 = rnd() & 1;')
    a(f'        printf("r"); TRP({s["create"]}(c % 3)); printf("{NL}");')
    a('        state();')
    a('    }')
    a('    for (c = 0; c < 20; c++) { /* OnInit / OnStart / OnLoad / OnDemoInit */')
    a('        CASE(1000 + c);')
    a('        rseed(2000 + c);')
    a('        gr_reset();')
    a(f'        {s["init"]}();')
    a('        state();')
    a(f'        {s["start"]}();')
    a(f'        {s["load"]}();')
    a(f'        {s["demo"]}((int) rnd());')
    a('        state();')
    a('    }')
    a('    for (c = 0; c < 12; c++) { /* every stage callback of the three gobjs */')
    a('        HSD_GObj* g;')
    a('        CASE(2000 + c);')
    a('        rseed(3000 + c);')
    a('        gr_reset();')
    a('        g = mkgobj();')
    for (i_, p_, g_, c3) in s["ents"]:
        a(f'        {i_}(g); state();')
        a(f'        printf("r %d{NL}", (int) {p_}(g));')
        a(f'        {g_}(g); {c3}(g); state();')
    a(f'        printf("r %d{NL}", (int) {s["pred4"]}());')
    a(f'        printf("r"); TRP({s["touch"]}((int) rnd())); printf("{NL}");')
    a('        {')
    a('            Vec3 v;')
    a('            int a1;')
    a('            HSD_JObj* j;')
    a('            v.x = rf(); v.y = rf(); v.z = rf();')
    a('            a1 = (int) rnd();')
    a('            j = mkjobj();')
    a(f'            printf("r %d{NL}", (int) {s["shadow"]}(&v, a1, j));')
    a('        }')
    a('        state();')
    a('    }')
    a('    return 0;')
    a('}')
    return "\n".join(L) + "\n"


def rs_test(stem, s):
    L = []
    a = L.append
    a(f'//! tu::{stem} against the C TU compiled natively with shipping contraction (state oracle:')
    a(f'//! gen/turef/tu_{stem}_ref.c, data tests/data/tu_{stem}.txt; regenerate with')
    a(f'//! `python rust/melee_world/gen/turef/tu_shard585.py {stem}`). Generated by gen_target_stage.py.')
    a('#![allow(static_mut_refs, non_snake_case, unused)]')
    a('mod common;')
    a('use common::gr::*;')
    a('use common::*;')
    a('use melee_types::*;')
    a(f'use melee_world::tu::{stem} as t;')
    a('use melee_world::tu_ext as ext;')
    a('')
    a(f'include!("stubs/{stem}.rs");')
    a('')
    a('unsafe fn state() {')
    a(f'    out(&format!("rs {{}}{NL}", ORS));')
    a(f'    out(&format!("si {{}} {{}}{NL}", ext::stage_info.unk8C.b4(), ext::stage_info.unk8C.b5()));')
    a('    dump_arena();')
    a('    state_end();')
    a('}')
    a('')
    a('macro_rules! fnr {')
    a('    ($($p:path),* $(,)?) => { $( fnreg(stringify!($p).rsplit("::").next().unwrap(), $p as usize); )* };')
    a('}')
    a('')
    a('#[test]')
    a('fn matches_c() {')
    a('    unsafe {')
    a('        reset_all();')
    a('        gen_stubs::install();')
    a('        install_custom();')
    for t in ("Ground", "HSD_GObj", "HSD_JObj", "StageCallbacks", "StageData"):
        a(f'        size_t::<{t}>("{t}");')
    a(f'        reg("cb", t::{s["tbl"]}.as_ptr(), core::mem::size_of_val(&t::{s["tbl"]}));')
    a(f'        reg("sd", &t::{s["data"]}, core::mem::size_of::<StageData>());')
    a(f'        reg("dat", t::{s["data"]}.data1, 16);')
    a('        fnr!(' + ", ".join("t::" + f for f in fns(s)) + ');')
    a('        fnreg("grDisplay_801C5DB0", ext::grDisplay_801C5DB0 as usize);')
    a(f'        dump_t("cb", &t::{s["tbl"]});')
    a(f'        dump_t("sd", &t::{s["data"]});')
    a('        state_end();')
    a('')
    a('        for c in 0..60usize {')
    a('            case(c);')
    a('            rseed(100 + c as u32);')
    a('            gr_reset();')
    a('            ext::stage_info.unk8C.set_b4((rnd() & 1) as u8);')
    a('            ext::stage_info.unk8C.set_b5((rnd() & 1) as u8);')
    a('            out("r");')
    a(f'            trp(t::{s["create"]}((c % 3) as i32) as *const u8);')
    a(f'            out("{NL}");')
    a('            state();')
    a('        }')
    a('        for c in 0..20usize {')
    a('            case(1000 + c);')
    a('            rseed(2000 + c as u32);')
    a('            gr_reset();')
    a(f'            t::{s["init"]}();')
    a('            state();')
    a(f'            t::{s["start"]}();')
    a(f'            t::{s["load"]}();')
    a(f'            t::{s["demo"]}(rnd() as i32);')
    a('            state();')
    a('        }')
    a('        for c in 0..12usize {')
    a('            case(2000 + c);')
    a('            rseed(3000 + c as u32);')
    a('            gr_reset();')
    a('            let g = mkgobj();')
    for (i_, p_, g_, c3) in s["ents"]:
        a(f'            t::{i_}(g);')
        a('            state();')
        a(f'            out(&format!("r {{}}{NL}", t::{p_}(g)));')
        a(f'            t::{g_}(g);')
        a(f'            t::{c3}(g);')
        a('            state();')
    a(f'            out(&format!("r {{}}{NL}", t::{s["pred4"]}()));')
    a('            out("r");')
    a(f'            trp(t::{s["touch"]}(rnd() as i32) as *const u8);')
    a(f'            out("{NL}");')
    a('            let mut v = Vec3 { x: rf(), y: rf(), z: rf() };')
    a('            let a1 = rnd() as i32;')
    a('            let j = mkjobj();')
    a(f'            out(&format!("r {{}}{NL}", t::{s["shadow"]}(&mut v, a1, j)));')
    a('            state();')
    a('        }')
    a('    }')
    a(f'    check("tu_{stem}");')
    a('}')
    return "\n".join(L) + "\n"


for stem, s in STAGES.items():
    (HERE / f"tu_{stem}_ref.c").write_text(c_driver(stem, s), encoding="utf-8", newline="\n")
    (TESTS / f"tu_{stem}.rs").write_text(rs_test(stem, s), encoding="utf-8", newline="\n")
    print("wrote", stem)
