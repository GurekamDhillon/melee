//! src/melee/gm/gmopeningmode.c: the Opening, Debug-Cutscene game-mode state tables and their
//! callbacks; the title-demo setup (random four-character CPU match: which characters and
//! stage, balanced by a usage history that lives in the first bytes of the save data); the
//! getters/setters of that demo's description (`gm_8049E548`). No float math beyond one stored
//! constant (no fused sites).
//! Verified against the C by the TU state oracle (tests/tuo_gmopeningmode.rs; oracle/tuo).
#![allow(non_snake_case, non_upper_case_globals, static_mut_refs, unused_unsafe)]

