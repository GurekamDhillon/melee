#!/usr/bin/env python3
"""C references (state oracles) for the gm TUs of game_tus.txt lines 529-536.

  python rust/melee_modes/gen/turef/tu_shard529.py [--gen-only] [gm_180A ...]     (worktree root)

For each TU: stubgen.py writes the C stubs (rust/target/cref/<stem>_stubs.inc), the shared Rust
hook module src/tu_ext.rs and tests/stubs/<stem>.rs; then the driver tu_<stem>_ref.c (the game TU
#included verbatim + oracle.h + the stubs) is built like melee_fighter/gen/cref/run.py does
(shipping contraction + gwtool lowering) and run; its stdout is tests/data/tu_<stem>.txt.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "rust/melee_fighter/gen/cref"))
import run  # noqa: E402
import calls_common  # noqa: E402
import stubgen  # noqa: E402
from configs import CONFIGS  # noqa: E402

run.HERE = HERE
run.DATA = ROOT / "rust/melee_modes/tests/data"
run.FLAGS += ["-I", str(HERE)]
run.EXTRACTS.update({f"tu_{k}": [] for k in CONFIGS})


def main():
    args = sys.argv[1:]
    gen_only = "--gen-only" in args
    names = [a for a in args if not a.startswith("--")] or sorted(CONFIGS)
    run.BUILD.mkdir(parents=True, exist_ok=True)
    allext, allvalues, allglobals = {}, set(), {}
    anas = {}
    for stem in sorted(CONFIGS):
        ana = calls_common.analyze(CONFIGS[stem]["src"])
        anas[stem] = ana
        allext.update(ana["externs"])
        allvalues |= ana["values"]
        for n, v in ana["globals"].items():
            allglobals.setdefault(n, v)
    # shared Rust hooks
    ext_cfg_custom = set()
    for cfg in CONFIGS.values():
        ext_cfg_custom |= set(cfg.get("custom", ()))
    ext = {n: f for n, f in allext.items() if n != "__assert"}
    rs = ["//! GENERATED by rust/melee_modes/gen/turef/tu_shard529.py (stubgen.py); never hand-edited.",
          "//! Settable hooks for every function the shard 529-536 gm TUs call but do not define, named",
          "//! like the C function. Unset, a hook panics `TODO: <name> is not ported`; a test (or the",
          "//! integrating crate) sets `HOOK_<name>`.",
          "#![allow(non_snake_case, non_upper_case_globals, static_mut_refs, unused_imports, clippy::all)]",
          "use melee_types::*;", ""]
    rs.append(stubgen.rust_ext_for(ext, allvalues))
    rs.append("")
    for n, v in sorted(allglobals.items()):
        t = v.type
        rs.append(f"/// extern global `{n}` (owner TU is elsewhere)\npub static mut {n}: {stubgen.rust_type(t)} = unsafe {{ core::mem::zeroed() }};")
    (ROOT / "rust/melee_modes/src/tu_ext.rs").write_text("\n".join(rs) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "rust/melee_modes/tests/stubs").mkdir(parents=True, exist_ok=True)
    for stem in names:
        cfg = CONFIGS[stem]
        ana = anas[stem]
        ctext, used, rstubs = stubgen.gen(stem, cfg, ana)
        (run.BUILD / f"tu_{stem}_stubs.inc").write_text(ctext, encoding="utf-8", newline="\n")
        inst = [f"        ext::HOOK_{n} = Some(t_{n});" for n in used]
        rtext = ("// GENERATED by tu_shard529.py (stubgen.py): trace stubs mirroring tu_%s_stubs.inc.\n"
                 "#[allow(non_snake_case, unused_variables, unused_unsafe, static_mut_refs)]\n"
                 "mod gen_stubs {\n    use super::*;\n    use melee_modes::tu_ext as ext;\n" % stem
                 + "\n".join(rstubs) + "\n    pub fn install() {\n        unsafe {\n" + "\n".join(inst) + "\n        }\n    }\n}\n")
        (ROOT / f"rust/melee_modes/tests/stubs/{stem}.rs").write_text(rtext, encoding="utf-8", newline="\n")
        print(f"stubgen: {stem}: {len(used)} stubs, {len(ana['globals'])} globals, inline={sorted(ana['inline'])}")
    if gen_only:
        return
    sys.argv = [sys.argv[0], *[f"tu_{n}" for n in names]]
    run.main()


if __name__ == "__main__":
    main()
