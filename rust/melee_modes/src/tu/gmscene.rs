/// True while the scene is being held (the caller skips the scene's own frame).
pub unsafe fn mnLoadScreen_Frame() -> bool {
    melee_core::ct!("mnLoadScreen_Frame");
    if mnLoadScreen_holding == 0 {
        return false;
    }
    mnLoadScreen_frames += 1;

    let created = ext::Gfx_PipelinesCreated();
    mnLoadScreen_created = created;
    if ext::Gfx_PipelinesUrgent() != 0 || ext::Script_LaunchPending() != 0 {
        mnLoadScreen_settled = 0;
    } else {
        mnLoadScreen_settled += 1;
    }

    if !mnLoadScreen_text.is_null() {
        ext::DevText_Erase(mnLoadScreen_text);
        ext::DevText_SetCursorXY(mnLoadScreen_text, 0, 0);
        ext::DevText_Print(mnLoadScreen_text, c"NOW LOADING".as_ptr() as *mut i8);
        let dots = (mnLoadScreen_frames / LOADSCREEN_DOT_FRAMES) % 3;
        ext::DevText_Print(mnLoadScreen_text, c".".as_ptr() as *mut i8);
        if dots >= 1 {
            ext::DevText_Print(mnLoadScreen_text, c".".as_ptr() as *mut i8);
        }
        if dots >= 2 {
            ext::DevText_Print(mnLoadScreen_text, c".".as_ptr() as *mut i8);
        }
    }

    let warm = mnLoadScreen_warm != 0;
    if mnLoadScreen_frames >= (if warm { LOADSCREEN_WARM_MIN_FRAMES } else { LOADSCREEN_MIN_FRAMES })
        && ext::Gfx_SeedCorePending() == 0
        && ext::Script_LaunchPending() == 0
        && mnLoadScreen_settled >= (if warm { LOADSCREEN_WARM_SETTLE_FRAMES } else { LOADSCREEN_SETTLE_FRAMES })
    {
        mnLoadScreen_Release(c"warm".as_ptr());
        return false;
    }
    // Staging never exposes its host, even at the renderer ceiling.
    if ext::Script_LaunchPending() == 0 {
        let ceiling = LOADSCREEN_CEILING_SECONDS.wrapping_mul(ext::__OSBusClock / 4) as i64;
        if ext::OSGetTime().wrapping_sub(mnLoadScreen_started) > ceiling {
            mnLoadScreen_Release(c"ceiling".as_ptr());
            return false;
        }
    }
    true
}

