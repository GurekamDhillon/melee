def ctype(tu, name):
    return ("struct " + name) if name in tu.tagged else name


def world_c(tu):
    c = ["/* generated by gen/mtu/mk_driver.py: the shared world of the melee_items::tu C oracles */"]
    for t, a, n in POOLS:
        c.append(f"static {ctype(tu, t)} {a}[{n}];")
    c += [f"static {ctype(tu, 'SpawnItem')} SP;", "static Vec3 VA[4];", f"static {ctype(tu, 'itECB')} EC[3];",
          "static u8 U8A[16];", "static int IA[4];", "static u32 UA[4];", "static HSD_GObj* PLINK[16];",
          "static u8 BOGUS[64];", ""]
    for t, a, n in POOLS:
        c.append(f"static {ctype(tu, t)}* pick_{t}(void) {{ u32 r = rnd(); return (r % 6) == 0 ? 0 : &{a}[(r >> 8) % {n}]; }}")
    c += [
        "static HSD_GObj* pick_igo(void) { u32 r = rnd(); return (r & 3) == 0 ? 0 : &GO[(r >> 8) % 4]; }",
        "static HSD_GObj* pick_fgo(void) { u32 r = rnd(); return (r & 3) == 0 ? 0 : &GO[4 + (r >> 8) % 3]; }",
        "static HitCapsule* pick_hit(void) { u32 r = rnd(); u32 q = rnd(); return &IT[r % 4].x5D4_hitboxes[q % 4].hit; }",
        "static HurtCapsule* pick_hurt(void) { u32 r = rnd(); u32 q = rnd(); return &IT[r % 4].xACC_itemHurtbox[q % 2]; }",
        "/* recording callbacks that struct fields and arguments name */",
        "static void cbev1(HSD_GObj* g) { T(7001); T(PI(g)); }",
        "static void cbev2(HSD_GObj* g) { T(7002); T(PI(g)); }",
        "static int cbp1(HSD_GObj* g) { T(7003); T(PI(g)); return (int) (fv() & 1); }",
        "static int cbp2(HSD_GObj* g) { T(7004); T(PI(g)); return (int) (fv() & 1); }",
        "static void cbev3(HSD_GObj* g, HSD_GObj* h) { T(7005); T(PI(g)); T(PI(h)); }",
        "static void* pick_fn(int kind)",
        "{",
        "    u32 r = rnd();",
        "    if ((r & 3) == 0) return 0;",
        "    switch (kind) {",
        "    case 1: return (r & 4) ? (void*) cbev1 : (void*) cbev2;",
        "    case 2: return (r & 4) ? (void*) cbp1 : (void*) cbp2;",
        "    case 3: return (void*) cbev3;",
        "    }",
        "    return 0;",
        "}",
        "/* non-null callback for an argument */",
        "static void* pick_cb(int kind) { void* f = pick_fn(kind); return f ? f : (kind == 2 ? (void*) cbp1 : kind == 3 ? (void*) cbev3 : (void*) cbev1); }",
        "static void freg_world(void) { freg((const void*) cbev1); freg((const void*) cbev2); freg((const void*) cbp1); freg((const void*) cbp2); freg((const void*) cbev3); }",
        "static void preg_world(void)",
        "{",
    ]
    for t, a, n in POOLS:
        c.append(f"    preg({a}, sizeof {a});")
    c += ["    preg(&SP, sizeof SP); preg(VA, sizeof VA); preg(EC, sizeof EC); preg(U8A, sizeof U8A); preg(IA, sizeof IA);",
          "    preg(UA, sizeof UA); preg(PLINK, sizeof PLINK); preg(BOGUS, sizeof BOGUS);", "}", ""]
    return "\n".join(c)


