/// `struct gm_random_history` (gmopeningmode.c) is laid over the start of the save data
/// (`gmMainLib_804D3EE0`): `u8 pad0[2]; u8 character_usage[0x1A]; u8 stage_usage[0x1D]`.
/// The C indexes past the declared bounds (flat memory), so these are raw byte offsets.
#[inline(always)]
unsafe fn history(off: usize) -> *mut u8 {
    (ext::gmMainLib_804D3EE0 as *mut u8).add(off)
}
/// `gm_GetCharacterUsage` / `gm_GetCharacterUsageDirect`: `character_usage[index]`.
#[inline(always)]
unsafe fn gm_GetCharacterUsage(index: i32) -> i32 {
    *history(2 + index as usize) as i32
}
/// `gm_GetStageUsage`: `stage_usage[index]`.
#[inline(always)]
unsafe fn gm_GetStageUsage(index: i32) -> i32 {
    *history(2 + 0x1A + index as usize) as i32
}

