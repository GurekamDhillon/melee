pub unsafe extern "C" fn gm_801A0FEC(slot: i32, flag: u8) {
    melee_core::ct!("gm_801A0FEC");
    // TARGET_PC: the Atlas retail mask hides the panel (flag 0 is retail's own "no panel" path).
    let mut flag = flag;
    if ext::Ui_RetailHidden(AT_RE_PAUSE_PANEL) != 0 {
        flag = 0;
    }
    // port: an Envoy run draws its own pause (envoy_ui): no retail panel
    if crate::tu::envoy::ARMED != 0 && crate::tu::envoy::pause_ui_on() {
        flag = 0;
    }
    lbl_80479B10.slot = slot;
    ext::HSD_JObjReqAnimAll(lbl_80479B10.background, (slot.wrapping_add(1)) as f32);
    // flag is set by match rules
    if flag != 0 {
        ext::HSD_JObjClearFlagsAll(lbl_80479B10.background, JOBJ_HIDDEN as u32);
        ext::HSD_JObjSetFlagsAll(lbl_80479B10.lras, JOBJ_HIDDEN as u32);
        ext::HSD_JObjSetFlagsAll(lbl_80479B10.z, JOBJ_HIDDEN as u32);
        ext::HSD_JObjSetFlagsAll(lbl_80479B10.analog_stick, JOBJ_HIDDEN as u32);
        ext::HSD_JObjSetFlagsAll(lbl_80479B10.analog_stick_outline, JOBJ_HIDDEN as u32);
        if flag & 1 != 0 {
            ext::HSD_JObjClearFlagsAll(lbl_80479B10.lras, JOBJ_HIDDEN as u32);
        }
        if flag & 2 != 0 {
            ext::HSD_JObjClearFlagsAll(lbl_80479B10.z, JOBJ_HIDDEN as u32);
        }
        if flag & 4 != 0 {
            ext::HSD_JObjClearFlagsAll(lbl_80479B10.analog_stick, JOBJ_HIDDEN as u32);
            ext::HSD_JObjClearFlagsAll(lbl_80479B10.analog_stick_outline, JOBJ_HIDDEN as u32);
        }
    } else {
        ext::HSD_JObjSetFlagsAll(lbl_80479B10.background, JOBJ_HIDDEN as u32);
    }
    ext::HSD_JObjAnimAll(lbl_80479B10.background);
}

